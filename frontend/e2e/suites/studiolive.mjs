// The studio like a desktop DAW: shared playback for everyone in a project (and opting out), track I/O (input
// device and channel, monitoring, output incl. sends only), per-track and exclusive arm, a member recording two
// armed tracks at once as two takes, input monitoring, the Ableton-style mixer strip, movable windows, clearing the
// loop, and solid menus in see-through themes.
import { chromium } from 'playwright'
import { WEB, S, reg, call, callS, ok, finish } from '../lib.mjs'

const a = await reg('alice'); const b = await reg('bob')
const g = await call(a.token, 'POST', '/guilds', { name: `Live ${S}` })
const inv = await call(a.token, 'POST', `/guilds/${g.id}/invites`, {}); await call(b.token, 'POST', `/invites/${inv.code}`)
const studio = (await callS(a.token, 'POST', `/guilds/${g.id}/channels`, { name: 'studio', kind: 'studio' })).body
const P = (await callS(a.token, 'POST', `/channels/${studio.id}/studio/projects`, { name: 'Live Song' })).body
const room = P.channel_id
await callS(a.token, 'PUT', `/channels/${room}/studio/role/${b.user.id}`, { role: 'artist' })
const full = () => call(a.token, 'GET', `/studio/projects/${P.id}`)
const ops = (list, tok = a.token) => callS(tok, 'POST', `/studio/projects/${P.id}/ops`, { ops: list })
const L1 = crypto.randomUUID(), L2 = crypto.randomUUID(), BUS = crypto.randomUUID(), M = crypto.randomUUID()

console.log('-- track I/O (API)')
let r = await ops([{ op: 'lane.put', lane: { id: BUS, name: 'Verb', kind: 'bus', position: 0 } }, { op: 'lane.put', lane: { id: L1, name: 'Guitar', position: 1, user_id: a.user.id } }, { op: 'lane.put', lane: { id: L2, name: 'Vocal', position: 2 } }, { op: 'lane.put', lane: { id: M, name: 'Keys', kind: 'midi', position: 3 } }])
ok('tracks, a bus', r.status === 200)
let f = await full()
ok('a track made someone\'s is armed for them; an empty one is not', f.lanes.find((l) => l.id === L1).armed === true && f.lanes.find((l) => l.id === L2).armed === false && f.lanes.find((l) => l.id === L1).monitor === 'off')
r = await ops([{ op: 'lane.put', lane: { id: L2, input: { device: 'Interface', channel: '2' }, monitor: 'auto', sends_only: true, sends: { [BUS]: 0.5 } } }])
f = await full()
const v = f.lanes.find((l) => l.id === L2)
ok('input device and channel, monitoring and sends only are kept', r.status === 200 && v.input.device === 'Interface' && v.input.channel === '2' && v.monitor === 'auto' && v.sends_only === true, JSON.stringify(v))
ok('a bad input channel is refused', (await ops([{ op: 'lane.put', lane: { id: L2, input: { channel: '3' } } }])).status === 400)
ok('a bad monitor mode is refused', (await ops([{ op: 'lane.put', lane: { id: L2, monitor: 'loud' } }])).status === 400)
await ops([{ op: 'lane.put', lane: { id: L2, input: null, monitor: 'off', sends_only: false } }])

console.log('-- clearing the loop (API)')
await ops([{ op: 'project', loop_start_ms: 1000, loop_end_ms: 3000, loop_on: true, punch_on: true }])
r = await ops([{ op: 'project', clear_loop: true }])
f = await full()
ok('clear_loop drops the range, the loop and the punch', r.status === 200 && f.project.loop_start_ms === null && f.project.loop_end_ms === null && !f.project.loop_on && !f.project.punch_on, JSON.stringify(f.project))

console.log('-- shared playback (API)')
r = await callS(b.token, 'POST', `/studio/projects/${P.id}/transport`, { playing: true, position_ms: 1500 })
ok('a band member plays for everyone, a moment ahead', r.status === 200 && r.body.play_from_ms === 1500 && Date.parse(r.body.play_at) > Date.now() - 1000, JSON.stringify(r.body))
ok('the project knows it is playing', !!(await full()).project.play_at)
r = await callS(b.token, 'POST', `/studio/projects/${P.id}/transport`, { playing: false, position_ms: 4000 })
ok('and stops it where it is', r.status === 200 && r.body.play_at === null && (await full()).project.play_from_ms === 4000)
const outsider = await reg('carol'); await call(outsider.token, 'POST', `/invites/${inv.code}`)
ok('someone outside the band cannot', (await callS(outsider.token, 'POST', `/studio/projects/${P.id}/transport`, { playing: true })).status === 403)
const clock = await call(a.token, 'GET', '/studio/clock')
ok('the server clock is there to line clients up', Math.abs(clock.now - Date.now()) < 5000)

console.log('-- UI')
const browser = await chromium.launch({ args: ['--use-fake-ui-for-media-stream', '--use-fake-device-for-media-stream', '--autoplay-policy=no-user-gesture-required'] }); const errors = []
const mk = async (tok, w = 1500) => { const ctx = await browser.newContext({ viewport: { width: w, height: 950 }, permissions: ['microphone'] }); const p = await ctx.newPage(); p.on('pageerror', (e) => errors.push(e.message)); await p.goto(`${WEB}/login`); await p.evaluate((t) => localStorage.setItem('parley.token', t), tok); await p.goto(`${WEB}/channels/${g.id}/${room}`); await p.waitForSelector('[data-daw-play]', { timeout: 15000 }); return p }
const pa = await mk(a.token); const pb = await mk(b.token)
// Shared playback in the browser
await pa.click('[data-daw-play]')
await pb.waitForFunction(() => window.__parleyDaw?.playing === 'shared', null, { timeout: 8000 }).catch(() => {})
ok('pressing play plays for everyone in the project', await pa.evaluate(() => window.__parleyDaw?.playing) === 'shared' && await pb.evaluate(() => window.__parleyDaw?.playing) === 'shared')
await pb.click('[data-daw-play]')
await pa.waitForFunction(() => !window.__parleyDaw?.playing, null, { timeout: 8000 }).catch(() => {})
ok('and anyone in the band stops it for everyone', !(await pa.evaluate(() => window.__parleyDaw?.playing)))
await pb.click('[data-daw-follow]')
ok('following can be turned off', await pb.locator('[data-daw-follow][aria-pressed="false"]').count() === 1)
await pa.click('[data-daw-play]')
await pa.waitForFunction(() => window.__parleyDaw?.playing === 'shared', null, { timeout: 8000 }).catch(() => {})
await pb.waitForTimeout(1200)
ok('then someone else\'s play stays theirs', !(await pb.evaluate(() => window.__parleyDaw?.playing)))
await pb.click('[data-daw-play]')
await pb.waitForFunction(() => window.__parleyDaw?.playing === 'local', null, { timeout: 8000 }).catch(() => {})
ok('and play is your own', await pb.evaluate(() => window.__parleyDaw?.playing) === 'local')
await pb.click('[data-daw-play]'); await pb.click('[data-daw-follow]')
await pa.click('[data-daw-play]')
// The loop: set by API, cleared from the transport, back with undo
await ops([{ op: 'project', loop_start_ms: 1000, loop_end_ms: 3000, loop_on: true }])
await pa.waitForSelector('[data-daw-loop-clear]', { timeout: 8000 }).catch(() => {})
await pa.click('[data-daw-loop-clear]')
await pa.waitForTimeout(600)
ok('the loop clears from the transport', (await full()).project.loop_end_ms === null && await pa.locator('[data-daw-loop-clear]').count() === 0)
await pa.click('[data-daw-undo]'); await pa.waitForTimeout(600)
ok('and undo brings it back', (await full()).project.loop_end_ms === 3000)
// Arm: exclusive, Ctrl for several
await pa.click(`[data-daw-arm="${L2}"]`)
await pa.waitForTimeout(500)
f = await full()
ok('arming an empty track arms it', f.lanes.find((l) => l.id === L2).armed)
await pa.click(`[data-daw-rec-here="${L2}"]`)
await pa.waitForTimeout(600)
f = await full()
ok('making a track yours arms it and disarms your others (exclusive arm)', f.lanes.find((l) => l.id === L2).user_id === a.user.id && f.lanes.find((l) => l.id === L2).armed && !f.lanes.find((l) => l.id === L1).armed)
await pa.click(`[data-daw-arm="${L1}"]`, { modifiers: ['Control'] })
await pa.waitForTimeout(600)
f = await full()
ok('Ctrl-click arms another as well', f.lanes.find((l) => l.id === L1).armed && f.lanes.find((l) => l.id === L2).armed)
// The mixer strip: I/O, monitoring, output, activator, delay
await pa.click('[data-daw-view-mixer]'); await pa.waitForSelector(`[data-daw-strip="${L1}"]`)
ok('strips have an I/O section, send knobs and a numbered activator', await pa.locator(`[data-daw-io="${L1}"] [data-daw-input-user="${L1}"]`).count() === 1 && await pa.locator(`[data-daw-strip="${L1}"] [data-daw-send="${BUS}"]`).count() === 1 && await pa.locator(`[data-daw-activator="${L1}"]`).textContent() === '2')
await pa.selectOption(`[data-daw-input-channel="${L1}"]`, '1')
await pa.selectOption(`[data-daw-input-channel="${L2}"]`, '2')
await pa.selectOption(`[data-daw-output="${L2}"]`, 'sends')
await pa.click(`[data-daw-monitor="${L1}"] [data-daw-monitor-pick="in"]`)
await pa.fill(`[data-daw-track-delay="${L1}"]`, '12')
await pa.click(`[data-daw-activator="${L2}"]`)
await pa.waitForTimeout(900)
f = await full()
const g1 = f.lanes.find((l) => l.id === L1), g2 = f.lanes.find((l) => l.id === L2)
ok('picking channels, the output, monitoring and the delay is shared', g1.input?.channel === '1' && g2.input?.channel === '2' && g2.sends_only && g1.monitor === 'in' && g1.nudge_ms === 12, JSON.stringify([g1.input, g2.input, g2.sends_only, g1.monitor, g1.nudge_ms]))
ok('the activator turns a track off', g2.mute === true)
await pa.click(`[data-daw-activator="${L2}"]`)
await pa.waitForFunction((id) => (window.__parleyMonitor ?? []).includes(id), L1, { timeout: 8000 }).catch(() => {})
ok('monitoring In plays my live input through the track, here', await pa.evaluate((id) => (window.__parleyMonitor ?? []).includes(id), L1))
await pa.click(`[data-daw-monitor="${L1}"] [data-daw-monitor-pick="off"]`)
await pa.waitForFunction((id) => !(window.__parleyMonitor ?? []).includes(id), L1, { timeout: 8000 }).catch(() => {})
ok('and Off stops it', await pa.evaluate((id) => !(window.__parleyMonitor ?? []).includes(id), L1))
// Two armed tracks, two channels of one input: two takes, each on its track
await ops([{ op: 'project', clear_loop: true }])
await pa.click('[data-daw-view-arrange]')
await pa.click('[data-project-join]'); await pa.waitForSelector('[data-voice-leave]')
await pa.click('[data-daw-rtz]'); await pa.click('[data-daw-record]')
await pa.waitForFunction(() => (window.__parleyStudio?.tracks ?? []).length === 2, null, { timeout: 12000 }).catch(() => {})
ok('a member with two armed tracks records both at once', await pa.evaluate(() => (window.__parleyStudio?.tracks ?? []).length) === 2, JSON.stringify(await pa.evaluate(() => [window.__parleyStudio, [...document.querySelectorAll('[data-toast]')].map((x) => x.textContent)])))
await pa.waitForTimeout(2500)
await pa.click('[data-daw-record]')
for (let i = 0; i < 40; i++) { f = await full(); if (f.clips.some((c) => c.lane_id === L1) && f.clips.some((c) => c.lane_id === L2)) break; await pa.waitForTimeout(500) }
ok('each take lands on its own track', f.clips.some((c) => c.lane_id === L1) && f.clips.some((c) => c.lane_id === L2) && new Set(f.clips.map((c) => c.audio_id)).size === 2, JSON.stringify(f.clips.map((c) => c.lane_id)))
// Windows: dragged, and opened again where they were left
await pa.click('[data-daw-takes-open]')
const h = await pa.locator('[data-float-window="panel-takes"] [data-float-window-handle]').boundingBox()
await pa.mouse.move(h.x + 40, h.y + h.height / 2); await pa.mouse.down(); await pa.mouse.move(h.x - 260, h.y + 120, { steps: 6 }); await pa.mouse.up()
await pa.waitForTimeout(300)
const moved = await pa.locator('[data-float-window="panel-takes"]').boundingBox()
await pa.click('[data-float-window="panel-takes"] [data-float-window-close]')
await pa.click('[data-daw-takes-open]')
await pa.waitForTimeout(300)
const again = await pa.locator('[data-float-window="panel-takes"]').boundingBox()
ok('a panel moves by its title bar and reopens where it was', Math.abs(moved.x - (h.x - 300 + (h.x - h.x))) < 400 && moved.y > h.y + 60 && Math.abs(again.x - moved.x) < 2 && Math.abs(again.y - moved.y) < 2, JSON.stringify({ h, moved, again }))
// See-through theme: menus and windows are solid
await pa.evaluate(() => { document.documentElement.setAttribute('data-palette', 'aurora'); document.documentElement.setAttribute('data-see-through', '') })
await pa.click('[data-daw-project]')
const alpha = (sel) => pa.evaluate((s) => { const c = getComputedStyle(document.querySelector(s)).backgroundColor; const m = c.match(/rgba?\(([^)]+)\)/); const parts = m ? m[1].split(/[ ,/]+/).filter(Boolean) : []; return parts.length > 3 ? Number(parts[3]) : 1 }, sel)
ok('in a see-through theme the project menu is solid', await alpha('[data-daw-projects]') === 1)
ok('and so are windows', await alpha('[data-float-window="panel-takes"]') === 1)
ok('no page errors', errors.length === 0, errors.join(' | '))
await browser.close()
await finish()
