// Zoom and position for profile pictures, profile banners, server icons and server banners. The picture is uploaded as
// is; its framing (zoom and focus point) is recorded on the URL as #crop= and applied wherever it is drawn. Animated
// GIFs can be framed too, re-framing never makes the server delete or re-upload the picture, and Cancel or Escape
// uploads nothing.
import { chromium } from 'playwright'
import { WEB, B, S, reg, call, callS, ok, finish, gifFile, openProfileEditor, adminToken } from '../lib.mjs'

const a = await reg('alice')
const g = await call(a.token, 'POST', '/guilds', { name: `Crop ${S}` })
const browser = await chromium.launch()
const p = await (await browser.newContext({ viewport: { width: 1280, height: 900 } })).newPage()
const errors = []; p.on('pageerror', (e) => errors.push(e.message))
await p.goto(`${WEB}/login`); await p.evaluate((t) => localStorage.setItem('parley.token', t), a.token)
await p.goto(`${WEB}/channels/${g.id}`); await p.waitForSelector('[data-panel-self]')

// A test picture: left half red, right half blue.
const picture = async (w, h) => Buffer.from(await p.evaluate(([w, h]) => {
  const c = document.createElement('canvas'); c.width = w; c.height = h; const x = c.getContext('2d')
  x.fillStyle = '#ff0000'; x.fillRect(0, 0, w / 2, h); x.fillStyle = '#0000ff'; x.fillRect(w / 2, 0, w / 2, h)
  return c.toDataURL('image/png').split(',')[1]
}, [w, h]), 'base64')
const wide = { name: 'wide.png', mimeType: 'image/png', buffer: await picture(1600, 800) }
const crop = (url) => { const m = /#crop=([\d.]+),([\d.]+),([\d.]+)$/.exec(url ?? ''); return m ? { z: +m[1], x: +m[2], y: +m[3] } : null }
const size = (url) => p.evaluate(async (u) => { const i = new Image(); i.src = u; await i.decode(); return { w: i.naturalWidth, h: i.naturalHeight } }, url.split('#')[0])
const box = () => p.locator('[data-crop-area]').boundingBox()
const zoom = async () => Number(await p.locator('[data-crop-zoom]').inputValue())

console.log('-- profile picture')
await openProfileEditor(p)
await p.setInputFiles('[data-inline-avatar-input]', wide)
await p.waitForSelector('[data-crop-dialog="avatar"]')
ok('choosing a picture opens the cropper first', true)
ok('  with a circle guide for profile pictures', (await p.locator('[data-crop-round]').count()) === 1)
let b = await box()
ok('  in a square frame', Math.abs(b.width - b.height) < 2, JSON.stringify(b))
await p.waitForTimeout(500); await p.screenshot({ path: 'crop-avatar.png' })
await p.click('[data-crop-zoom-in]'); await p.click('[data-crop-zoom-in]')
ok('the + button zooms in', (await zoom()) > 1.3)
await p.click('[data-crop-zoom-out]')
ok('the - button zooms out', (await zoom()) < 1.3)
await p.click('[data-crop-reset]')
ok('Reset goes back to the whole picture', (await zoom()) === 1)
await p.click('[data-crop-zoom-in]'); await p.click('[data-crop-zoom-in]')
// Drag the picture right as far as it goes: the left (red) side fills the frame.
b = await box()
await p.mouse.move(b.x + b.width / 2, b.y + b.height / 2); await p.mouse.down(); await p.mouse.move(b.x + b.width * 3, b.y + b.height / 2, { steps: 6 }); await p.mouse.up()
await p.click('[data-crop-apply]')
await p.waitForSelector('[data-crop-dialog]', { state: 'detached' })
await p.waitForFunction(() => !!document.querySelector('[data-inline-avatar-remove]'), null, { timeout: 8000 }).catch(() => {})
await p.click('button:has-text("Save Changes")'); await p.waitForTimeout(800)
let me = await call(a.token, 'GET', '/users/@me')
let c = crop(me.avatar_url)
ok('the zoom and position are saved with the picture', c && Math.abs(c.z - 1.4) < 0.05 && c.x === 0 && c.y === 50, me.avatar_url)
const sz = await size(me.avatar_url)
ok('  and the picture itself is uploaded whole, not cropped', sz.w === 1600 && sz.h === 800, JSON.stringify(sz))
await p.keyboard.press('Escape'); await p.waitForTimeout(300); await p.keyboard.press('Escape'); await p.waitForTimeout(300)
const panel = p.locator('[data-panel-self] [data-cropped]').first()
ok('the app draws it framed (zoomed, focus on the left)', (await panel.count()) === 1 && /scale\(1\.4\)/.test(await panel.locator('img').getAttribute('style')) && /0% 50%/.test(await panel.locator('img').getAttribute('style')))

console.log('-- re-framing')
const base = me.avatar_url.split('#')[0]
let r = await callS(a.token, 'PATCH', '/users/@me', { avatar_url: `${base}#crop=2,80,20` })
ok('changing only the framing keeps the same picture', r.status === 200 && (await fetch(`${B.replace(/\/api$/, '')}${base}`)).status === 200)
const admin = await adminToken()
await callS(admin.token, 'POST', '/admin/maintenance/sweep-images?min_age_secs=0')
ok('the unused-image cleanup leaves a framed picture alone', (await fetch(`${B.replace(/\/api$/, '')}${base}`)).status === 200)
ok("  and doesn't fill the avatar history with copies of it", !(r.body.avatar_history ?? []).some((h) => h.split('#')[0] === base), JSON.stringify(r.body.avatar_history))

console.log('-- cancel and Escape')
await openProfileEditor(p)
const before = (await call(a.token, 'GET', '/users/@me')).avatar_url
await p.setInputFiles('[data-inline-avatar-input]', wide); await p.waitForSelector('[data-crop-dialog]')
await p.click('[data-crop-cancel]'); await p.waitForTimeout(500)
ok('Cancel uploads nothing', (await p.locator('[data-crop-dialog]').count()) === 0 && (await call(a.token, 'GET', '/users/@me')).avatar_url === before)
await p.setInputFiles('[data-inline-avatar-input]', wide); await p.waitForSelector('[data-crop-dialog]')
await p.keyboard.press('Escape'); await p.waitForTimeout(400)
ok('Escape closes the cropper but not the profile editor', (await p.locator('[data-crop-dialog]').count()) === 0 && (await p.locator('[data-profile-editor]').count()) === 1)

console.log('-- keyboard')
await p.setInputFiles('[data-inline-avatar-input]', wide); await p.waitForSelector('[data-crop-dialog]')
await p.focus('[data-crop-area]')
const pos0 = await p.locator('[data-crop-img]').evaluate((e) => e.style.objectPosition)
await p.keyboard.press('Shift+ArrowLeft')
ok('arrow keys nudge the picture', (await p.locator('[data-crop-img]').evaluate((e) => e.style.objectPosition)) !== pos0)
await p.keyboard.press('+')
ok('+ zooms in from the keyboard', (await zoom()) > 1)
await p.click('[data-crop-cancel]')

console.log('-- profile banner')
await p.setInputFiles('[data-inline-banner-input]', wide)
await p.waitForSelector('[data-crop-dialog="profileBanner"]')
b = await box()
ok('banners frame at 5:2 without a circle', Math.abs(b.width / b.height - 2.5) < 0.05 && (await p.locator('[data-crop-round]').count()) === 0, JSON.stringify(b))
await p.click('[data-crop-zoom-in]')
await p.click('[data-crop-apply]'); await p.waitForSelector('[data-crop-dialog]', { state: 'detached' }); await p.waitForTimeout(1200)
await p.click('button:has-text("Save Changes")'); await p.waitForTimeout(800)
me = await call(a.token, 'GET', '/users/@me')
ok('  and keep their framing', crop(me.banner_url)?.z === 1.2, me.banner_url)
ok('the profile card draws the framed banner', (await p.locator('[data-profile-card] [data-crop-layer]').count()) >= 1)

console.log('-- animated pictures')
await p.setInputFiles('[data-inline-avatar-input]', gifFile)
await p.waitForSelector('[data-crop-dialog]', { timeout: 5000 }).catch(() => {})
ok('animated GIFs can be framed too (nothing is re-encoded, so they keep animating)', (await p.locator('[data-crop-dialog]').count()) === 1)
await p.click('[data-crop-cancel]')
await p.keyboard.press('Escape'); await p.waitForTimeout(300); await p.keyboard.press('Escape'); await p.waitForTimeout(300)

console.log('-- server icon and banner')
await p.goto(`${WEB}/channels/${g.id}`); await p.waitForSelector('[data-panel-self]')
await p.locator(`button:has-text("Crop ${S}")`).first().click(); await p.click('text=Server Settings'); await p.waitForSelector('[data-image-picker]')
await p.locator('[data-image-picker] ~ input[type=file]').first().setInputFiles(wide)
await p.waitForSelector('[data-crop-dialog="icon"]')
b = await box()
ok('the server icon frames as a square, no circle', Math.abs(b.width - b.height) < 2 && (await p.locator('[data-crop-round]').count()) === 0)
await p.click('[data-crop-zoom-in]'); await p.click('[data-crop-apply]'); await p.waitForSelector('[data-crop-dialog]', { state: 'detached' }); await p.waitForTimeout(1000)
await p.locator('[data-image-picker] ~ input[type=file]').nth(1).setInputFiles(wide)
await p.waitForSelector('[data-crop-dialog="serverBanner"]')
b = await box()
ok('the server banner frames at 16:9', Math.abs(b.width / b.height - 16 / 9) < 0.05, JSON.stringify(b))
await p.waitForTimeout(500); await p.screenshot({ path: 'crop-server-banner.png' })
await p.click('[data-crop-zoom-in]'); await p.click('[data-crop-apply]'); await p.waitForSelector('[data-crop-dialog]', { state: 'detached' }); await p.waitForTimeout(500)
await p.click('[data-image-adjust] >> nth=0')
await p.waitForSelector('[data-crop-dialog="icon"]')
ok('Adjust re-opens the framing of a picture already set, where it was left', Math.abs((await zoom()) - 1.2) < 0.01)
await p.click('[data-crop-zoom-in]'); await p.click('[data-crop-apply]'); await p.waitForSelector('[data-crop-dialog]', { state: 'detached' })
ok('Server Settings stayed open throughout', (await p.locator('[data-settings-tab]').count()) > 0)
await p.click('button:has-text("Save Changes")').catch(() => {}); await p.waitForTimeout(1000)
const gs = await call(a.token, 'GET', `/guilds/${g.id}`)
ok('the server keeps both framings', crop(gs.icon_url)?.z === 1.4 && crop(gs.banner_url)?.z === 1.2, `${gs.icon_url} ${gs.banner_url}`)
await p.keyboard.press('Escape'); await p.waitForTimeout(500)
ok('the server bar and channel list draw them framed', (await p.locator('[data-cropped]').count()) >= 1 && (await p.locator('[data-guild-banner] [data-crop-layer]').count()) === 1)
await p.screenshot({ path: 'crop-applied.png' })

console.log('-- phone')
const ph = await (await browser.newContext({ viewport: { width: 390, height: 844 }, hasTouch: true, isMobile: true })).newPage()
await ph.goto(`${WEB}/login`); await ph.evaluate((t) => localStorage.setItem('parley.token', t), a.token)
await ph.goto(`${WEB}/channels/@me`); await ph.waitForTimeout(1500)
await openProfileEditor(ph)
await ph.setInputFiles('[data-inline-banner-input]', wide)
await ph.waitForSelector('[data-crop-dialog]')
const pb = await ph.locator('[data-crop-area]').boundingBox()
ok('on a phone the frame fits the screen', pb.x >= 0 && pb.x + pb.width <= 390, JSON.stringify(pb))
await ph.waitForTimeout(500); await ph.screenshot({ path: 'crop-phone.png' })
ok('no page errors', errors.length === 0, errors.join(' | '))
await browser.close(); await finish()
