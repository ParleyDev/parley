// Account deletion: soft delete, then anonymize (docs/account-deletion.md).
// Request (re-auth, blockers, sessions and push tokens die, profile hidden), sign-in during the grace period offers
// Restore, finalize scrubs personal data but keeps content as "Deleted User", running it again changes nothing, the
// name and email are free again, an account deleted while banned can't sign straight back up, admin delete and
// purge, how deleted users render, and the web /delete-account page.
