// Menus and keys: Ctrl+/ shortcuts help, Ctrl+Shift+E and type-anywhere to reach the message box, Ctrl+U underlines
// without toggling the member list, the image menu (copy/save/copy link/open), the extra user menu actions
// (Mention, Call, Add Note, Change Nickname, Roles, Invite to Server), the category menu (Mark As Read, notifications,
// Collapse/Expand All) and the desktop app's back/forward buttons.
import { chromium } from 'playwright'
import { WEB, S, reg, call, ok, finish } from '../lib.mjs'
const a = await reg('alice'), b = await reg('bob')
const g = await call(a.token, 'POST', '/guilds', { name: `Menus ${S}` })
const g2 = await call(a.token, 'POST', '/guilds', { name: `Second ${S}` })
const inv = await call(a.token, 'POST', `/guilds/${g.id}/invites`, {}); await call(b.token, 'POST', `/invites/${inv.code}`)
const general = g.channels.find((c) => c.kind === 'text')
const cat = await call(a.token, 'POST', `/guilds/${g.id}/channels`, { name: 'Lounge', kind: 'category' })
const inCat = await call(a.token, 'POST', `/guilds/${g.id}/channels`, { name: 'chill', kind: 'text', parent_id: cat.id })
const role = await call(a.token, 'POST', `/guilds/${g.id}/roles`, { name: 'Helper' })
const browser = await chromium.launch(); const errors = []
const ctx = await browser.newContext({ viewport: { width: 1400, height: 900 }, permissions: ['clipboard-read', 'clipboard-write'] })
const p = await ctx.newPage(); p.on('pageerror', (e) => errors.push(e.message))
await p.goto(`${WEB}/login`); await p.evaluate((t) => { localStorage.setItem('parley.token', t); localStorage.setItem('parley.keybinds', JSON.stringify({ focusComposer: 'Ctrl+/' })) }, a.token)
await p.goto(`${WEB}/channels/${g.id}/${general.id}`); await p.waitForSelector('[data-composer-box] textarea'); await p.waitForTimeout(800)
const box = '[data-composer-box] textarea'
const blur = () => p.evaluate(() => document.activeElement?.blur())

console.log('-- keys')
await blur(); await p.keyboard.press('Control+/'); await p.waitForTimeout(200)
ok('Ctrl+/ opens the shortcuts, even with an old saved keybind map', await p.locator('[data-shortcuts]').count() === 1)
ok('it lists keybinds and fixed keys', /Show keyboard shortcuts/.test(await p.locator('[data-shortcuts]').innerText()) && /Edit your last message/.test(await p.locator('[data-shortcuts]').innerText()))
await p.keyboard.press('Control+/'); await p.waitForTimeout(200)
ok('Ctrl+/ again closes them', await p.locator('[data-shortcuts]').count() === 0)
await blur(); await p.keyboard.press('Control+Shift+E'); await p.waitForTimeout(100)
ok('Ctrl+Shift+E focuses the message box', await p.evaluate((sel) => document.activeElement === document.querySelector(sel), box))
await blur(); await p.keyboard.type('hi'); await p.waitForTimeout(100)
ok('typing with nothing focused goes into the message box', await p.inputValue(box) === 'hi')
const membersBefore = await p.evaluate(() => !!document.querySelector('[data-member-list]'))
await p.keyboard.press('Control+a'); await p.keyboard.press('Control+u'); await p.waitForTimeout(150)
ok('Ctrl+U in the box underlines without toggling the member list', await p.inputValue(box) === '__hi__' && await p.evaluate(() => !!document.querySelector('[data-member-list]')) === membersBefore)
await p.fill(box, '')

console.log('-- image menu')
// A real-sized picture (the shared fixture is 1x1, too small to right-click).
const png = Buffer.from(await p.evaluate(() => { const c = document.createElement('canvas'); c.width = 64; c.height = 48; const x = c.getContext('2d'); x.fillStyle = '#6d5dfc'; x.fillRect(0, 0, 64, 48); return c.toDataURL('image/png').split(',')[1] }), 'base64')
await p.setInputFiles('[data-file-input="files"]', { name: 'swatch.png', mimeType: 'image/png', buffer: png })
await p.waitForFunction(() => /B$/.test(document.querySelector('[data-pending]')?.textContent ?? ''), null, { timeout: 10000 })
await p.focus(box); await p.keyboard.press('Enter'); await p.waitForSelector('[data-attachment-img]')
await p.click('[data-attachment-img]', { button: 'right' }); await p.waitForSelector('[data-context-menu]')
const imgItems = await p.locator('[data-context-menu] [data-menu-item]').evaluateAll((els) => els.map((e) => e.dataset.menuItem))
ok('right-clicking an image offers copy, save, copy link and open', ['Copy Image', 'Save Image', 'Copy Link', 'Open Link'].every((x) => imgItems.includes(x)), JSON.stringify(imgItems))
await p.click('[data-menu-item="Copy Link"]'); await p.waitForTimeout(200)
ok('Copy Link copies a full address', /^https?:\/\/.+\/api\/attachments\//.test(await p.evaluate(() => navigator.clipboard.readText())), await p.evaluate(() => navigator.clipboard.readText()))

console.log('-- user menu')
const bobRow = `[data-member-row="${b.user.id}"]`
await p.waitForSelector(bobRow)
const userItems = async () => { await p.click(bobRow, { button: 'right' }); await p.waitForSelector('[data-context-menu]'); return p.locator('[data-context-menu] [data-menu-item]').evaluateAll((els) => els.map((e) => e.dataset.menuItem)) }
const items = await userItems()
ok('the user menu has Mention, Call, Add Note, Change Nickname, Roles and Invite to Server', ['Mention', 'Message', 'Call', 'Add Note', 'Change Nickname', 'Roles', 'Invite to Server'].every((x) => items.includes(x)), JSON.stringify(items))
await p.click('[data-menu-item="Mention"]'); await p.waitForTimeout(150)
ok('Mention puts @name in the box', /^@\S+ $/.test(await p.inputValue(box)), await p.inputValue(box))
await p.keyboard.type('hello'); await p.keyboard.press('Enter'); await p.waitForTimeout(500)
const sent = (await call(a.token, 'GET', `/channels/${general.id}/messages?limit=3`)).find((m) => m.content.endsWith('hello'))
ok('and it is sent as a real mention', sent?.content === `<@${b.user.id}> hello`, sent?.content)
await userItems(); await p.hover('[data-menu-item="Roles"]'); await p.click('[data-context-menu] button:has-text("Helper")'); await p.waitForTimeout(500)
const bobMember = async () => (await call(a.token, 'GET', `/guilds/${g.id}/members`)).find((m) => m.user_id === b.user.id)
ok('Roles ticks a role on', (await bobMember()).roles.includes(role.id))
await userItems(); await p.hover('[data-menu-item="Roles"]')
ok('and shows it ticked', await p.locator('[data-context-menu] button:has-text("✓ Helper")').count() === 1)
await p.keyboard.press('Escape')
await userItems(); await p.click('[data-menu-item="Change Nickname"]'); await p.fill('[data-nick-input]', 'Bobby'); await p.click('[data-nick-save]'); await p.waitForTimeout(500)
ok('Change Nickname sets theirs', (await bobMember()).nickname === 'Bobby')
await userItems(); await p.hover('[data-menu-item="Invite to Server"]'); await p.click(`[data-context-menu] button:has-text("Second ${S}")`); await p.waitForTimeout(800)
const dms = await call(b.token, 'GET', '/users/@me/channels')
const dm = dms.find((d) => d.recipients?.some((r) => r.id === a.user.id))
const dmMsgs = dm ? await call(b.token, 'GET', `/channels/${dm.id}/messages?limit=5`) : []
ok('Invite to Server DMs them an invite link', dmMsgs.some((m) => /\/invite\/\w+/.test(m.content)), JSON.stringify(dmMsgs.map((m) => m.content)))

console.log('-- category menu')
await call(b.token, 'POST', `/channels/${inCat.id}/messages`, { content: 'anyone here?' }); await p.waitForTimeout(600)
const catHeader = `[data-category="${cat.id}"] [data-category-header]`
const catItems = async () => { await p.click(catHeader, { button: 'right' }); await p.waitForSelector('[data-context-menu]'); return p.locator('[data-context-menu] [data-menu-item]').evaluateAll((els) => els.map((e) => [e.dataset.menuItem, e.disabled])) }
let ci = await catItems()
ok('the category menu has Mark As Read, notifications and Collapse/Expand All', ['Mark As Read', 'Collapse All Categories', 'Expand All Categories', 'Mute Category'].every((x) => ci.some(([l]) => l === x || l.startsWith(x))), JSON.stringify(ci))
ok('Mark As Read is live when a channel inside is unread', ci.find(([l]) => l === 'Mark As Read')?.[1] === false)
await p.click('[data-menu-item="Mark As Read"]'); await p.waitForTimeout(600)
ci = await catItems()
ok('after marking, nothing inside is unread', ci.find(([l]) => l === 'Mark As Read')?.[1] === true)
await p.hover('[data-context-menu] [data-menu-item^="Mute Category"]'); await p.waitForTimeout(150)
await p.locator('[data-context-menu] [data-menu-item="Until I turn it back on"]').click().catch(async () => { await p.locator('[data-context-menu] [data-menu-item^="Mute Category"]').click() })
await p.waitForTimeout(500)
ok('muting the category dims the channels in it', await p.locator(`[data-channel-item="${inCat.id}"] [data-muted="true"]`).count() === 1)
await catItems(); await p.click('[data-menu-item="Collapse All Categories"]'); await p.waitForTimeout(200)
ok('Collapse All Categories folds them', await p.locator(`[data-channel-item="${inCat.id}"]`).count() === 0)
await catItems(); await p.click('[data-menu-item="Expand All Categories"]'); await p.waitForTimeout(200)
ok('Expand All brings them back', await p.locator(`[data-channel-item="${inCat.id}"]`).count() === 1)

console.log('-- desktop back/forward')
ok('the web app has no back/forward buttons (the browser has its own)', await p.locator('[data-history-nav]').count() === 0)
const dctx = await browser.newContext({ viewport: { width: 1280, height: 800 }, userAgent: 'Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0.0.0 Safari/537.36 ParleyDesktop/0.1.0' })
const d = await dctx.newPage(); d.on('pageerror', (e) => errors.push(e.message))
await d.goto(`${WEB}/login`); await d.evaluate((t) => localStorage.setItem('parley.token', t), a.token)
await d.goto(`${WEB}/channels/${g.id}/${general.id}`); await d.waitForSelector('[data-history-back]'); await d.waitForTimeout(500)
await d.click(`[data-channel-item="${inCat.id}"] a`); await d.waitForTimeout(400)
await d.click('[data-history-back]'); await d.waitForTimeout(400)
ok('Back returns to the previous channel', d.url().endsWith(general.id), d.url())
await d.click('[data-history-forward]'); await d.waitForTimeout(400)
ok('Forward goes again', d.url().endsWith(inCat.id))
await d.evaluate(() => document.activeElement?.blur()); await d.keyboard.press('Alt+ArrowLeft'); await d.waitForTimeout(400)
ok('Alt+Left goes back too', d.url().endsWith(general.id))
ok('no page errors', errors.length === 0, errors.join(' | '))
await call(a.token, 'DELETE', `/guilds/${g.id}`); await call(a.token, 'DELETE', `/guilds/${g2.id}`)
await browser.close(); await finish()
