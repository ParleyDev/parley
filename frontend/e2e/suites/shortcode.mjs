import { chromium } from 'playwright'
import { API_ORIGIN, B, WEB, S, reg, login, loginRaw, call, raw, multi, ok, pass, fail, finish, PNG, GIF, pngFile, gifFile, adminToken, track } from '../lib.mjs'
const a=await reg('alice'); const g=await call(a.token,'POST','/guilds',{name:'SC'}); const tc=g.channels.find(x=>x.kind==='text').id
const f=new FormData(); f.append('name','party_blob'); f.append('file',new Blob([PNG],{type:'image/png'}),'p.png'); const em=await (await fetch(B+`/guilds/${g.id}/emojis`,{method:'POST',headers:{Authorization:'Bearer '+a.token},body:f})).json()
const browser=await chromium.launch(); const p=await browser.newPage({viewport:{width:1440,height:900}}); const errors=[]; p.on('pageerror',e=>errors.push(e.message))
await p.goto(`${WEB}/login`); await p.evaluate((t)=>localStorage.setItem('parley.token',t),a.token)
await p.goto(`${WEB}/channels/${g.id}/${tc}`); await p.waitForSelector('textarea'); await p.waitForTimeout(500)
const ta=p.locator('textarea')
await ta.click(); await ta.type('hello :fir'); await p.waitForTimeout(500)
ok('typing :fir opens suggestions with :fire:', await p.locator('[data-shortcode-suggest] [data-suggestion=":fire:"]').count()===1)
ok('first row highlighted', await p.locator('[data-shortcode-suggest] [role=option][aria-selected="true"]').count()===1)
await p.screenshot({ path: '57-shortcode.png' })
const first=await p.locator('[data-shortcode-suggest] [role=option]').first().getAttribute('data-suggestion')
await p.keyboard.press('ArrowDown'); await p.waitForTimeout(100)
const second=await p.locator('[data-shortcode-suggest] [role=option][aria-selected="true"]').getAttribute('data-suggestion')
ok('ArrowDown moves the highlight', second!==first, `${first} -> ${second}`)
await p.keyboard.press('ArrowUp'); await p.keyboard.press('Enter'); await p.waitForTimeout(150)
ok('Enter inserts the highlighted emoji and closes', (await ta.inputValue())==='hello 🔥 ' && await p.locator('[data-shortcode-suggest]').count()===0, JSON.stringify(await ta.inputValue()))
ok('Enter did not send the message', await p.locator('.msg-content').count()===0)
await ta.type(':party_'); await p.waitForTimeout(400)
ok('custom emoji suggested', await p.locator('[data-suggestion=":party_blob:"]').count()===1)
await p.keyboard.press('Tab'); await p.waitForTimeout(150)
ok('Tab inserts the custom token', (await ta.inputValue()).includes(`<:party_blob:${em.id}> `))
await ta.type(':fire:'); await p.waitForTimeout(300)
ok('typing the closing colon converts an exact shortcode', (await ta.inputValue()).endsWith('🔥 '), JSON.stringify(await ta.inputValue()))
await ta.type(':thumbs'); await p.waitForTimeout(300); await p.keyboard.press('Escape'); await p.waitForTimeout(100)
ok('Escape dismisses without inserting', await p.locator('[data-shortcode-suggest]').count()===0 && (await ta.inputValue()).endsWith(':thumbs'))
await ta.type(' x:ab'); await p.waitForTimeout(300)
ok('no popup mid-word (x:ab)', await p.locator('[data-shortcode-suggest]').count()===0)
await ta.fill(''); await ta.type('12:30'); await p.waitForTimeout(300)
ok('no popup for times like 12:30', await p.locator('[data-shortcode-suggest]').count()===0)
await ta.fill(''); await ta.type(':zzzzzz'); await p.waitForTimeout(300)
ok('no popup when nothing matches', await p.locator('[data-shortcode-suggest]').count()===0)
await ta.fill(''); await ta.type('go :rocket'); await p.waitForTimeout(300); await p.keyboard.press('Enter'); await p.waitForTimeout(100); await p.keyboard.press('Enter'); await p.waitForTimeout(600)
ok('pick then Enter sends the message with the emoji', await p.locator('.msg-content:has-text("go 🚀")').count()===1)
await ta.fill(''); await ta.type(':smile:'); await p.waitForTimeout(300)
ok('Discord alias :smile: converts to 😄', (await ta.inputValue())==='😄 ', JSON.stringify(await ta.inputValue()))
await ta.type(':joy'); await p.waitForTimeout(300)
ok(':joy suggests 😂 labelled :joy: first', (await p.locator('[data-shortcode-suggest] [role=option]').first().getAttribute('data-suggestion'))===':joy:' && await p.locator('[data-suggestion=":joy:"] img, [data-suggestion=":joy:"] span:has-text("😂")').count()===1)
await p.keyboard.press('Enter'); await p.waitForTimeout(100)
ok('alias pick inserts the emoji', (await ta.inputValue())==='😄 😂 ')
await ta.type(':+1:'); await p.waitForTimeout(300)
ok(':+1: converts to 👍', (await ta.inputValue())==='😄 😂 👍 ', JSON.stringify(await ta.inputValue()))
await ta.type(':thumbsup'); await p.waitForTimeout(300); await p.keyboard.press('Escape')
await p.click('[data-emoji-button]'); await p.waitForTimeout(500); await p.fill('[data-emoji-search]', 'joy'); await p.waitForTimeout(200)
ok('picker search finds aliases too', await p.locator('[data-emoji-btn=":joy:"]').count()===1)
await p.keyboard.press('Escape')
ok('no page errors', errors.length===0, errors.join('|'))
await browser.close(); await finish()
