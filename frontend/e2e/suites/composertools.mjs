// Composer tools: <t:…> timestamps in each reader's time zone, built-in slash commands (/shrug, /me, /spoiler, /nick),
// Up arrow to edit your last message, per-channel drafts that survive switching and reloads, the 2000-character
// limit with "Send as file", and the tab title with where you are and the unread count.
import { chromium } from 'playwright'
import { WEB, S, reg, call, ok, finish } from '../lib.mjs'
const a = await reg('alice'), b = await reg('bob')
const g = await call(a.token, 'POST', '/guilds', { name: `Tools ${S}` })
const inv = await call(a.token, 'POST', `/guilds/${g.id}/invites`, {}); await call(b.token, 'POST', `/invites/${inv.code}`)
const general = g.channels.find((c) => c.kind === 'text')
const other = await call(a.token, 'POST', `/guilds/${g.id}/channels`, { name: 'other', kind: 'text' })
const browser = await chromium.launch(); const errors = []
const ctx = await browser.newContext({ viewport: { width: 1280, height: 800 }, locale: 'en-US', timezoneId: 'UTC' })
const p = await ctx.newPage(); p.on('pageerror', (e) => errors.push(e.message))
await p.goto(`${WEB}/login`); await p.evaluate((t) => localStorage.setItem('parley.token', t), a.token)
await p.goto(`${WEB}/channels/${g.id}/${general.id}`); await p.waitForSelector('[data-composer-box] textarea'); await p.waitForTimeout(600)
const box = '[data-composer-box] textarea'
const latest = async (ch = general.id) => (await call(a.token, 'GET', `/channels/${ch}/messages?limit=5`)).sort((x, y) => (x.id < y.id ? 1 : -1))[0]
const send = async (text) => { await p.fill(box, text); await p.keyboard.press('Enter'); await p.waitForTimeout(500) }

console.log('-- timestamps')
await send('Launch <t:1700000000:D> at <t:1700000000:t>, that was <t:1700000000:R>')
const ts = await p.locator('[data-timestamp]').evaluateAll((els) => els.map((e) => [e.dataset.timestamp, e.textContent, e.getAttribute('title')]))
ok('long date in the reader\'s locale and zone', ts.some(([s, t]) => s === 'D' && t === 'November 14, 2023'), JSON.stringify(ts))
ok('short time', ts.some(([s, t]) => s === 't' && /10:13/.test(t)))
ok('relative time', ts.some(([s, t]) => s === 'R' && /years? ago/.test(t)))
ok('hovering shows the full date and time', ts.every(([, , title]) => /Tuesday, November 14, 2023/.test(title)))

console.log('-- slash commands')
await p.fill(box, '/'); await p.waitForTimeout(150)
ok('typing / lists the commands', await p.locator('[data-command-suggest] [data-command]').count() >= 6)
await p.fill(box, '/shr'); await p.waitForTimeout(150)
ok('typing narrows the list', await p.locator('[data-command-suggest] [data-command]').count() === 1)
await p.keyboard.press('Enter'); await p.waitForTimeout(100)
ok('Enter picks the command', await p.inputValue(box) === '/shrug ')
await p.keyboard.type('fine'); await p.keyboard.press('Enter'); await p.waitForTimeout(600)
ok('/shrug appends the face, shown as typed', /fine ¯\\_\(ツ\)_\/¯$/.test(await p.locator('[data-msg-id]').last().innerText()), await p.locator('[data-msg-id]').last().innerText())
await send('/me waves')
ok('/me sends italics', (await latest()).content === '_waves_')
await send('/spoiler the ending')
ok('/spoiler hides the text', (await latest()).content === '||the ending||')
await send('/nick Captain')
const me = async () => (await call(a.token, 'GET', `/guilds/${g.id}/members`)).find((m) => m.user_id === a.user.id)
ok('/nick changes your server nickname without sending', (await me())?.nickname === 'Captain' && (await latest()).content === '||the ending||')
await send('/nick ')
ok('/nick on its own resets it', !(await me())?.nickname)
await send('/notacommand hello')
ok('an unknown /word is sent as typed', (await latest()).content === '/notacommand hello')

console.log('-- Up arrow edits')
await send('first try')
await p.focus(box); await p.keyboard.press('ArrowUp'); await p.waitForTimeout(200)
const editing = p.locator('[data-msg-id] textarea')
ok('Up arrow in an empty box opens your last message', await editing.count() === 1 && await editing.inputValue() === 'first try')
await p.keyboard.type(', fixed'); await p.keyboard.press('Enter'); await p.waitForTimeout(500)
ok('typing goes to the end and Enter saves', (await latest()).content === 'first try, fixed')
ok('focus returns to the message box', await p.evaluate((sel) => document.activeElement === document.querySelector(sel), box))

console.log('-- drafts')
await p.fill(box, 'half-written thought'); await p.waitForTimeout(500)
await p.click(`[data-channel-item="${other.id}"] button, [data-channel-item="${other.id}"] a`)
await p.waitForTimeout(500)
ok('another channel starts empty', await p.inputValue(box) === '')
await p.fill(box, 'other channel note'); await p.waitForTimeout(500)
await p.goto(`${WEB}/channels/${g.id}/${general.id}`); await p.waitForSelector(box); await p.waitForTimeout(600)
ok('coming back (even after a reload) restores the draft', await p.inputValue(box) === 'half-written thought', await p.inputValue(box))
await p.keyboard.press('Enter'); await p.waitForTimeout(500)
await p.reload(); await p.waitForSelector(box); await p.waitForTimeout(600)
ok('sending clears the draft', await p.inputValue(box) === '')
await p.goto(`${WEB}/channels/${g.id}/${other.id}`); await p.waitForSelector(box); await p.waitForTimeout(600)
ok('each channel keeps its own', await p.inputValue(box) === 'other channel note')
await p.fill(box, ''); await p.waitForTimeout(500)
await p.goto(`${WEB}/channels/${g.id}/${general.id}`); await p.waitForSelector(box); await p.waitForTimeout(500)

console.log('-- long messages')
const before = (await latest()).id
await p.fill(box, 'x'.repeat(1900)); await p.waitForTimeout(100)
ok('near the limit, a counter shows what is left', /100 characters left/.test(await p.locator('[data-char-count]').innerText()))
await p.fill(box, 'y'.repeat(2100)); await p.waitForTimeout(100)
ok('over the limit it says by how much', /100 characters over/.test(await p.locator('[data-char-count]').innerText()))
await p.keyboard.press('Enter'); await p.waitForTimeout(500)
ok('Enter refuses instead of cutting the message off', (await latest()).id === before && (await p.inputValue(box)).length === 2100)
await p.click('[data-send-as-file]'); await p.waitForSelector('[data-pending]'); await p.waitForFunction(() => /KB|B$/.test(document.querySelector('[data-pending]')?.textContent ?? ''), null, { timeout: 10000 })
ok('Send as file turns it into message.txt', /message\.txt/.test(await p.locator('[data-pending]').innerText()) && await p.inputValue(box) === '')
await p.focus(box); await p.keyboard.press('Enter'); await p.waitForTimeout(800)
const filed = await latest()
ok('and sends it as an attachment', filed.attachments?.[0]?.filename === 'message.txt' && filed.attachments[0].size === 2100, JSON.stringify(filed.attachments))

console.log('-- tab title')
ok('the title says where you are', await p.title() === `#general | Tools ${S} | Parley`, await p.title())
await call(b.token, 'POST', `/channels/${other.id}/messages`, { content: `hey <@${a.user.id}>` })
await p.waitForFunction(() => document.title.startsWith('(1) '), null, { timeout: 8000 }).catch(() => {})
ok('a mention elsewhere puts the count in front', (await p.title()).startsWith('(1) #general'), await p.title())
ok('no page errors', errors.length === 0, errors.join(' | '))
await call(a.token, 'DELETE', `/guilds/${g.id}`)
await browser.close(); await finish()
