// README badges for invites: the public SVG (counts, invisible members, expired and unknown invites, styles, label
// escaping, headers), the server's badge settings (label, colour, counts, default style, off) and Server Settings › Badge.
import { chromium } from 'playwright'
import { WEB, B, S, reg, call, raw, ok, finish } from '../lib.mjs'
const a = await reg('alice'), b = await reg('bob'), c = await reg('carol')
const g = await call(a.token, 'POST', '/guilds', { name: `Badge ${S}` })
const forever = await call(a.token, 'POST', `/guilds/${g.id}/invites`, { max_age: 0, max_uses: 0 })
for (const u of [b, c]) await call(u.token, 'POST', `/invites/${forever.code}`)
const svg = async (path) => { const r = await fetch(`${B}/invites/${path}`); return { r, t: await r.text() } }
const message = (t) => [...t.matchAll(/<text x="[^"]+" y="\d+" transform="scale\(.1\)" fill="#fff" textLength="[^"]+">([^<]*)<\/text>/g)].map((m) => m[1])

console.log('-- public SVG')
let { r, t } = await svg(`${forever.code}/badge.svg`)
ok('served without logging in, as SVG', r.status === 200 && /^image\/svg\+xml/.test(r.headers.get('content-type')) && t.startsWith('<svg'))
ok('revalidated by viewers, cached briefly by CDNs, locked down', r.headers.get('cache-control') === 'no-cache' && /max-age=300/.test(r.headers.get('cdn-cache-control')) && /default-src 'none'/.test(r.headers.get('content-security-policy')) && r.headers.get('x-content-type-options') === 'nosniff')
ok('shows the label and counts', JSON.stringify(message(t)) === JSON.stringify(['Parley', '0 online · 3 members']), JSON.stringify(message(t)))
ok('carries the Parley logo', /<image [^>]*xlink:href="data:image\/svg\+xml;base64,/.test(t))

const browser = await chromium.launch()
const ctx = await browser.newContext({ viewport: { width: 1280, height: 900 }, permissions: ['clipboard-read', 'clipboard-write'] })
const p = await ctx.newPage(); const errors = []; p.on('pageerror', (e) => errors.push(e.message))
await p.goto(`${WEB}/login`); await p.evaluate((tok) => localStorage.setItem('parley.token', tok), a.token)
await p.goto(`${WEB}/channels/${g.id}`); await p.waitForTimeout(1500)
// bob is online but invisible: he mustn't show as online to the world.
await call(b.token, 'PATCH', '/users/@me', { status: 'invisible' })
const pb = await (await browser.newContext()).newPage()
await pb.goto(`${WEB}/login`); await pb.evaluate((tok) => localStorage.setItem('parley.token', tok), b.token)
await pb.goto(`${WEB}/channels/@me`); await pb.waitForTimeout(1500)
;({ t } = await svg(`${forever.code}/badge.svg`))
ok('counts online members, not invisible ones', message(t)[1] === '1 online · 3 members', message(t)[1])

const once = await call(a.token, 'POST', `/guilds/${g.id}/invites`, { max_age: 3600, max_uses: 1 })
const outsider = await reg('dave'); await call(outsider.token, 'POST', `/invites/${once.code}`)
;({ r, t } = await svg(`${once.code}/badge.svg`))
ok('a used-up invite turns grey: "invite expired"', r.status === 200 && message(t)[1] === 'invite expired' && t.includes('#9f9f9f'))
;({ r, t } = await svg('nope-not-real/badge.svg'))
ok('an unknown code says "invalid invite"', r.status === 200 && message(t)[1] === 'invalid invite')
;({ t } = await svg(`${forever.code}/badge.svg?style=for-the-badge`))
ok('for-the-badge is taller and upper case', t.includes('height="28"') && message(t)[0] === 'PARLEY')
;({ t } = await svg(`${forever.code}/badge.svg?style=flat-square`))
ok('flat-square has square corners', t.includes('rx="0"'))
;({ t } = await svg(`${forever.code}/badge.svg?label=${encodeURIComponent('<script>alert(1)</script> & co')}`))
ok('a custom label is escaped', !t.includes('<script') && message(t)[0].startsWith('&lt;script&gt;'))

console.log('-- badge settings')
const put = (t, body) => raw(t, 'PUT', `/guilds/${g.id}/badge`, body)
ok('defaults when never set', JSON.stringify(await call(a.token, 'GET', `/guilds/${g.id}/badge`)) === JSON.stringify({ enabled: true, label: '', color: '', show: 'both', style: 'flat' }))
ok('only Manage Server can change them', (await put(b.token, { label: 'nope' })).status === 403 && (await raw(b.token, 'GET', `/guilds/${g.id}/badge`)).status === 403)
let saved = await (await put(a.token, { enabled: true, label: '  Acme  ', color: '#E05D44', show: 'members', style: 'for-the-badge' })).json()
ok('saved settings are cleaned', saved.label === 'Acme' && saved.color === '#e05d44')
;({ t } = await svg(`${forever.code}/badge.svg`))
ok('the public badge uses the label, members-only count and default style', JSON.stringify(message(t)) === JSON.stringify(['ACME', '4 MEMBERS']) && t.includes('height="28"'), JSON.stringify(message(t)))
ok('and the colour', t.includes('#e05d44'))
;({ t } = await svg(`${forever.code}/badge.svg?style=flat&label=Hi`))
ok('a style or label in the URL still wins', t.includes('height="20"') && message(t)[0] === 'Hi')
saved = await (await put(a.token, { ...saved, color: 'red" onload="x', show: 'everything' })).json()
ok('a bad colour or count choice falls back to the default', saved.color === '' && saved.show === 'both')
await put(a.token, { ...saved, show: 'online', style: 'flat' })
;({ t } = await svg(`${forever.code}/badge.svg`))
ok('online only', message(t)[1] === '1 online', message(t)[1])
await put(a.token, { ...saved, enabled: false })
;({ t } = await svg(`${forever.code}/badge.svg`))
ok('turned off: grey "badge disabled", no counts', message(t)[1].toLowerCase() === 'badge disabled' && t.includes('#9f9f9f') && !/online|member/i.test(t), JSON.stringify(message(t)))
const prev = await raw(a.token, 'GET', `/guilds/${g.id}/badge/preview.svg?enabled=true&label=Draft&color=%23007ec6&show=both&style=flat`)
const pt = await prev.text()
ok('the settings preview draws unsaved values with real counts', prev.status === 200 && JSON.stringify(message(pt)) === JSON.stringify(['Draft', '1 online · 4 members']) && pt.includes('#007ec6'))
ok('the preview is for managers only', (await raw(b.token, 'GET', `/guilds/${g.id}/badge/preview.svg`)).status === 403)
await put(a.token, { enabled: true, label: '', color: '', show: 'both', style: 'flat' })

console.log('-- Server Settings › Badge')
await p.click(`aside button:has-text("Badge ${S}")`); await p.click('text=Server Settings'); await p.waitForTimeout(400)
await p.click('[role=dialog] button:has-text("Invites")'); await p.waitForTimeout(600)
ok('Invites links to the badge settings', await p.locator('[data-badge-link]').count() === 1)
await p.click('[data-badge-link]'); await p.waitForSelector('[data-badge-tab]'); await p.waitForTimeout(600)
const previewOk = () => p.waitForFunction(() => { const i = document.querySelector('[data-badge-preview]'); return i?.complete && i.naturalWidth > 50 }, null, { timeout: 5000 }).then(() => true).catch(() => false)
ok('the preview loads', await previewOk())
ok('defaults to the invite that never expires', await p.inputValue('[data-badge-invite]') === forever.code)
ok('no warning for a link that never expires', await p.locator('[data-badge-warn]').count() === 0)
ok('save is off until something changes', await p.isDisabled('[data-badge-save]'))
const src0 = await p.getAttribute('[data-badge-preview]', 'src')
await p.fill('[data-badge-label]', 'Our server'); await p.click('[data-badge-color="#007ec6"]'); await p.selectOption('[data-badge-show]', 'members'); await p.selectOption('[data-badge-style]', 'flat-square')
await p.waitForFunction((s0) => document.querySelector('[data-badge-preview]')?.getAttribute('src') !== s0, src0, { timeout: 5000 }).catch(() => {})
ok('the preview follows unsaved changes', await previewOk() && (await p.getAttribute('[data-badge-preview]', 'src')) !== src0)
;({ t } = await svg(`${forever.code}/badge.svg`))
ok('posted badges don\'t change before saving', message(t)[0] === 'Parley')
await p.click('[data-badge-save]'); await p.waitForTimeout(600)
ok('save stores the settings', JSON.stringify(await call(a.token, 'GET', `/guilds/${g.id}/badge`)) === JSON.stringify({ enabled: true, label: 'Our server', color: '#007ec6', show: 'members', style: 'flat-square' }))
;({ t } = await svg(`${forever.code}/badge.svg`))
ok('and every posted badge follows', JSON.stringify(message(t)) === JSON.stringify(['Our server', '4 members']) && t.includes('rx="0"') && t.includes('#007ec6'))
await p.click('[data-badge-copy="markdown"]'); await p.waitForTimeout(200)
let clip = await p.evaluate(() => navigator.clipboard.readText())
ok('Copy Markdown gives a linked badge that follows the settings', clip === `[![Join Badge ${S} on Parley](${WEB}/api/invites/${forever.code}/badge.svg)](${WEB}/invite/${forever.code})`, clip)
await p.click('[data-badge-copy="html"]'); await p.waitForTimeout(200)
clip = await p.evaluate(() => navigator.clipboard.readText())
ok('HTML copy too', clip === `<a href="${WEB}/invite/${forever.code}"><img src="${WEB}/api/invites/${forever.code}/badge.svg" alt="Join Badge ${S} on Parley"></a>`, clip)
await p.click('[data-badge-enabled] [role=switch]'); await p.click('[data-badge-save]'); await p.waitForTimeout(600)
ok('the switch turns the badge off', (await call(a.token, 'GET', `/guilds/${g.id}/badge`)).enabled === false)
await p.click('[data-badge-enabled] [role=switch]'); await p.fill('[data-badge-color-custom]', '#123456')
await p.click('[data-badge-save]'); await p.waitForTimeout(600)
const after = await call(a.token, 'GET', `/guilds/${g.id}/badge`)
ok('back on, with a custom colour', after.enabled === true && after.color === '#123456', JSON.stringify(after))
const temp = await call(a.token, 'POST', `/guilds/${g.id}/invites`, { max_age: 86400, max_uses: 0 })
await p.click('[role=dialog] button:has-text("Invites")'); await p.waitForTimeout(400); await p.click('[data-badge-link]'); await p.waitForTimeout(800)
await p.selectOption('[data-badge-invite]', temp.code); await p.waitForTimeout(200)
ok('an expiring invite warns the badge will go grey', /expires in 1 day/.test(await p.locator('[data-badge-warn]').innerText().catch(() => '')))
await p.click('[role=dialog] button:has-text("Audit Log")'); await p.waitForTimeout(800)
ok('changes show in the audit log', /changed the README badge/.test(await p.locator('[role=dialog]').innerText()))
await p.click('[role=dialog] button:has-text("Badge")'); await p.waitForTimeout(600)
await p.setViewportSize({ width: 390, height: 844 }); await p.waitForTimeout(400)
ok('phone: the tab fits', await p.evaluate(() => { const t = document.querySelector('[data-badge-tab]'); return !!t && t.scrollWidth <= t.clientWidth + 1 }), await p.evaluate(() => { const t = document.querySelector('[data-badge-tab]'); return t ? `${t.scrollWidth}/${t.clientWidth} ` + [...t.querySelectorAll('*')].filter((e) => e.getBoundingClientRect().right > t.getBoundingClientRect().right + 1).slice(0, 3).map((e) => e.tagName + '.' + e.className.toString().slice(0, 40)).join(',') : 'none' }))
ok('no page errors', errors.length === 0, errors.join(' | '))
await call(a.token, 'DELETE', `/guilds/${g.id}`, { password: 'password1', name: g.name })
await browser.close()
await finish()
