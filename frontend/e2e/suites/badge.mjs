// README badges for invites: the public SVG (counts, invisible members, expired and unknown invites, styles, label
// escaping, headers) and the README badge section in Server Settings › Invites (preview, Markdown/HTML copy, warning).
import { chromium } from 'playwright'
import { WEB, B, S, reg, call, ok, finish } from '../lib.mjs'
const a = await reg('alice'), b = await reg('bob'), c = await reg('carol')
const g = await call(a.token, 'POST', '/guilds', { name: `Badge ${S}` })
const forever = await call(a.token, 'POST', `/guilds/${g.id}/invites`, { max_age: 0, max_uses: 0 })
for (const u of [b, c]) await call(u.token, 'POST', `/invites/${forever.code}`)
const svg = async (path) => { const r = await fetch(`${B}/invites/${path}`); return { r, t: await r.text() } }
const message = (t) => [...t.matchAll(/<text x="[^"]+" y="\d+" transform="scale\(.1\)" fill="#fff" textLength="[^"]+">([^<]*)<\/text>/g)].map((m) => m[1])

console.log('-- public SVG')
let { r, t } = await svg(`${forever.code}/badge.svg`)
ok('served without logging in, as SVG', r.status === 200 && /^image\/svg\+xml/.test(r.headers.get('content-type')) && t.startsWith('<svg'))
ok('revalidated by viewers, cached briefly by CDNs, locked down', r.headers.get('cache-control') === 'no-cache' && /max-age=300/.test(r.headers.get('cdn-cache-control')) && /default-src 'none'/.test(r.headers.get('content-security-policy')) && r.headers.get('x-content-type-options') === 'nosniff')
ok('shows the label and counts', JSON.stringify(message(t)) === JSON.stringify(['Parley', '0 online · 3 members']), JSON.stringify(message(t)))
ok('carries the Parley logo', /<image [^>]*xlink:href="data:image\/svg\+xml;base64,/.test(t))

const browser = await chromium.launch()
const ctx = await browser.newContext({ viewport: { width: 1280, height: 900 }, permissions: ['clipboard-read', 'clipboard-write'] })
const p = await ctx.newPage(); const errors = []; p.on('pageerror', (e) => errors.push(e.message))
await p.goto(`${WEB}/login`); await p.evaluate((tok) => localStorage.setItem('parley.token', tok), a.token)
await p.goto(`${WEB}/channels/${g.id}`); await p.waitForTimeout(1500)
// bob is online but invisible: he mustn't show as online to the world.
await call(b.token, 'PATCH', '/users/@me', { status: 'invisible' })
const pb = await (await browser.newContext()).newPage()
await pb.goto(`${WEB}/login`); await pb.evaluate((tok) => localStorage.setItem('parley.token', tok), b.token)
await pb.goto(`${WEB}/channels/@me`); await pb.waitForTimeout(1500)
;({ t } = await svg(`${forever.code}/badge.svg`))
ok('counts online members, not invisible ones', message(t)[1] === '1 online · 3 members', message(t)[1])

const once = await call(a.token, 'POST', `/guilds/${g.id}/invites`, { max_age: 3600, max_uses: 1 })
const outsider = await reg('dave'); await call(outsider.token, 'POST', `/invites/${once.code}`)
;({ r, t } = await svg(`${once.code}/badge.svg`))
ok('a used-up invite turns grey: "invite expired"', r.status === 200 && message(t)[1] === 'invite expired' && t.includes('#9f9f9f'))
;({ r, t } = await svg('nope-not-real/badge.svg'))
ok('an unknown code says "invalid invite"', r.status === 200 && message(t)[1] === 'invalid invite')
;({ t } = await svg(`${forever.code}/badge.svg?style=for-the-badge`))
ok('for-the-badge is taller and upper case', t.includes('height="28"') && message(t)[0] === 'PARLEY')
;({ t } = await svg(`${forever.code}/badge.svg?style=flat-square`))
ok('flat-square has square corners', t.includes('rx="0"'))
;({ t } = await svg(`${forever.code}/badge.svg?label=${encodeURIComponent('<script>alert(1)</script> & co')}`))
ok('a custom label is escaped', !t.includes('<script') && message(t)[0].startsWith('&lt;script&gt;'))

console.log('-- Server Settings › Invites')
await p.click(`aside button:has-text("Badge ${S}")`); await p.click('text=Server Settings'); await p.waitForTimeout(400)
await p.click('[role=dialog] button:has-text("Invites")'); await p.waitForTimeout(900)
ok('README badge section shows', await p.locator('[data-badge-section]').count() === 1)
ok('defaults to the invite that never expires', await p.inputValue('[data-badge-invite]') === forever.code)
const loaded = await p.waitForFunction(() => { const i = document.querySelector('[data-badge-preview]'); return i?.complete && i.naturalWidth > 50 }, null, { timeout: 5000 }).then(() => true).catch(() => false)
ok('the preview image loads', loaded)
ok('no warning for a link that never expires', await p.locator('[data-badge-warn]').count() === 0)
await p.click('[data-badge-copy="markdown"]'); await p.waitForTimeout(200)
let clip = await p.evaluate(() => navigator.clipboard.readText())
ok('Copy Markdown gives a linked badge', clip === `[![Join Badge ${S} on Parley](${WEB}/api/invites/${forever.code}/badge.svg)](${WEB}/invite/${forever.code})`, clip)
await p.selectOption('[data-badge-style]', 'for-the-badge'); await p.click('[data-badge-copy="html"]'); await p.waitForTimeout(200)
clip = await p.evaluate(() => navigator.clipboard.readText())
ok('HTML copy carries the chosen style', clip === `<a href="${WEB}/invite/${forever.code}"><img src="${WEB}/api/invites/${forever.code}/badge.svg?style=for-the-badge" alt="Join Badge ${S} on Parley"></a>`, clip)
ok('preview follows the style', (await p.getAttribute('[data-badge-preview]', 'src')).endsWith('?style=for-the-badge'))
const temp = await call(a.token, 'POST', `/guilds/${g.id}/invites`, { max_age: 86400, max_uses: 0 })
await p.keyboard.press('Escape'); await p.waitForTimeout(300)
await p.click(`aside button:has-text("Badge ${S}")`); await p.click('text=Server Settings'); await p.waitForTimeout(400)
await p.click('[role=dialog] button:has-text("Invites")'); await p.waitForTimeout(900)
await p.selectOption('[data-badge-invite]', temp.code); await p.waitForTimeout(200)
ok('an expiring invite warns the badge will go grey', /expires in 1 day/.test(await p.locator('[data-badge-warn]').innerText().catch(() => '')))
await p.setViewportSize({ width: 390, height: 844 }); await p.waitForTimeout(400)
ok('phone: the section fits', await p.evaluate(() => { const t = document.querySelector('[data-badge-section]'); return !!t && t.scrollWidth <= t.clientWidth + 1 }))
ok('no page errors', errors.length === 0, errors.join(' | '))
await call(a.token, 'DELETE', `/guilds/${g.id}`)
await browser.close()
await finish()
