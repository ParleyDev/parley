// User Settings › Profiles: edit display name, pronouns, custom status, presence, avatar and banner right on the preview
// card; changes join the unsaved-changes bar like the form fields.
import { chromium } from 'playwright'
import { WEB, reg, call, ok, finish, pngFile } from '../lib.mjs'
const a = await reg('alice')
const browser = await chromium.launch()
const errors = []
const ctx = await browser.newContext({ viewport: { width: 1440, height: 900 } })
const p = await ctx.newPage(); p.on('pageerror', (e) => errors.push(e.message))
await p.goto(`${WEB}/login`); await p.evaluate((t) => localStorage.setItem('parley.token', t), a.token)
await p.goto(`${WEB}/channels/@me`); await p.waitForSelector('text=Add Friend')
await p.click('button[title="User Settings"]'); await p.click('[role=dialog] nav button:has-text("Profiles")'); await p.waitForSelector('[data-profile-editable]')
const card = p.locator('[data-profile-editable]').locator('xpath=ancestor::*[@data-profile-card]')

console.log('-- text fields')
ok('preview is editable', await p.locator('[data-inline-edit="display_name"]').count() === 1)
await p.click('[data-inline-edit="display_name"]')
await p.fill('[data-inline-input="display_name"]', 'Ally Cat'); await p.keyboard.press('Enter')
ok('name updates on the card', (await p.locator('[data-profile-editable] [data-profile-name]').innerText()) === 'Ally Cat')
ok('and in the form field', (await p.inputValue('input[maxlength="32"]')) === 'Ally Cat')
ok('unsaved bar appears', await p.locator('text=you have unsaved changes').count() === 1)
await p.click('[data-inline-edit="display_name"]'); await p.fill('[data-inline-input="display_name"]', ''); await p.keyboard.press('Enter')
ok('an empty name is ignored', (await p.locator('[data-profile-editable] [data-profile-name]').innerText()) === 'Ally Cat')
await p.click('[data-inline-edit="display_name"]'); await p.fill('[data-inline-input="display_name"]', 'Nope'); await p.keyboard.press('Escape')
ok('Escape cancels without closing settings', (await p.locator('[data-profile-editable] [data-profile-name]').innerText()) === 'Ally Cat' && await p.locator('[data-profile-editable]').count() === 1)
ok('pronouns show a placeholder', /Add pronouns/.test(await p.locator('[data-inline-edit="pronouns"]').innerText()))
await p.click('[data-inline-edit="pronouns"]'); await p.fill('[data-inline-input="pronouns"]', 'she/her'); await p.locator('[data-inline-input="pronouns"]').blur()
ok('pronouns commit on blur', (await p.locator('[data-inline-edit="pronouns"]').innerText()).includes('she/her'))
await p.click('[data-inline-edit="custom_status"]'); await p.fill('[data-inline-input="custom_status"]', '🎧 mixing'); await p.keyboard.press('Enter')
ok('custom status set inline', (await p.locator('[data-inline-edit="custom_status"]').innerText()).includes('🎧 mixing') && (await p.inputValue('[data-profile-custom-status]')) === '🎧 mixing')

console.log('-- images')
await p.locator('[data-inline-avatar-input]').setInputFiles(pngFile)
await p.waitForFunction(() => !!document.querySelector('[data-profile-card] img[src*="/"]'), null, { timeout: 8000 }).catch(() => {})
await p.waitForTimeout(800)
ok('avatar uploaded from the card', await p.locator('[data-inline-avatar-remove]').count() === 1)
await p.locator('[data-inline-banner-input]').setInputFiles(pngFile); await p.waitForTimeout(1200)
const bannerStyle = await card.locator('.group\\/banner').getAttribute('style')
ok('banner uploaded from the card', /url\(/.test(bannerStyle ?? ''), bannerStyle)
await card.locator('.group\\/banner').hover()
ok('banner offers change', /Change banner/.test(await p.locator('[data-inline-banner]').innerText()))

console.log('-- save')
await p.click('button:has-text("Save Changes")'); await p.waitForTimeout(800)
const me = await call(a.token, 'GET', '/users/@me')
ok('saved name, pronouns and status', me.display_name === 'Ally Cat' && me.pronouns === 'she/her' && me.custom_status === '🎧 mixing', JSON.stringify({ n: me.display_name, p: me.pronouns, s: me.custom_status }))
ok('saved avatar and banner', !!me.avatar_url && !!me.banner_url)
ok('unsaved bar gone', await p.locator('text=you have unsaved changes').count() === 0)

console.log('-- remove images and presence')
await card.locator('.group\\/banner').hover(); await p.click('[data-inline-banner-remove]')
await card.locator('.group\\/avatar').hover(); await p.click('[data-inline-avatar-remove]')
await p.click('button:has-text("Save Changes")'); await p.waitForTimeout(800)
const me2 = await call(a.token, 'GET', '/users/@me')
ok('avatar and banner removed', !me2.avatar_url && !me2.banner_url, JSON.stringify({ a: me2.avatar_url, b: me2.banner_url }))
await p.click('[data-inline-presence]'); await p.click('[data-presence-option="dnd"]'); await p.waitForTimeout(800)
ok('presence applied straight away', (await call(a.token, 'GET', '/users/@me')).status === 'dnd')
ok('presence chip follows', (await p.getAttribute('[data-inline-presence]', 'data-inline-presence')) === 'dnd')
await p.click('[data-inline-presence]'); await p.click('[data-presence-option="online"]'); await p.waitForTimeout(500)

console.log('-- other cards stay read-only')
await p.keyboard.press('Escape'); await p.waitForTimeout(300)
await p.click('[data-user-panel] [data-avatar], [data-user-panel] img, [data-user-panel] button').catch(() => {})
ok('no inline editing outside settings', await p.locator('[data-inline-edit]').count() === 0)

console.log('-- phone')
const m = await (await browser.newContext({ viewport: { width: 390, height: 800 }, isMobile: true, hasTouch: true })).newPage(); m.on('pageerror', (e) => errors.push(e.message))
await m.goto(`${WEB}/login`); await m.evaluate((t) => localStorage.setItem('parley.token', t), a.token)
await m.goto(`${WEB}/channels/@me`); await m.waitForTimeout(1200)
await m.click('button[title="User Settings"]'); await m.waitForTimeout(400)
await m.click('[role=dialog] button:has-text("Profiles")'); await m.waitForTimeout(800)
ok('phone: editable preview shows', await m.locator('[data-profile-editable]').count() === 1)
await m.click('[data-inline-edit="pronouns"]'); await m.fill('[data-inline-input="pronouns"]', 'they/them'); await m.keyboard.press('Enter')
ok('phone: inline edit works', (await m.locator('[data-inline-edit="pronouns"]').innerText()).includes('they/them'))
ok('phone: no sideways scroll', await m.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth))
ok('no page errors', errors.length === 0, errors.join(' | '))
await browser.close()
await finish()
