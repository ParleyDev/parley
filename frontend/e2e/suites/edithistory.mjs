import { chromium } from 'playwright'
import { WEB, S, reg, call, callS, raw, ok, finish } from '../lib.mjs'

const a = await reg('alice'); const b = await reg('bob'); const c = await reg('carol')
const g = await call(a.token, 'POST', '/guilds', { name: `Edits ${S}` })
const inv = await call(a.token, 'POST', `/guilds/${g.id}/invites`, {}); await call(b.token, 'POST', `/invites/${inv.code}`)
const tc = (await call(a.token, 'GET', `/guilds/${g.id}/channels`)).find((x) => x.kind === 'text')

console.log('-- API')
const m = await call(a.token, 'POST', `/channels/${tc.id}/messages`, { content: 'first draft' })
let r = await callS(b.token, 'GET', `/channels/${tc.id}/messages/${m.id}/history`); ok('unedited message has an empty history', r.status === 200 && r.body.length === 0)
await callS(a.token, 'PATCH', `/channels/${tc.id}/messages/${m.id}`, { content: 'first draft' })
ok('saving the same text keeps no revision', (await call(a.token, 'GET', `/channels/${tc.id}/messages/${m.id}/history`)).length === 0)
await callS(a.token, 'PATCH', `/channels/${tc.id}/messages/${m.id}`, { content: 'second **draft**' })
await callS(a.token, 'PATCH', `/channels/${tc.id}/messages/${m.id}`, { content: 'third draft' })
const h = await call(b.token, 'GET', `/channels/${tc.id}/messages/${m.id}/history`)
ok('two edits leave two revisions, oldest first', h.length === 2 && h[0].content === 'first draft' && h[1].content === 'second **draft**' && h[0].replaced_at <= h[1].replaced_at)
ok('the message itself carries the latest text', (await call(b.token, 'GET', `/channels/${tc.id}/messages?limit=5`)).find((x) => x.id === m.id)?.content === 'third draft')
r = await raw(c.token, 'GET', `/channels/${tc.id}/messages/${m.id}/history`); ok('non-members cannot read history', r.status === 403 || r.status === 404)
r = await raw(b.token, 'GET', `/channels/${tc.id}/messages/${g.id}/history`); ok('unknown message -> 404', r.status === 404)
const dm = await call(a.token, 'POST', '/users/@me/channels', { recipient_id: b.user.id })
const dmsg = await call(a.token, 'POST', `/channels/${dm.id}/messages`, { content: 'dm one' }); await callS(a.token, 'PATCH', `/channels/${dm.id}/messages/${dmsg.id}`, { content: 'dm two' })
ok('DM edits are kept too and the recipient can read them', (await call(b.token, 'GET', `/channels/${dm.id}/messages/${dmsg.id}/history`))[0]?.content === 'dm one')
r = await raw(c.token, 'GET', `/channels/${dm.id}/messages/${dmsg.id}/history`); ok('outsiders cannot read DM history', r.status === 403 || r.status === 404)
await callS(a.token, 'DELETE', `/channels/${tc.id}/messages/${m.id}`)
r = await raw(b.token, 'GET', `/channels/${tc.id}/messages/${m.id}/history`); ok('deleting the message removes its history', r.status === 404)

console.log('-- UI')
const m2 = await call(a.token, 'POST', `/channels/${tc.id}/messages`, { content: 'hello wrold' })
await callS(a.token, 'PATCH', `/channels/${tc.id}/messages/${m2.id}`, { content: 'hello world' })
const browser = await chromium.launch(); const errors = []
const p = await browser.newPage({ viewport: { width: 1440, height: 900 } }); p.on('pageerror', (e) => errors.push(e.message))
await p.goto(`${WEB}/login`); await p.evaluate((t) => localStorage.setItem('parley.token', t), b.token)
await p.goto(`${WEB}/channels/${g.id}/${tc.id}`); await p.waitForSelector(`[data-msg-id="${m2.id}"] [data-edited]`)
await p.click(`[data-msg-id="${m2.id}"] [data-edited]`); await p.waitForSelector('[data-edit-history] [data-revision="current"]')
ok('clicking (edited) opens the history with the original and current text', (await p.textContent('[data-edit-history] [data-revision="0"]')).includes('hello wrold') && (await p.textContent('[data-edit-history] [data-revision="current"]')).includes('hello world'))
await p.screenshot({ path: '100-edit-history.png' })
ok('no page errors', errors.length === 0, errors.join(' | '))
await browser.close(); await finish()
