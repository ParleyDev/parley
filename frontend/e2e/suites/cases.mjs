// Phase 2 cases (docs/admin-access-and-server-deletion.md): admin content access goes through a case. A report opens
// one with a context window around the reported message; going further, reading a DM or group chat, or exporting
// needs a grant approved by a different T&S lead, scoped to the case and expiring. Every read is logged with the case.
import { execSync } from 'node:child_process'
import { chromium } from 'playwright'
import { WEB, S, reg, call, callS, raw, ok, finish, adminToken, testContainer, openDms } from '../lib.mjs'

const sql = (q) => execSync(`docker exec ${testContainer('db')} psql -U parley -tAc "${q.replace(/"/g, '\\"')}"`, { stdio: ['pipe', 'pipe', 'pipe'] }).toString().trim()
const admin = await adminToken()
const role = async (name, roles) => { const u = await reg(name); await call(admin.token, 'PUT', `/admin/users/${u.user.id}/roles`, { roles }); return u }
const mod = await role('mod', ['MODERATOR']), lead1 = await role('leadone', ['TS_LEAD']), lead2 = await role('leadtwo', ['TS_LEAD']), legal = await role('legal', ['LEGAL']), sup = await role('sup', ['SUPPORT'])
const a = await reg('alice'), b = await reg('bob')
await openDms(a, b)
const g = await call(a.token, 'POST', '/guilds', { name: `Cases ${S}` }); const ch = g.channels.find((x) => x.kind === 'text')
const inv = await call(a.token, 'POST', `/guilds/${g.id}/invites`, {}); await call(b.token, 'POST', `/invites/${inv.code}`)
const posted = []
for (let i = 0; i < 50; i++) posted.push(await call(i % 2 ? b.token : a.token, 'POST', `/channels/${ch.id}/messages`, { content: `line ${i} ${S}` }))
const dm = await call(a.token, 'POST', '/users/@me/channels', { recipient_id: b.user.id })
const dmMsgs = []
for (let i = 0; i < 5; i++) dmMsgs.push(await call(b.token, 'POST', `/channels/${dm.id}/messages`, { content: `dm ${i} ${S}` }))
const why = 'case e2e: checking the report'
const lastLog = (action) => JSON.parse(sql(`SELECT row_to_json(l) FROM (SELECT * FROM admin_access_log WHERE action = '${action}' ORDER BY at DESC LIMIT 1) l`) || 'null')

console.log('-- a report opens a case')
const rep = await call(a.token, 'POST', '/reports', { kind: 'message', message_id: posted[25].id, reason: 'harassment in the channel' })
const reports = await call(mod.token, 'GET', '/admin/reports')
const r = reports.find((x) => x.id === rep.id)
ok('the report carries its case', !!r?.case_id)
const kase = (await call(mod.token, 'GET', `/admin/cases/${r.case_id}`))
ok('a report case, scoped to the channel, centred on the message', kase.case.kind === 'report' && kase.case.status === 'open' && JSON.stringify(kase.case.scope_channel_ids) === JSON.stringify([ch.id]) && kase.case.anchor_message_id === posted[25].id && kase.context_window === 20)
ok('it expires (30 days by default)', Math.abs(new Date(kase.case.expires_at) - Date.now() - 30 * 86400e3) < 120e3)

console.log('-- the context window')
let ctx = await call(mod.token, 'GET', `/admin/cases/${r.case_id}/context`)
const ids = ctx.messages.map((m) => m.id)
ok('moderators see 20 before, the message and 20 after', ctx.messages.length === 41 && ids[0] === posted[5].id && ids[20] === posted[25].id && ids[40] === posted[45].id, `${ctx.messages.length}`)
ok('from that channel only', ctx.messages.every((m) => m.channel_id === ch.id))
let e = lastLog('case.context')
ok('the read is logged with the case and every id shown', e.case_id === r.case_id && e.actor_id === mod.user.id && e.target_ids.length === 41)
ok('support has no report access', (await raw(sup.token, 'GET', `/admin/cases/${r.case_id}/context`)).status === 403 && (await raw(sup.token, 'GET', '/admin/cases')).status === 403)

console.log('-- no case, no content')
ok('reading the channel past the window needs a grant', (await raw(mod.token, 'GET', `/admin/cases/${r.case_id}/messages?channel_id=${ch.id}`)).status === 403)
ok('channels outside the scope are refused', (await raw(lead1.token, 'GET', `/admin/cases/${r.case_id}/messages?channel_id=${dm.id}`)).status === 403)
ok('a grant cannot reach outside the scope', (await raw(mod.token, 'POST', `/admin/cases/${r.case_id}/grants`, { kind: 'expand', justification: why, channel_ids: [dm.id] })).status === 400)

console.log('-- two-person approval')
let gr = await callS(mod.token, 'POST', `/admin/cases/${r.case_id}/grants`, { kind: 'expand', justification: 'need the earlier conversation' })
ok('a moderator asks to expand', gr.status === 200 && gr.body.status === 'pending')
ok('moderators cannot approve', (await raw(mod.token, 'POST', `/admin/cases/${r.case_id}/grants/${gr.body.id}`, { decision: 'approve' })).status === 403)
ok('still no access while pending', (await raw(mod.token, 'GET', `/admin/cases/${r.case_id}/messages?channel_id=${ch.id}`)).status === 403)
const pend = await call(lead1.token, 'GET', '/admin/case-grants')
ok('leads see what waits for them', pend.some((x) => x.id === gr.body.id))
let d = await callS(lead1.token, 'POST', `/admin/cases/${r.case_id}/grants/${gr.body.id}`, { decision: 'approve' })
ok('a lead approves', d.status === 200 && d.body.status === 'approved' && d.body.decided_by === lead1.user.id)
ok('for 72 hours', Math.abs(new Date(d.body.expires_at) - Date.now() - 72 * 3600e3) < 120e3)
let page = await call(mod.token, 'GET', `/admin/cases/${r.case_id}/messages?channel_id=${ch.id}&limit=100`)
const hasAll = (list) => posted.every((x) => list.some((m) => m.id === x.id))
ok('now the moderator reads the channel', hasAll(page) && page.every((m) => m.channel_id === ch.id), `${page.length}`)
e = lastLog('case.messages')
ok('logged too', e.case_id === r.case_id && e.target_ids.length === page.length)
ok("the grant serves only who asked: others can't ride on it", (await raw(lead2.token, 'GET', `/admin/cases/${r.case_id}/messages?channel_id=${ch.id}`)).status === 403)
const own = await callS(lead1.token, 'POST', `/admin/cases/${r.case_id}/grants`, { kind: 'expand', justification: 'my own look at the context' })
ok('leads cannot approve their own requests', (await raw(lead1.token, 'POST', `/admin/cases/${r.case_id}/grants/${own.body.id}`, { decision: 'approve' })).status === 400)
let dbRefused = false
try { sql(`UPDATE case_grants SET status = 'approved', decided_by = requested_by WHERE id = '${own.body.id}'`) } catch (x) { dbRefused = /case_grants_two_person/.test(String(x.stderr)) }
ok('nor can anyone through the database', dbRefused)
ok('a denial sticks', (await callS(lead2.token, 'POST', `/admin/cases/${r.case_id}/grants/${own.body.id}`, { decision: 'deny' })).body.status === 'denied' && (await raw(lead2.token, 'POST', `/admin/cases/${r.case_id}/grants/${own.body.id}`, { decision: 'approve' })).status === 400)

console.log('-- expiry')
sql(`UPDATE case_grants SET expires_at = now() - interval '1 minute' WHERE id = '${gr.body.id}'`)
ok('an expired grant gives nothing', (await raw(mod.token, 'GET', `/admin/cases/${r.case_id}/messages?channel_id=${ch.id}`)).status === 403)
sql(`UPDATE case_grants SET expires_at = now() + interval '1 hour' WHERE id = '${gr.body.id}'`)
d = await callS(lead2.token, 'POST', `/admin/cases/${r.case_id}/grants/${gr.body.id}`, { decision: 'revoke' })
ok('approvals can be revoked', d.body.status === 'revoked' && (await raw(mod.token, 'GET', `/admin/cases/${r.case_id}/messages?channel_id=${ch.id}`)).status === 403)
sql(`UPDATE cases SET expires_at = now() - interval '1 minute' WHERE id = '${r.case_id}'`)
ok('an expired case gives nothing, not even the window', (await raw(mod.token, 'GET', `/admin/cases/${r.case_id}/context`)).status === 400)
sql(`UPDATE cases SET expires_at = now() + interval '1 day' WHERE id = '${r.case_id}'`)

console.log('-- DMs and group chats')
const drep = await call(a.token, 'POST', '/reports', { kind: 'message', message_id: dmMsgs[2].id, reason: 'threats in my DMs' })
const dcase = (await call(mod.token, 'GET', '/admin/reports')).find((x) => x.id === drep.id).case_id
ok('moderators never see DM context', (await raw(mod.token, 'GET', `/admin/cases/${dcase}/context`)).status === 403)
ok('leads neither, without an approved grant', (await raw(lead1.token, 'GET', `/admin/cases/${dcase}/context`)).status === 403)
ok('moderators cannot even ask for DM access', (await raw(mod.token, 'POST', `/admin/cases/${dcase}/grants`, { kind: 'private_access', justification: why })).status === 403)
gr = await callS(lead1.token, 'POST', `/admin/cases/${dcase}/grants`, { kind: 'private_access', justification: 'threat report, need the DM context' })
await call(lead2.token, 'POST', `/admin/cases/${dcase}/grants/${gr.body.id}`, { decision: 'approve' })
ctx = await call(lead1.token, 'GET', `/admin/cases/${dcase}/context`)
ok('with a second lead approving, the requester sees it', ctx.messages.length === 5 && ctx.messages[2].id === dmMsgs[2].id)

console.log('-- investigations and legal cases')
ok('investigations need a justification', (await raw(mod.token, 'POST', '/admin/cases', { kind: 'investigation', subject_kind: 'user', subject_id: b.user.id, channel_ids: [ch.id] })).status === 400)
ok('and an explicit scope', (await raw(mod.token, 'POST', '/admin/cases', { kind: 'investigation', subject_kind: 'user', subject_id: b.user.id, channel_ids: [], justification: why })).status === 400)
ok('support cannot open one', (await raw(sup.token, 'POST', '/admin/cases', { kind: 'investigation', subject_kind: 'user', subject_id: b.user.id, channel_ids: [ch.id], justification: why })).status === 403)
ok('only legal opens legal cases', (await raw(mod.token, 'POST', '/admin/cases', { kind: 'legal', subject_kind: 'user', subject_id: b.user.id, channel_ids: [ch.id], justification: why })).status === 403)
const from = new Date(Date.now() - 3600e3).toISOString()
const icase = await call(mod.token, 'POST', '/admin/cases', { kind: 'investigation', subject_kind: 'user', subject_id: b.user.id, channel_ids: [ch.id, dm.id], justification: 'spam wave from this account', from })
ok('a moderator opens an investigation', icase.kind === 'investigation' && icase.opened_by === mod.user.id && icase.scope_channel_ids.length === 2)
e = lastLog('case.open')
ok('logged with its scope', e.case_id === icase.id && e.target_ids.length === 2 && e.justification === 'spam wave from this account')
page = await call(mod.token, 'GET', `/admin/cases/${icase.id}/messages?channel_id=${ch.id}&limit=100`)
ok('server channels in scope read directly', hasAll(page))
ok('the DM in scope still needs a two-person grant', (await raw(mod.token, 'GET', `/admin/cases/${icase.id}/messages?channel_id=${dm.id}`)).status === 403)
let found = await call(mod.token, 'GET', `/admin/cases/${icase.id}/search?q=${encodeURIComponent(`${S}`)}`)
ok('case search covers what the moderator may read: the channel, not the DM', found.length > 0 && found.every((h) => h.channel_id === ch.id) && found.some((h) => h.id === posted[49].id))
ok('results are metadata, no content', found.every((h) => !('content' in h) && h.author_username))
e = lastLog('case.search')
ok('the search is logged with the case', e.case_id === icase.id && e.target_ids.length === found.length)
let opened = await callS(mod.token, 'POST', `/admin/cases/${icase.id}/messages/${posted[49].id}/open`)
ok('opening a result gives its content, logged', opened.status === 200 && opened.body.content === `line 49 ${S}` && lastLog('case.open_message').target_ids[0] === posted[49].id)
ok('a DM message in scope stays closed without a grant', (await raw(mod.token, 'POST', `/admin/cases/${icase.id}/messages/${dmMsgs[0].id}/open`)).status === 403)
ok('messages outside the case scope stay closed', (await raw(mod.token, 'POST', `/admin/cases/${r.case_id}/messages/${dmMsgs[0].id}/open`)).status === 403)
sql(`UPDATE cases SET scope_from = now() + interval '1 hour' WHERE id = '${icase.id}'`)
ok('the time range bounds what is read', (await call(mod.token, 'GET', `/admin/cases/${icase.id}/messages?channel_id=${ch.id}`)).length === 0)

console.log('-- export')
const lcase = await call(legal.token, 'POST', '/admin/cases', { kind: 'legal', subject_kind: 'conversation', subject_id: ch.id, channel_ids: [ch.id], justification: 'lawful request #2041' })
ok('no export without an approved grant', (await raw(legal.token, 'GET', `/admin/cases/${lcase.id}/export`)).status === 403)
gr = await callS(legal.token, 'POST', `/admin/cases/${lcase.id}/grants`, { kind: 'export', justification: 'production for request #2041' })
ok('only legal can ask to export', (await raw(lead1.token, 'POST', `/admin/cases/${lcase.id}/grants`, { kind: 'export', justification: why })).status === 403)
await call(lead1.token, 'POST', `/admin/cases/${lcase.id}/grants/${gr.body.id}`, { decision: 'approve' })
const ex = await callS(legal.token, 'GET', `/admin/cases/${lcase.id}/export`)
ok('approved, legal exports the case scope', ex.status === 200 && hasAll(ex.body.messages) && ex.body.messages.every((m) => m.channel_id === ch.id))
e = lastLog('case.export')
ok('logged with every exported id', e.case_id === lcase.id && e.target_ids.length === ex.body.messages.length)
ok('leads cannot export', (await raw(lead1.token, 'GET', `/admin/cases/${lcase.id}/export`)).status === 403)

console.log('-- closing')
await call(admin.token, 'PATCH', `/admin/reports/${rep.id}`, { status: 'resolved' })
ok('resolving the report closes its case', (await call(mod.token, 'GET', `/admin/cases/${r.case_id}`)).case.status === 'closed')
ok('closed cases give nothing', (await raw(mod.token, 'GET', `/admin/cases/${r.case_id}/context`)).status === 400)
await call(admin.token, 'PATCH', `/admin/reports/${rep.id}`, { status: 'open' })
ok('reopening reopens it', (await call(mod.token, 'GET', `/admin/cases/${r.case_id}`)).case.status === 'open')
const cl = await callS(legal.token, 'POST', `/admin/cases/${lcase.id}/close`)
ok('closing a case revokes its grants', cl.body.status === 'closed' && (await call(legal.token, 'GET', `/admin/cases/${lcase.id}`)).grants.every((x) => x.status === 'revoked'))

console.log('-- console')
const browser = await chromium.launch(); const errors = []
const page2 = async (u, path) => { const p = await browser.newPage({ viewport: { width: 1400, height: 900 } }); p.on('pageerror', (x) => errors.push(x.message)); await p.goto(`${WEB}/login`); await p.evaluate((t) => localStorage.setItem('parley.token', t), u.token); await p.goto(`${WEB}${path}`); return p }
let p = await page2(mod, `/admin/cases/${r.case_id}`)
await p.waitForSelector('[data-case-context-show]'); await p.click('[data-case-context-show]'); await p.waitForSelector('[data-case-context] [data-anchor="1"]')
ok('the case page shows the context with the reported message marked', (await p.locator('[data-case-context] [data-case-msg]').count()) === 41 && (await p.textContent('[data-anchor="1"]')).includes(`line 25 ${S}`))
await p.click('[data-case-request]'); await p.fill('[data-case-request-why]', 'see what led up to it'); await p.click('[data-case-request-go]')
await p.waitForSelector('[data-case-grant][data-grant-status="pending"]')
ok('and asks for more', (await p.locator('[data-case-grant][data-grant-status="pending"] [data-grant-approve]').count()) === 0)
await p.close()
p = await page2(lead2, '/admin/cases')
await p.waitForSelector('[data-case-pending-grant]'); await p.goto(`${WEB}/admin/cases/${r.case_id}`)
await p.waitForSelector('[data-grant-status="pending"] [data-grant-approve]'); await p.click('[data-grant-status="pending"] [data-grant-approve]')
await p.waitForSelector('[data-case-grant][data-grant-status="approved"]')
ok('another lead approves from the queue', true); await p.close()
p = await page2(mod, `/admin/cases/${r.case_id}`)
await p.waitForSelector(`[data-case-scope="${ch.id}"]`); await p.click(`[data-case-scope="${ch.id}"]`)
await p.waitForSelector('[data-case-reading] [data-case-msg]')
ok('the moderator then reads the channel', (await p.locator('[data-case-reading] [data-case-msg]').count()) >= 50); await p.close()
p = await page2(mod, '/admin/reports')
await p.waitForSelector(`[data-admin-report="${rep.id}"] [data-report-case]`)
ok('reports link to their case', true); await p.close()
ok('no page errors', errors.length === 0, errors.join(' | '))
await browser.close()
await call(a.token, 'DELETE', `/guilds/${g.id}`)
await finish()
