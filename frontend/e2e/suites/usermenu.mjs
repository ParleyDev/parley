// The user menu (Discord's layout) and the profile editor: the menu shows your card with a status bubble, bio and
// reviews, then Edit Profile, a status flyout (with notes and durations), Badges, Switch Accounts and Copy User ID.
// Edit Profile, Badges, Settings → Profiles and the user context menu all open one editor: tiles open pickers,
// the card edits in place, About Me/Activity/Wishlist/Games sit on the right, Escape closes a picker then the editor.
import { chromium } from 'playwright'
import { WEB, S, reg, call, ok, finish } from '../lib.mjs'
const a = await reg('alice')
await call(a.token, 'PATCH', '/users/@me', { bio: `Hello from ${S}`, pronouns: 'she/her', theme_primary: '#5b2a86', theme_accent: '#b03060' })
const g = await call(a.token, 'POST', '/guilds', { name: `Menu ${S}` })
const browser = await chromium.launch(); const errors = []
const ctx = await browser.newContext({ viewport: { width: 1400, height: 900 }, permissions: ['clipboard-read', 'clipboard-write'] })
const p = await ctx.newPage(); p.on('pageerror', (e) => errors.push(e.message))
await p.goto(`${WEB}/login`); await p.evaluate((t) => localStorage.setItem('parley.token', t), a.token)
await p.goto(`${WEB}/channels/@me`); await p.waitForSelector('[data-panel-self]'); await p.waitForTimeout(800)

console.log('-- the menu')
await p.click('[data-panel-self]'); await p.waitForSelector('[data-user-menu]')
const menu = p.locator('[data-user-menu]')
ok('your card: name, username, pronouns and bio', (await menu.innerText()).includes('she/her') && (await menu.locator('[data-user-menu-bio]').innerText()).includes(`Hello from ${S}`))
ok('a status bubble to set your custom status', await menu.locator('[data-set-status]').innerText().then((x) => x.includes("hot take")))
ok('user reviews', (await menu.locator('[data-user-menu-reviews]').innerText()).includes('No reviews yet'))
ok('then Edit Profile, status, Badges, Switch Accounts, Copy User ID', await menu.locator('[data-user-menu-edit]').count() === 1 && await menu.locator('[data-status-menu]').count() === 1 && await menu.locator('[data-user-menu-badges]').count() === 1 && await menu.locator('[data-switch-accounts]').count() === 1 && await menu.locator('[data-copy-user-id]').count() === 1)
await p.hover('[data-status-menu]'); await p.waitForSelector('[data-status-option="dnd"]')
ok('the status flyout explains Do Not Disturb and Invisible', (await p.locator('[data-status-option="dnd"]').innerText()).includes('desktop notifications') && (await p.locator('[data-status-option="invisible"]').innerText()).includes('appear offline'))
await p.hover('[data-status-option="idle"]'); await p.waitForSelector('[data-status-duration-list="idle"]')
ok('hovering a status offers durations', await p.locator('[data-status-duration-list="idle"] [data-status-for]').count() === 5)
await p.click('[data-status-option="dnd"]')
await p.waitForFunction(() => !document.querySelector('[data-user-menu]'))
ok('picking one sets it and closes the menu', await (async () => { for (let i = 0; i < 20; i++) { if ((await call(a.token, 'GET', '/users/@me')).status === 'dnd') return true; await new Promise((r) => setTimeout(r, 150)) } return false })())
await p.click('[data-panel-self]'); await p.hover('[data-switch-accounts]'); await p.waitForSelector('[data-account-switcher]')
ok('Switch Accounts lists accounts and Manage Accounts', await p.locator('[data-account-row]').count() >= 1 && await p.locator('[data-manage-accounts]').count() === 1)
await p.click('[data-copy-user-id]'); await p.waitForTimeout(300)
ok('Copy User ID copies it', await p.evaluate(() => navigator.clipboard.readText()) === a.user.id)

console.log('-- the editor')
await p.click('[data-panel-self]'); await p.click('[data-user-menu-edit]'); await p.waitForSelector('[data-profile-editor]')
ok('Edit Profile opens the editor with its tiles and a live card', await p.locator('[data-editor-section]').count() >= 9 && await p.locator('[data-profile-editor] [data-profile-card]').count() === 1)
ok('About Me, Activity, Wishlist and Games on the right', await p.locator('[data-editor-tab]').count() === 4)
await p.click('[data-editor-section="effect"]'); await p.waitForSelector('[data-editor-panel="effect"]')
await p.click('[data-effect-option="snow"]')
ok('a picker changes the preview', await p.locator('[data-profile-editor] [data-profile-effect="snow"]').count() === 1)
await p.keyboard.press('Escape'); await p.waitForTimeout(200)
ok('Escape closes the picker first', await p.locator('[data-editor-panel]').count() === 0 && await p.locator('[data-profile-editor]').count() === 1)
await p.click('[data-editor-tab="about"]'); await p.fill('[data-bio-input]', `New bio ${S}`)
ok('changes wait for Save', await p.locator('[data-editor-savebar]').count() === 1)
await p.click('[data-editor-savebar] button:has-text("Save Changes")'); await p.waitForSelector('text=Profile saved')
const me = await call(a.token, 'GET', '/users/@me')
ok('Save keeps them', me.bio === `New bio ${S}` && me.profile_effect === 'snow' && await p.locator('[data-editor-savebar]').count() === 0)
await p.keyboard.press('Escape')
ok('and Escape closes the editor', await p.waitForFunction(() => !document.querySelector('[data-profile-editor]')).then(() => true))

console.log('-- one editor everywhere')
await p.click('[data-panel-self]'); await p.click('[data-user-menu-badges]'); await p.waitForSelector('[data-profile-editor]')
ok('Badges opens it too', true)
await p.keyboard.press('Escape'); await p.waitForTimeout(200)
await p.click('button[title="User Settings"]'); await p.click('[data-settings-tab="profile"]'); await p.waitForSelector('[data-profiles-tab]')
ok('Settings → Profiles no longer duplicates the fields', await p.locator('[data-profiles-tab] [data-bio-input], [data-profiles-tab] [data-decoration-options]').count() === 0)
ok('and lists server profiles', await p.locator(`[data-profiles-tab] [data-server-profile="${g.id}"]`).count() === 1)
await p.click('[data-open-profile-editor]'); await p.waitForSelector('[data-profile-editor]')
ok('its Edit Profile opens the same editor', await p.locator('[data-editor-section]').count() >= 9)
await p.keyboard.press('Escape')

console.log('-- phones')
const m = await (await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true })).newPage(); m.on('pageerror', (e) => errors.push(e.message))
await m.goto(`${WEB}/login`); await m.evaluate((t) => localStorage.setItem('parley.token', t), a.token)
await m.goto(`${WEB}/channels/@me`); await m.waitForSelector('[data-panel-self]'); await m.waitForTimeout(800)
await m.click('[data-panel-self]'); await m.waitForSelector('[data-user-menu]')
ok('phone: the menu fits the screen', await m.evaluate(() => { const r = document.querySelector('[data-user-menu]').getBoundingClientRect(); return r.left >= 0 && r.right <= innerWidth }))
await m.click('[data-user-menu-edit]'); await m.waitForSelector('[data-profile-editor]')
ok('phone: the editor fills the screen without sideways scrolling', await m.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
ok('no page errors', errors.length === 0, errors.join(' | '))
await call(a.token, 'DELETE', `/guilds/${g.id}`, { password: 'password1', name: g.name })
await browser.close(); await finish()
