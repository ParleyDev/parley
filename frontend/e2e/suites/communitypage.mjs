// A community's page: header, formatted about, safe links, channels, counts and managers; following from it; live
// updates and deletion while it is open; a community the member cannot view is simply not found.
import { chromium } from 'playwright'
import { WEB, S, reg, call, raw, ok, finish, pngFile } from '../lib.mjs'

const a = await reg('alice'), b = await reg('bob'), c = await reg('carol')
const g = await call(a.token, 'POST', '/guilds', { name: `Comm Page ${S}` })
const inv = await call(a.token, 'POST', `/guilds/${g.id}/invites`, {})
await call(b.token, 'POST', `/invites/${inv.code}`); await call(c.token, 'POST', `/invites/${inv.code}`)
const base = `/guilds/${g.id}/communities`
const metal = await call(a.token, 'POST', base, { slug: 'metal', name: 'Metal', description: 'Loud music' })
await call(a.token, 'PATCH', `${base}/metal`, {
  about: 'Welcome to **metal**. <img src=x onerror="window.__x=1">',
  links: [{ label: 'Home', url: 'https://www.example.com/a' }, { label: 'Docs', url: 'http://docs.example.org/b' }],
})
const hid = await call(a.token, 'POST', base, { slug: 'hidden', name: 'Hidden' })
await call(a.token, 'PUT', `/channels/${hid.category_id}/permissions/${g.id}`, { kind: 'role', allow: 0, deny: 1024 })
await call(a.token, 'POST', base, { slug: 'bare', name: 'Bare', channels: [] })
await call(a.token, 'PUT', `${base}/metal/managers/${c.user.id}`, { kind: 'member' })
await call(a.token, 'POST', `/channels/${metal.channel_ids[0]}/messages`, { content: 'first post here' })

const browser = await chromium.launch(); const errors = []
const p = await browser.newPage({ viewport: { width: 1440, height: 900 } }); p.on('pageerror', (e) => errors.push(e.message))
await p.goto(`${WEB}/login`); await p.evaluate((t) => localStorage.setItem('parley.token', t), b.token)

console.log('-- viewing')
await p.goto(`${WEB}/channels/${g.id}/c/metal`)
await p.waitForSelector('[data-community-page="metal"]')
ok('name and description shown', (await p.textContent('[data-community-page]')).includes('Metal') && (await p.textContent('[data-community-page]')).includes('Loud music'))
ok('a tinted band stands in for a missing header image', (await p.locator('[data-community-banner]').count()) === 1)
ok('about is formatted, not raw html', (await p.locator('[data-community-about] strong').count()) === 1 && (await p.locator('[data-community-about] img').count()) === 0 && (await p.evaluate(() => window.__x)) === undefined)
ok('link shows label and host, opens safely', await p.$eval('[data-community-link]', (a) => a.textContent.includes('example.com') && a.target === '_blank' && a.rel.includes('noopener')))
ok('every link is listed', (await p.locator('[data-community-link]').count()) === 2)
ok('channels listed', (await p.locator('[data-community-channel]').count()) === 1)
ok('manager listed', (await p.textContent('[data-community-managers]')).includes('Carol'))
ok('not following by just opening', (await p.textContent('[data-community-follow]')).trim() === 'Follow' && !(await call(b.token, 'GET', `${base}/metal`)).following)
await p.click('[data-community-follow]')
await p.waitForFunction(() => document.querySelector('[data-community-follow]').textContent.trim() === 'Following')
// The follow request is sent after the optimistic click: give it a moment to land before asking the API.
let followed = false
for (let i = 0; i < 20 && !followed; i++) { followed = (await call(b.token, 'GET', `${base}/metal`)).following === true; if (!followed) await p.waitForTimeout(100) }
ok('follow from the page', followed)
ok('the followed community shows in the sidebar', (await p.locator('[data-community="metal"]').count()) === 1)

console.log('-- phone width')
await p.setViewportSize({ width: 390, height: 800 })
ok('no sideways scroll', await p.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth))
await p.setViewportSize({ width: 1440, height: 900 })

console.log('-- opening a channel')
await p.click('[data-community-channel]'); await p.waitForURL(new RegExp(`/channels/${g.id}/[0-9a-f-]{36}`))
ok('channel row opens the channel', /[0-9a-f-]{36}$/.test(new URL(p.url()).pathname))

console.log('-- not found')
await p.goto(`${WEB}/channels/${g.id}/c/hidden`); await p.waitForSelector('[data-community-missing]')
ok('hidden community is not found', (await p.locator('[data-community-page]').count()) === 0)
ok('and says nothing about it', !(await p.textContent('[data-community-missing]')).includes('Hidden'))
await p.goto(`${WEB}/channels/${g.id}/c/nope`); await p.waitForSelector('[data-community-missing]')
ok('unknown address is not found', await p.isVisible('[data-community-missing]'))

console.log('-- a community with no channels, links, about or managers')
await p.goto(`${WEB}/channels/${g.id}/c/bare`); await p.waitForSelector('[data-community-page="bare"]')
ok('renders with nothing in it', (await p.locator('[data-community-channel]').count()) === 0 && (await p.locator('[data-community-link]').count()) === 0 && (await p.locator('[data-community-managers]').count()) === 0)

console.log('-- live updates')
await p.goto(`${WEB}/channels/${g.id}/c/metal`); await p.waitForSelector('[data-community-page="metal"]')
await call(a.token, 'PATCH', `${base}/metal`, { description: 'Louder music' })
await p.waitForFunction(() => document.querySelector('[data-community-page]')?.textContent?.includes('Louder music'), null, { timeout: 8000 }).catch(() => {})
ok('a description change shows without reload', (await p.textContent('[data-community-page]')).includes('Louder music'))
await call(a.token, 'DELETE', `${base}/metal`)
await p.waitForSelector('[data-community-missing]', { timeout: 8000 }).catch(() => {})
ok('deleting it while open shows the not-found state', (await p.locator('[data-community-missing]').count()) === 1)

console.log('-- follow prompt links to the page')
const two = await call(a.token, 'POST', base, { slug: 'jazz', name: 'Jazz' })
await p.goto(`${WEB}/channels/${g.id}/${two.channel_ids[0]}`)
await p.waitForSelector('[data-community-about-link]')
await p.click('[data-community-about-link]')
await p.waitForSelector('[data-community-page="jazz"]')
ok('About this community leads to the page', p.url().endsWith(`/channels/${g.id}/c/jazz`))

console.log('-- editing as a manager')
await call(a.token, 'POST', base, { slug: 'forge', name: 'Forge', description: 'Before' })
await call(a.token, 'PUT', `${base}/forge/managers/${c.user.id}`, { kind: 'member' })
const asUser = async (u, w = 1440, h = 900) => { const pg = await browser.newPage({ viewport: { width: w, height: h } }); pg.on('pageerror', (e) => errors.push(e.message)); await pg.goto(`${WEB}/login`); await pg.evaluate((t) => localStorage.setItem('parley.token', t), u.token); return pg }
const cp = await asUser(c)
const patches = []
cp.on('request', (r) => { if (r.method() === 'PATCH' && r.url().includes('/communities/')) patches.push(r.postData()) })
await cp.goto(`${WEB}/channels/${g.id}/c/forge`); await cp.waitForSelector('[data-community-page="forge"]')
ok('a manager sees Edit and Add channel', (await cp.locator('[data-community-edit]').count()) === 1 && (await cp.locator('[data-community-add-channel]').count()) === 1)
ok('a manager does not see Delete or Add for managers', (await cp.locator('[data-community-delete]').count()) === 0 && (await cp.locator('[data-manager-add]').count()) === 0)
const bp = await asUser(b)
await bp.goto(`${WEB}/channels/${g.id}/c/forge`); await bp.waitForSelector('[data-community-page="forge"]')
ok('a plain member sees no Edit and no Add channel', (await bp.locator('[data-community-edit]').count()) === 0 && (await bp.locator('[data-community-add-channel]').count()) === 0)
await bp.close()

await cp.click('[data-community-edit]'); await cp.waitForSelector('[data-community-editing]')
ok('edit mode shows the bar and fields, and no Delete for a manager', (await cp.textContent('[data-community-editing]')).includes('Editing this page.') && (await cp.locator('[data-edit-name]').count()) === 1 && (await cp.locator('[data-community-delete]').count()) === 0)
await cp.click('[data-community-save]'); await cp.waitForSelector('[data-community-editing]', { state: 'detached' })
ok('Save with nothing changed sends no request', patches.length === 0)
await cp.click('[data-community-edit]'); await cp.waitForSelector('[data-community-editing]')
await cp.fill('[data-edit-description]', 'Heavier'); await cp.fill('[data-edit-about]', 'About **forge**')
await cp.click('[data-edit-link-add]')
await cp.locator('[data-edit-link-label]').last().fill('Site'); await cp.locator('[data-edit-link-url]').last().fill('https://example.com/forge')
await cp.dblclick('[data-community-save]'); await cp.waitForSelector('[data-community-editing]', { state: 'detached' })
ok('a double-clicked Save sends one request with only the changed fields', patches.length === 1 && Object.keys(JSON.parse(patches[0])).sort().join() === 'about,description,links', patches.join('|'))
ok('the page shows the new values', (await cp.textContent('[data-community-page]')).includes('Heavier') && (await cp.locator('[data-community-about] strong').count()) === 1 && (await cp.locator('[data-community-link]').count()) === 1)
const after = await call(c.token, 'GET', `${base}/forge`)
ok('the server has them', after.description === 'Heavier' && after.about === 'About **forge**' && after.links.length === 1 && after.links[0].label === 'Site')

patches.length = 0
await cp.click('[data-community-edit]'); await cp.waitForSelector('[data-community-editing]')
await cp.click('[data-edit-link-add]')
await cp.locator('[data-edit-link-label]').last().fill('Bad'); await cp.locator('[data-edit-link-url]').last().fill('javascript:alert(1)')
await cp.click('[data-community-save]')
ok('an invalid link shows an error under it and sends nothing', (await cp.locator('[data-edit-link]').last().textContent()).includes('web address') && patches.length === 0)
await cp.click('[data-community-cancel]')
await cp.waitForSelector('[role=dialog]')
ok('cancelling with unsaved changes asks to discard', (await cp.textContent('[role=dialog]')).includes('Discard your changes?'))
await cp.click('[role=dialog] button:has-text("Cancel")'); await cp.waitForSelector('[role=dialog]', { state: 'detached' })
ok('keeping the changes stays in edit mode', (await cp.locator('[data-community-editing]').count()) === 1)
await cp.click('[data-community-channel]')
await cp.waitForSelector('[role=dialog]').catch(() => {})
ok('leaving for a channel asks too and stays when declined', (await cp.locator('[role=dialog]').count()) === 1 && new URL(cp.url()).pathname.endsWith('/c/forge'))
await cp.click('[role=dialog] button:has-text("Cancel")'); await cp.waitForSelector('[role=dialog]', { state: 'detached' })
await cp.click('[data-community-cancel]'); await cp.waitForSelector('[role=dialog]')
await cp.click('[role=dialog] button:has-text("Discard")'); await cp.waitForSelector('[data-community-editing]', { state: 'detached' })
ok('discarding leaves edit mode with the saved values', (await cp.locator('[data-community-link]').count()) === 1)

console.log('-- address change, channels, header image')
await cp.click('[data-community-edit]'); await cp.waitForSelector('[data-community-editing]')
await cp.fill('[data-edit-slug]', 'heavy')
await cp.setInputFiles('[data-edit-banner] input[type=file]', pngFile)
await cp.click('[data-crop-apply]'); await cp.waitForSelector('[data-crop-dialog]', { state: 'detached' })
await cp.waitForSelector('[data-edit-banner] img') // the upload finishes after the cropper closes
await cp.click('[data-community-save]')
await cp.waitForURL(new RegExp(`/channels/${g.id}/c/heavy$`)); await cp.waitForSelector('[data-community-page="heavy"]')
ok('the address changed in the URL', cp.url().endsWith(`/channels/${g.id}/c/heavy`))
ok('the header image shows', (await cp.locator('[data-community-banner] img').count()) === 1 || /url\(/.test(await cp.$eval('[data-community-banner]', (e) => getComputedStyle(e).backgroundImage)))
ok('and is saved', !!(await call(c.token, 'GET', `${base}/heavy`)).banner_url)
await cp.goto(`${WEB}/channels/${g.id}/c/forge`); await cp.waitForSelector('[data-community-missing]')
ok('the old address is not found', (await cp.locator('[data-community-missing]').count()) === 1)
await cp.goto(`${WEB}/channels/${g.id}/c/heavy`); await cp.waitForSelector('[data-community-page="heavy"]')
const rowsBefore = await cp.locator('[data-community-channel]').count()
await cp.click('[data-community-add-channel]'); await cp.waitForSelector('[data-channel-name]')
await cp.fill('[data-channel-name]', 'new-forge-chat'); await cp.click('[role=dialog] button:has-text("Create Channel")')
await cp.waitForFunction((n) => document.querySelectorAll('[data-community-channel]').length === n + 1, rowsBefore, { timeout: 8000 }).catch(() => {})
ok('a channel added from the page appears in its list and the page stays', (await cp.locator('[data-community-channel]').count()) === rowsBefore + 1 && cp.url().endsWith('/c/heavy'))

console.log('-- managers')
const ap = await asUser(a)
await ap.goto(`${WEB}/channels/${g.id}/c/heavy`); await ap.waitForSelector('[data-manager-add]')
await ap.click('[data-manager-add]'); await ap.fill('[data-manager-pick]', 'Bob')
await ap.click(`[data-manager-option="${b.user.id}"]`)
await ap.waitForSelector(`[data-manager-remove="${b.user.id}"]`)
ok('an owner appoints a manager from the picker', (await ap.textContent('[data-community-managers]')).includes('Bob') && (await call(a.token, 'GET', `${base}/heavy/managers`)).members.some((m) => m.id === b.user.id))
await ap.click(`[data-manager-remove="${b.user.id}"]`)
await ap.waitForSelector(`[data-manager-remove="${b.user.id}"]`, { state: 'detached' })
ok('and removes one', !(await call(a.token, 'GET', `${base}/heavy/managers`)).members.some((m) => m.id === b.user.id))

console.log('-- losing the right while editing')
await cp.click('[data-community-edit]'); await cp.waitForSelector('[data-community-editing]')
await call(a.token, 'DELETE', `${base}/heavy/managers/${c.user.id}`)
await cp.waitForSelector('[data-community-editing]', { state: 'detached', timeout: 8000 }).catch(() => {})
ok('edit mode closes with a notice when the member loses the right', (await cp.locator('[data-community-editing]').count()) === 0 && (await cp.locator('[data-community-notice]').count()) === 1 && (await cp.locator('[data-community-edit]').count()) === 0)

console.log('-- deleting')
await ap.click('[data-community-edit]'); await ap.waitForSelector('[data-community-editing]')
await ap.click('[data-community-delete]'); await ap.waitForSelector('[data-community-delete-confirm]')
ok('the confirmation names the community and its channels', (await ap.textContent('[data-community-editing]')).includes('Delete Forge and its'))
await ap.click('[data-community-delete-confirm]')
await ap.waitForURL(new RegExp(`/channels/${g.id}/[0-9a-f-]{36}$`))
ok('deleting lands on a channel of the server', true)
ok('and the community is gone', (await raw(a.token, 'GET', `${base}/heavy`)).status === 404)
await cp.close(); await ap.close()

console.log('-- edit mode at phone width')
const ten = Array.from({ length: 10 }, (_, i) => ({ label: `Link ${i}`, url: `https://example.com/${i}` }))
await call(a.token, 'POST', base, { slug: 'wide', name: 'Wide', about: 'long text '.repeat(300), links: ten })
const pp = await asUser(a, 390, 800)
await pp.goto(`${WEB}/channels/${g.id}/c/wide`); await pp.waitForSelector('[data-community-edit]'); await pp.click('[data-community-edit]'); await pp.waitForSelector('[data-community-editing]')
ok('edit mode has no sideways scroll with ten links and a long About', await pp.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth) && (await pp.locator('[data-edit-link]').count()) === 10)
await pp.close()

ok('no page errors', errors.length === 0, errors.join('\n'))
await browser.close(); await finish()
