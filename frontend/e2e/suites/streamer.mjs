// Streamer Mode (hide info, blur invites, mute sounds/notifications, keybind) and Advanced (developer mode, logs).
import { chromium } from 'playwright'
import { WEB, S, reg, call, ok, finish } from '../lib.mjs'
const a = await reg('alice'); const b = await reg('bob')
await call(a.token, 'POST', '/users/@me/relationships', { user_id: b.user.id }); await call(b.token, 'PUT', `/users/@me/relationships/${a.user.id}`)
const g = await call(a.token, 'POST', '/guilds', { name: `Stream ${S}` }); const tc = g.channels.find((x) => x.kind === 'text')
const inv = await call(a.token, 'POST', `/guilds/${g.id}/invites`, {}); await call(b.token, 'POST', `/invites/${inv.code}`)
const pub = (await call(a.token, 'GET', '/instance')).app_url
const im = await call(a.token, 'POST', `/channels/${tc.id}/messages`, { content: `join here ${pub}/invite/${inv.code}` })
const dm = await call(a.token, 'POST', '/users/@me/channels', { recipient_id: b.user.id })
const browser = await chromium.launch(); const errors = []
const ctx = await browser.newContext({ viewport: { width: 1280, height: 800 } }); const p = await ctx.newPage(); p.on('pageerror', (e) => errors.push(e.message))
await p.goto(`${WEB}/login`); await p.evaluate((t) => localStorage.setItem('parley.token', t), b.token)
await p.evaluate(() => localStorage.setItem('parley.prefs', JSON.stringify({ streamer: true })))
await p.goto(`${WEB}/channels/${g.id}/${tc.id}`); await p.waitForSelector(`[data-msg-id="${im.id}"]`)

console.log('-- streamer mode')
ok('the banner shows while Streamer Mode is on', await p.locator('[data-streamer-banner]').count() === 1)
ok('invite links in chat are blurred', (await p.locator(`[data-msg-id="${im.id}"] a[href*="/invite/"]`).first().evaluate((el) => getComputedStyle(el).filter)).includes('blur'))
await p.evaluate(() => { window.__parleySfx = [] }); await p.goto(`${WEB}/channels/@me`); await p.waitForSelector('[data-user-panel-bar]')
await call(a.token, 'POST', `/channels/${dm.id}/messages`, { content: 'quiet please' }); await p.waitForTimeout(800)
ok('sounds are muted', (await p.evaluate(() => window.__parleySfx ?? [])).length === 0)
await p.click('button[title="User Settings"]'); await p.waitForSelector('[data-account-row="email"]')
ok('the email is hidden in My Account', await p.locator('[data-account-value="email"] [data-streamer-masked]').count() === 1 && !(await p.textContent('[data-account-value="email"]')).includes(`bob${S}@x.io`))
await p.locator('button', { hasText: /^Streamer Mode$/ }).first().click(); await p.waitForSelector('[data-streamer-tab]')
await p.locator('[data-streamer-toggle] [role=switch]').click(); await p.waitForFunction(() => !document.querySelector('[data-streamer-banner]'))
ok('the tab switch turns it off (banner gone)', true)
await p.keyboard.press('Escape'); await p.keyboard.press('Control+Shift+X'); await p.waitForSelector('[data-streamer-banner]')
ok('the keybind turns it back on', true)
await p.click('[data-streamer-off]'); await p.waitForFunction(() => !document.querySelector('[data-streamer-banner]'))
ok('the banner\'s Turn off works', true)

console.log('-- advanced')
await p.goto(`${WEB}/channels/${g.id}/${tc.id}`); await p.waitForSelector(`[data-msg-id="${im.id}"]`)
await p.locator(`[data-msg-id="${im.id}"] [data-msg-header]`).click({ button: 'right' }); await p.waitForSelector('text=Copy Message ID')
ok('Developer Mode (default on) offers Copy Message ID', true); await p.keyboard.press('Escape')
await p.click('button[title="User Settings"]'); await p.click('text=Advanced'); await p.waitForSelector('[data-advanced-tab]')
await p.locator('[data-developer-mode] [role=switch]').click(); await p.locator('[data-debug-logging] [role=switch]').click()
const [dl] = await Promise.all([p.waitForEvent('download'), p.click('[data-download-logs]')])
const text = await (await import('node:fs/promises')).readFile(await dl.path(), 'utf8')
ok('Download logs produces a text file with the header and the debug toggle entry', /parley client logs/.test(text) && /debug logging on/.test(text), text.slice(0, 120))
await p.keyboard.press('Escape'); await p.locator(`[data-msg-id="${im.id}"] [data-msg-header]`).click({ button: 'right' }); await p.waitForSelector('text=Copy Text')
ok('with Developer Mode off, Copy Message ID is gone', await p.locator('text=Copy Message ID').count() === 0)
await p.keyboard.press('Escape')
ok('no page errors', errors.length === 0, errors.join('\n'))
await browser.close(); await finish()
