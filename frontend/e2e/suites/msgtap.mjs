// Phones: tapping a message opens its action bar; only one is open at a time, and tapping anywhere else closes it.
import { chromium } from 'playwright'
import { WEB, S, reg, call, ok, finish } from '../lib.mjs'
const a = await reg('alice')
const g = await call(a.token, 'POST', '/guilds', { name: `Tap Land ${S}` })
const ch = g.channels.find((c) => c.kind === 'text')
const ids = []
for (const t of ['first message', 'second message', 'third message']) ids.push((await call(a.token, 'POST', `/channels/${ch.id}/messages`, { content: t })).id)
const browser = await chromium.launch()
const errors = []
const p = await (await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true })).newPage()
p.on('pageerror', (e) => errors.push(e.message))
await p.goto(`${WEB}/login`); await p.evaluate((t) => localStorage.setItem('parley.token', t), a.token)
await p.goto(`${WEB}/channels/${g.id}/${ch.id}`); await p.waitForSelector(`[data-msg-id="${ids[2]}"]`); await p.waitForTimeout(600)
const bar = (id) => p.locator(`[data-msg-id="${id}"] button[title="Reply"]`)
const open = async () => { const r = []; for (const id of ids) r.push(await bar(id).isVisible()); return r }
const body = (id) => ({ tap: () => p.locator(`[data-msg-id="${id}"] .msg-content`).first().tap({ position: { x: 4, y: 6 } }) })

await body(ids[0]).tap(); await p.waitForTimeout(200)
ok('tapping a message opens its bar', JSON.stringify(await open()) === '[true,false,false]', JSON.stringify(await open()))
await body(ids[1]).tap(); await p.waitForTimeout(200)
ok('tapping another moves the bar there', JSON.stringify(await open()) === '[false,true,false]', JSON.stringify(await open()))
await body(ids[1]).tap(); await p.waitForTimeout(200)
ok('tapping it again closes it', JSON.stringify(await open()) === '[false,false,false]')
await body(ids[2]).tap(); await p.waitForTimeout(200)
await p.locator('[data-composer] textarea, textarea').first().tap(); await p.waitForTimeout(200)
ok('tapping the composer closes it', JSON.stringify(await open()) === '[false,false,false]', JSON.stringify(await open()))
await body(ids[0]).tap(); await p.waitForTimeout(200)
await p.locator('text=This is the start of the').tap(); await p.waitForTimeout(200)
ok('tapping empty space in the chat closes it', JSON.stringify(await open()) === '[false,false,false]')
await body(ids[0]).tap(); await p.waitForTimeout(200)
await bar(ids[0]).tap(); await p.waitForTimeout(300)
ok('tapping a bar button keeps working (Reply)', (await p.locator('text=Replying to').count()) > 0)
await body(ids[2]).tap(); await p.waitForTimeout(200)
await p.locator(`[data-msg-id="${ids[2]}"] button[title="More"]`).tap(); await p.waitForTimeout(200)
ok('More menu opens from the bar', await p.locator('[data-msg-menu]').isVisible())
await p.locator('[data-msg-menu] [role=menuitem]:has-text("Copy Message ID")').tap(); await p.waitForTimeout(200)
ok('bar still there after a menu action, closes on the next outside tap', await bar(ids[2]).isVisible())
await body(ids[0]).tap(); await p.waitForTimeout(200)
ok('and only the new one is open', JSON.stringify(await open()) === '[true,false,false]', JSON.stringify(await open()))
ok('no page errors', errors.length === 0, errors.join(' | '))
await call(a.token, 'DELETE', `/guilds/${g.id}`)
await browser.close()
await finish()
