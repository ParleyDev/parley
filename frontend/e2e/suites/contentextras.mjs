// Content extras: text/code file previews with highlighting, PDF cards, inline YouTube/Spotify players and several
// embeds per message, and search extras (filter suggestions, during:, has:poll, sort order, result context).
import { chromium } from 'playwright'
import { WEB, S, reg, call, multi, ok, finish } from '../lib.mjs'
const a = await reg('alice'), b = await reg('bob')
const g = await call(a.token, 'POST', '/guilds', { name: `Content ${S}` })
const inv = await call(a.token, 'POST', `/guilds/${g.id}/invites`, {}); await call(b.token, 'POST', `/invites/${inv.code}`)
const ch = g.channels.find((x) => x.kind === 'text')
const up = async (name, mimeType, text) => (await (await multi(a.token, `/channels/${ch.id}/attachments`, { name, mimeType, buffer: Buffer.from(text) })).json())
const py = Array.from({ length: 30 }, (_, i) => `def f${i}(x):\n    return x + ${i}`).join('\n')
const code = await up('tools.py', 'text/x-python', py)
const pdf = await up('report.pdf', 'application/pdf', '%PDF-1.4\n1 0 obj << /Type /Catalog >> endobj\ntrailer << /Root 1 0 R >>\n%%EOF')
await call(a.token, 'POST', `/channels/${ch.id}/messages`, { content: 'files', attachment_ids: [code.id, pdf.id] })
await call(a.token, 'POST', `/channels/${ch.id}/messages`, { content: 'watch https://www.youtube.com/watch?v=dQw4w9WgXcQ and https://open.spotify.com/track/4cOdK2wGLETKBW3PvgPWqT' })
const browser = await chromium.launch(); const errors = []
const p = await (await browser.newContext({ viewport: { width: 1440, height: 900 } })).newPage(); p.on('pageerror', (e) => errors.push(e.message))
await p.goto(`${WEB}/login`); await p.evaluate((t) => localStorage.setItem('parley.token', t), a.token)
await p.goto(`${WEB}/channels/${g.id}/${ch.id}`); await p.waitForSelector('[data-composer-box] textarea'); await p.waitForTimeout(1500)

console.log('-- file previews')
const tp = p.locator(`[data-text-preview="${code.id}"]`)
ok('code files show a highlighted preview', await tp.count() === 1 && await tp.locator('code.hljs .hljs-keyword').count() > 0)
const collapsed = (await tp.locator('pre').innerText()).split('\n').length
await tp.locator('[data-text-preview-toggle]').click(); await p.waitForTimeout(200)
ok('expanding shows the rest', (await tp.locator('pre').innerText()).split('\n').length > collapsed)
ok('PDFs get a card that opens them', await p.locator(`[data-pdf-card="${pdf.id}"] [data-pdf-open]`).count() === 1)

console.log('-- embeds')
ok('YouTube links get a player card', await p.locator('[data-link-player-card="youtube"]').count() === 1)
ok('and Spotify a player, in the same message', await p.locator('[data-link-player="spotify"] iframe[src*="open.spotify.com/embed/track/4cOdK2wGLETKBW3PvgPWqT"]').count() === 1)
await p.click('[data-link-player-card="youtube"] [data-link-play]'); await p.waitForTimeout(300)
ok('Play swaps in the video', await p.locator('[data-link-player="youtube"] iframe[src*="youtube-nocookie.com/embed/dQw4w9WgXcQ"]').count() === 1)

console.log('-- search')
const m1 = await call(b.token, 'POST', `/channels/${ch.id}/messages`, { content: `zebra one ${S}` })
await call(b.token, 'POST', `/channels/${ch.id}/messages`, { content: 'in between' })
const m2 = await call(b.token, 'POST', `/channels/${ch.id}/messages`, { content: `zebra two ${S}` })
await call(b.token, 'POST', `/channels/${ch.id}/messages`, { content: '', poll: { question: `zebra poll ${S}`, options: ['a', 'b'], multi: false, duration_hours: 24 } })
await p.click('[data-search-input]'); await p.keyboard.type('fr'); await p.waitForTimeout(150)
ok('typing suggests filters', await p.locator('[data-search-suggestion="from:"]').count() === 1)
await p.keyboard.press('Tab'); await p.keyboard.type(b.user.username.slice(0, 3)); await p.waitForTimeout(150)
ok('and then people for from:', await p.locator(`[data-search-suggestion="from:${b.user.username}"]`).count() === 1)
await p.fill('[data-search-input]', ''); await p.keyboard.type(`zebra during:${new Date().toISOString().slice(0, 10)}`); await p.keyboard.press('Enter'); await p.waitForSelector('[data-search-total]')
await p.click('[data-search-scope="channel"]'); await p.waitForTimeout(800)
ok("during: finds today's messages", Number(await p.locator('[data-search-total]').innerText()) >= 2)
await p.selectOption('[data-search-sort]', 'oldest'); await p.waitForTimeout(800)
ok('Oldest puts the first match first', (await p.locator('[data-search-hit]').first().getAttribute('data-search-hit')) === m1.id)
await p.check('[data-search-context]'); await p.waitForTimeout(800)
ok('Context shows the neighbouring messages', await p.locator(`[data-search-hit="${m1.id}"] [data-search-context-line]`).count() >= 1 && /in between/.test(await p.locator(`[data-search-hit="${m2.id}"]`).innerText()))
const polls = await call(a.token, 'GET', `/search?q=has:poll&channel_id=${ch.id}`)
ok('has:poll finds polls only', polls.total === 1 && polls.results[0].poll)
ok('no page errors', errors.length === 0, errors.join(' | '))
await call(a.token, 'DELETE', `/guilds/${g.id}`, { password: 'password1', name: g.name })
await browser.close(); await finish()
