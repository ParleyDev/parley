// Server tools: drag roles to reorder, a role's Members tab with bulk add, View Server as Role, category permissions
// with a synced indicator and Sync Now, the public server widget, and an invite page background.
import { chromium } from 'playwright'
import { WEB, S, B, reg, call, raw, multi, pngFile, ok, finish } from '../lib.mjs'
const a = await reg('alice'), b = await reg('bob'), c = await reg('carol'), d = await reg('dave')
const g = await call(a.token, 'POST', '/guilds', { name: `Tools ${S}` })
const inv = await call(a.token, 'POST', `/guilds/${g.id}/invites`, { max_age: 0, max_uses: 0 })
for (const u of [b, c]) await call(u.token, 'POST', `/invites/${inv.code}`)
const general = g.channels.find((x) => x.kind === 'text')
const r1 = await call(a.token, 'POST', `/guilds/${g.id}/roles`, { name: `Alpha ${S}` })
const r2 = await call(a.token, 'POST', `/guilds/${g.id}/roles`, { name: `Beta ${S}` })
const secret = await call(a.token, 'POST', `/guilds/${g.id}/channels`, { name: 'staff-only', kind: 'text' })
await call(a.token, 'PUT', `/channels/${secret.id}/permissions/${g.id}`, { kind: 'role', allow: 0, deny: 1 << 10 })
await call(a.token, 'PUT', `/channels/${secret.id}/permissions/${r1.id}`, { kind: 'role', allow: 1 << 10, deny: 0 })
const cat = await call(a.token, 'POST', `/guilds/${g.id}/channels`, { name: 'Zone', kind: 'category' })
const child = await call(a.token, 'POST', `/guilds/${g.id}/channels`, { name: 'zone-chat', kind: 'text', parent_id: cat.id })
const browser = await chromium.launch(); const errors = []
const mk = async (tok, path) => {
  const ctx = await browser.newContext({ viewport: { width: 1280, height: 900 } })
  const p = await ctx.newPage(); p.on('pageerror', (e) => errors.push(e.message))
  await p.goto(`${WEB}/login`); if (tok) await p.evaluate((t) => localStorage.setItem('parley.token', t), tok)
  await p.goto(`${WEB}${path}`); await p.waitForTimeout(900)
  return p
}
const pa = await mk(a.token, `/channels/${g.id}/${general.id}`)
const openSettings = async (tab) => { await pa.locator(`button:has-text("Tools ${S}")`).first().click(); await pa.click('text=Server Settings'); await pa.click(`[data-settings-tab="${tab}"]`) }

console.log('-- roles')
await openSettings('roles'); await pa.waitForSelector(`[data-role-row="${r1.id}"]`)
const pos = async () => Object.fromEntries((await call(a.token, 'GET', `/guilds/${g.id}/roles`)).map((r) => [r.id, r.position]))
let before = await pos()
await pa.dragAndDrop(`[data-role-row="${r1.id}"]`, `[data-role-row="${r2.id}"]`); await pa.waitForTimeout(800)
let after = await pos()
ok('dragging a role onto another moves it there', Math.sign(before[r1.id] - before[r2.id]) === -Math.sign(after[r1.id] - after[r2.id]) && after[r1.id] !== after[r2.id], JSON.stringify({ before, after }))
await pa.click(`[data-role-row="${r2.id}"]`); await pa.click('[data-role-pane="members"]'); await pa.waitForSelector('[data-role-members]')
await pa.click('[data-role-add-members]'); await pa.waitForSelector(`[data-role-add-option="${b.user.id}"]`)
await pa.click(`[data-role-add-option="${b.user.id}"] input`); await pa.click(`[data-role-add-option="${c.user.id}"] input`); await pa.click('[data-role-add-confirm]'); await pa.waitForTimeout(1200)
let rm = await call(a.token, 'GET', `/guilds/${g.id}/roles/${r2.id}/members`)
ok('Add Members gives the role to everyone picked', [b.user.id, c.user.id].every((id) => rm.some((x) => x.id === id)))
await pa.click(`[data-role-member-remove="${c.user.id}"]`); await pa.waitForTimeout(800)
rm = await call(a.token, 'GET', `/guilds/${g.id}/roles/${r2.id}/members`)
ok('and the Members tab can take it away', rm.length === 1 && rm[0].id === b.user.id)

console.log('-- view as role')
await pa.click('[data-role-pane="display"]'); await pa.click(`[data-role-row="${g.id}"]`); await pa.click('[data-role-view-as]'); await pa.waitForTimeout(500)
ok('viewing as @everyone hides channels it cannot see', await pa.locator(`[data-channel-item="${secret.id}"]`).count() === 0 && await pa.locator('[data-view-as]').count() === 1)
await pa.click('[data-view-as-exit]'); await pa.waitForTimeout(300)
ok('Back shows everything again', await pa.locator(`[data-channel-item="${secret.id}"]`).count() === 1)

console.log('-- category permissions')
await call(a.token, 'PUT', `/channels/${child.id}/permissions/${r1.id}`, { kind: 'role', allow: 1 << 11, deny: 0 }); await pa.waitForTimeout(500)
await pa.locator(`[data-channel-item="${child.id}"] a`).click({ button: 'right' }); await pa.click('[data-menu-item="Edit Channel"]')
await pa.click('[data-settings-tab="permissions"]'); await pa.waitForSelector('[data-perm-sync]')
ok('a channel with its own permissions says it is not synced', (await pa.getAttribute('[data-perm-sync]', 'data-perm-sync')) === 'unsynced')
await pa.click('[data-perm-sync-now]'); await pa.waitForTimeout(800)
ok('Sync Now makes it follow the category again', (await pa.getAttribute('[data-perm-sync]', 'data-perm-sync')) === 'synced')
ok('sync needs a category', (await raw(a.token, 'POST', `/channels/${general.id}/permissions-sync`)).status === 400)
ok('and Manage Roles', (await raw(b.token, 'POST', `/channels/${child.id}/permissions-sync`)).status === 403)
await pa.keyboard.press('Escape'); await pa.waitForTimeout(300)

console.log('-- widget and invite splash')
ok('a widget is private until turned on', (await fetch(`${B}/guilds/${g.id}/widget.json`)).status === 403)
await openSettings('widget'); await pa.waitForSelector('[data-widget-tab]')
await pa.click('[data-widget-enabled]'); await pa.waitForTimeout(500); await pa.selectOption('[data-widget-invite]', inv.code); await pa.waitForTimeout(500)
const w = await (await fetch(`${B}/guilds/${g.id}/widget.json`)).json()
ok('the widget JSON needs no login and lists who is online', w.name === `Tools ${S}` && w.presence_count >= 1 && w.members.some((m) => m.id === a.user.id) && w.instant_invite === `/invite/${inv.code}`, JSON.stringify(w).slice(0, 200))
ok("the widget invite must be one of the server's", (await raw(a.token, 'PATCH', `/guilds/${g.id}`, { widget_invite: 'nope123' })).status === 400)
const anon = await mk(null, `/widget/${g.id}`)
ok('the embeddable widget page shows the server and a Join button', (await anon.locator('[data-widget-name]').innerText()) === `Tools ${S}` && await anon.locator('[data-widget-join]').count() === 1)
const img = await (await multi(a.token, '/images?kind=banner', pngFile)).json()
await call(a.token, 'PATCH', `/guilds/${g.id}`, { invite_splash_url: img.url })
const pd = await mk(d.token, `/invite/${inv.code}`)
ok('the invite page shows the server background', await pd.locator('[data-invite-splash="1"]').count() === 1)
ok('no page errors', errors.length === 0, errors.join(' | '))
await call(a.token, 'DELETE', `/guilds/${g.id}`, { password: 'password1', name: g.name })
await browser.close(); await finish()
