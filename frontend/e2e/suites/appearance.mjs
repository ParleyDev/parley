import { chromium } from 'playwright'
import { WEB, S, reg, call, ok, finish } from '../lib.mjs'

const a = await reg('alice')
const g = await call(a.token, 'POST', '/guilds', { name: `Looks ${S}` })
const tc = (await call(a.token, 'GET', `/guilds/${g.id}/channels`)).find((x) => x.kind === 'text')
await call(a.token, 'POST', `/channels/${tc.id}/messages`, { content: 'first message' })
await call(a.token, 'POST', `/channels/${tc.id}/messages`, { content: 'second message' })

const browser = await chromium.launch(); const errors = []
const p = await browser.newPage({ viewport: { width: 1440, height: 900 }, colorScheme: 'light' }); p.on('pageerror', (e) => errors.push(e.message))
await p.goto(`${WEB}/login`, { waitUntil: 'networkidle' }); await p.evaluate((t) => localStorage.setItem('parley.token', t), a.token)
await p.goto(`${WEB}/channels/${g.id}/${tc.id}`); await p.waitForSelector('.msg-content')
const theme = () => p.evaluate(() => document.documentElement.dataset.theme)
const bodyBg = () => p.evaluate(() => getComputedStyle(document.body).backgroundColor)
const msgSize = () => p.evaluate(() => parseFloat(getComputedStyle(document.querySelector('.msg-content')).fontSize))
ok('defaults: dark theme, cozy rows with avatars', await theme() === 'dark' && await bodyBg() === 'rgb(26, 27, 35)' && await p.locator('[data-msg-avatar]').count() === 1 && await p.locator('[data-msg-compact]').count() === 0)
const base = await msgSize()
await p.click('[data-control="User Settings"]'); await p.click('button:has-text("Appearance")'); await p.waitForSelector('[data-appearance]')
await p.click('[data-default-theme="light"]')
ok('Light flips the palette instantly', await theme() === 'light' && await bodyBg() === 'rgb(255, 255, 255)')
await p.screenshot({ path: '102-light-theme.png' })
await p.click('[data-theme-section] [role=switch]')
ok('Same as device theme follows the OS (light here)', await theme() === 'light' && await p.evaluate(() => document.documentElement.dataset.themeSetting) === 'system')
await p.emulateMedia({ colorScheme: 'dark' }); await p.waitForTimeout(100)
ok('…and tracks OS changes live', await theme() === 'dark')
await p.click('[data-theme-section] [role=switch]'); await p.click('[data-default-theme="light"]')
await p.locator('[data-font-scale]').fill('4')
ok('font scale 120% enlarges message text', Math.abs(await msgSize() - base * 1.2) < 0.6)
await p.click('[data-density-option="compact"]')
ok('compact mode drops avatars and puts the time inline', await p.locator('[data-msg-avatar]').count() === 0 && await p.locator('[data-msg-compact]').count() === 2)
await p.screenshot({ path: '103-compact-light.png' })
await p.reload(); await p.waitForSelector('.msg-content')
ok('settings persist across reloads', await theme() === 'light' && await p.locator('[data-msg-compact]').count() === 2 && Math.abs(await msgSize() - base * 1.2) < 0.6)
ok('stored under the app prefix', await p.evaluate(() => JSON.parse(localStorage.getItem('parley.appearance') || '{}').density) === 'compact')
await p.click('[data-control="User Settings"]'); await p.click('button:has-text("Appearance")'); await p.waitForSelector('[data-appearance]')
await p.click('[data-default-theme="default"]'); await p.click('[data-density-option="cozy"]'); await p.locator('[data-font-scale]').fill('2')
ok('back to defaults', await theme() === 'dark' && await p.locator('[data-msg-avatar]').count() === 1 && Math.abs(await msgSize() - base) < 0.6)
ok('no page errors', errors.length === 0, errors.join(' | '))
await browser.close(); await finish()
