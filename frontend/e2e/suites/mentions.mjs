import { chromium } from 'playwright'
import { WEB, S, reg, call, raw, ok, finish } from '../lib.mjs'

const a = await reg('alice'), b = await reg('bob'), c = await reg('carol')
const g = await call(a.token, 'POST', '/guilds', { name: `Mention Land ${S}` })
const inv = await call(a.token, 'POST', `/guilds/${g.id}/invites`, {}); await call(b.token, 'POST', `/invites/${inv.code}`); await call(c.token, 'POST', `/invites/${inv.code}`)
const tc = g.channels.find((x) => x.kind === 'text').id
const other = await call(a.token, 'POST', `/guilds/${g.id}/channels`, { name: 'announcements', kind: 'text' })
const role = await call(a.token, 'POST', `/guilds/${g.id}/roles`, { name: 'Mods', color: '#e91e63' })
await raw(a.token, 'PATCH', `/guilds/${g.id}/members/${b.user.id}`, { roles: [role.id] })

console.log('-- API')
let m = await call(a.token, 'POST', `/channels/${tc}/messages`, { content: `hey <@${b.user.id}> see <#${other.id}> and <@&${role.id}> @everyone` })
ok('mentions are parsed and stored on the message', m.mentions?.[0] === b.user.id && m.mention_roles?.[0] === role.id && m.mention_everyone === true, JSON.stringify([m.mentions, m.mention_roles, m.mention_everyone]))
let r = await raw(a.token, 'PATCH', `/channels/${tc}/messages/${m.id}`, { content: `now only <@${c.user.id}>` }); const e = await r.json()
ok('editing re-parses mentions', e.mentions?.[0] === c.user.id && e.mention_roles?.length === 0 && e.mention_everyone === false)
const dm = await call(a.token, 'POST', '/users/@me/channels', { recipient_id: b.user.id })
const dmm = await call(a.token, 'POST', `/channels/${dm.id}/messages`, { content: 'dm @everyone' })
ok('@everyone is text in DMs, not a mention', dmm.mention_everyone === false)
await raw(a.token, 'PATCH', `/guilds/${g.id}/members/${c.user.id}`, { roles: [role.id] })
await call(a.token, 'POST', `/channels/${tc}/messages`, { content: `ping <@${b.user.id}>` })
await call(a.token, 'POST', `/channels/${tc}/messages`, { content: `role ping <@&${role.id}>` })
await call(a.token, 'POST', `/channels/${other.id}/messages`, { content: 'all hands @everyone' })
await call(a.token, 'POST', `/channels/${tc}/messages`, { content: `see <#${other.id}>` })

console.log('-- UI (bob)')
const browser = await chromium.launch(); const errors = []
const mk = async (tok) => { const p = await browser.newPage({ viewport: { width: 1440, height: 900 } }); p.on('pageerror', (ev) => errors.push(ev.message)); await p.goto(`${WEB}/login`); await p.evaluate((t) => localStorage.setItem('parley.token', t), tok); return p }
const pb = await mk(b.token)
await pb.goto(`${WEB}/channels/@me`); await pb.waitForTimeout(1200)
ok('server icon shows the unread mention count from READY (3: direct, role, @everyone)', (await pb.locator(`[data-guild-icon="${g.id}"] [data-guild-mentions]`).getAttribute('data-guild-mentions')) === '3')
await pb.goto(`${WEB}/channels/${g.id}/${tc}`); await pb.waitForTimeout(1200)
ok('channel rows carry per-channel mention badges', await pb.locator('[data-channel-row="announcements"] [data-mention-badge="1"]').count() === 1)
ok('user mention renders as a pill with the name, highlighted for me', await pb.locator(`[data-mention-user="${b.user.id}"].mention-me:has-text("@Bob")`).count() >= 1)
ok('role pill uses the role colour; channel pill shows #name', await pb.locator(`[data-mention-role="${role.id}"]:has-text("@Mods")`).count() >= 1 && await pb.locator(`[data-mention-channel="${other.id}"]:has-text("#announcements")`).count() >= 1)
ok('messages that mention me are highlighted', await pb.locator('.msg-mentioned').count() >= 2)
await pb.screenshot({ path: '91-mentions.png' })
await pb.click(`[data-mention-channel="${other.id}"]`); await pb.waitForTimeout(800)
ok('clicking a channel pill navigates there and @everyone is a pill', pb.url().endsWith(`/${other.id}`) && await pb.locator('[data-mention-everyone="everyone"]').count() === 1)
await pb.waitForTimeout(700)
ok('reading the channel clears its badge', await pb.locator('[data-channel-row="announcements"] [data-mention-badge]').count() === 0)

console.log('-- composer autocomplete')
await pb.goto(`${WEB}/channels/${g.id}/${tc}`); await pb.waitForTimeout(900)
const ta = pb.locator('textarea'); await ta.click(); await ta.type('hi @car'); await pb.waitForTimeout(400)
ok('typing @car lists Carol', await pb.locator('[data-mention-suggest="@"] [data-mention-option="user:Carol"]').count() === 1)
await pb.keyboard.press('Enter'); await pb.waitForTimeout(150)
ok('Enter inserts the name as text', (await ta.inputValue()) === 'hi @Carol ')
await ta.type('and #ann'); await pb.waitForTimeout(400); ok('#ann lists the channel', await pb.locator('[data-mention-suggest="#"] [data-mention-option="channel:announcements"]').count() === 1)
await pb.keyboard.press('Tab'); await pb.waitForTimeout(150)
await ta.type('plus @mod'); await pb.waitForTimeout(400); await pb.click('[data-mention-option="role:Mods"]'); await pb.waitForTimeout(150)
await ta.type('@every'); await pb.waitForTimeout(400); await pb.keyboard.press('Enter'); await pb.waitForTimeout(150)
ok('text reads naturally before sending', (await ta.inputValue()) === 'hi @Carol and #announcements plus @Mods @everyone ')
await pb.keyboard.press('Enter'); await pb.waitForTimeout(900)
const last = (await call(a.token, 'GET', `/channels/${tc}/messages`)).at(-1)
ok('sending converts picks to wire tokens', last.content === `hi <@${c.user.id}> and <#${other.id}> plus <@&${role.id}> @everyone` && last.mentions[0] === c.user.id && last.mention_everyone === true, last.content)
const pc = await mk(c.token); await pc.goto(`${WEB}/channels/${g.id}/${tc}`); await pc.waitForTimeout(1200)
ok('carol sees it rendered as pills and highlighted', await pc.locator(`[data-msg-id="${last.id}"].msg-mentioned [data-mention-user="${c.user.id}"]`).count() === 1)
await pb.click(`[data-msg-id="${last.id}"] [data-mention-user="${c.user.id}"]`); await pb.waitForTimeout(400)
ok('clicking a user pill opens their profile popout', await pb.locator('[data-profile-popout]:has-text("Carol")').count() === 1)
ok('no page errors', errors.length === 0, errors.join(' | '))
await browser.close(); await finish()
