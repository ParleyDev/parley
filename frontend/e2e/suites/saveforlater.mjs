// Messaging extras: poll answers with emoji and "View votes", Remind Me on messages (bookmark + reminder that fires as a
// toast and shows in Bookmarks), favourite emoji in the picker, and message-link preview cards that jump to the message.
import { chromium } from 'playwright'
import { WEB, S, reg, call, ok, finish } from '../lib.mjs'
const a = await reg('alice'), b = await reg('bob')
const g = await call(a.token, 'POST', '/guilds', { name: `Later ${S}` })
const inv = await call(a.token, 'POST', `/guilds/${g.id}/invites`, {}); await call(b.token, 'POST', `/invites/${inv.code}`)
const general = g.channels.find((x) => x.kind === 'text')
const other = await call(a.token, 'POST', `/guilds/${g.id}/channels`, { name: 'elsewhere', kind: 'text' })
const browser = await chromium.launch(); const errors = []
const p = await (await browser.newContext({ viewport: { width: 1280, height: 800 } })).newPage(); p.on('pageerror', (e) => errors.push(e.message))
await p.goto(`${WEB}/login`); await p.evaluate((t) => localStorage.setItem('parley.token', t), a.token)
await p.goto(`${WEB}/channels/${g.id}/${general.id}`); await p.waitForSelector('[data-composer-box] textarea'); await p.waitForTimeout(800)

console.log('-- polls')
await p.click('[data-composer-plus]'); await p.click('[data-context-menu] [data-menu-item="Create Poll"]'); await p.waitForSelector('[data-create-poll]')
await p.fill('[data-poll-q]', `Snack? ${S}`); await p.fill('[data-poll-opt="0"]', 'Pizza'); await p.fill('[data-poll-emoji="0"]', '🍕')
await p.fill('[data-poll-opt="1"]', ''); await p.click('[data-poll-add]'); await p.fill('[data-poll-opt="2"]', 'Tacos'); await p.fill('[data-poll-emoji="2"]', '🌮')
await p.fill('[data-poll-opt="1"]', 'Salad'); await p.click('[data-poll-submit]'); await p.waitForSelector('[data-poll]')
const card = p.locator('[data-poll]').last()
const emojis = await card.locator('[data-poll-option]').evaluateAll((els) => els.map((e) => e.querySelector('[data-poll-option-emoji]')?.getAttribute('data-poll-option-emoji') ?? ''))
ok('answers show their emoji (and one without)', emojis[0] === '🍕' && emojis[1] === '' && emojis[2] === '🌮', JSON.stringify(emojis))
const pollMsg = (await call(a.token, 'GET', `/channels/${general.id}/messages?limit=5`)).find((m) => m.poll)
await call(b.token, 'PUT', `/channels/${general.id}/messages/${pollMsg.id}/poll/${pollMsg.poll.options[2].id}`)
await card.locator('[data-poll-option]').first().click(); await p.waitForTimeout(500)
await card.locator('[data-poll-view-votes]').click(); await p.waitForSelector('[data-poll-voters] [data-poll-voter]')
ok('View votes lists who picked an answer', await card.locator(`[data-poll-voter="${a.user.display_name}"]`).count() === 1)
await card.locator(`[data-poll-voters-tab="${pollMsg.poll.options[2].id}"]`).click(); await p.waitForTimeout(400)
ok('and switches between answers', await card.locator(`[data-poll-voter="${b.user.display_name}"]`).count() === 1 && await card.locator(`[data-poll-voter="${a.user.display_name}"]`).count() === 0)

console.log('-- remind me')
const target = await call(b.token, 'POST', `/channels/${general.id}/messages`, { content: `look later ${S}` }); await p.waitForTimeout(600)
await p.click(`[data-msg-id="${target.id}"] .msg-content`, { button: 'right' }); await p.waitForTimeout(250)
await p.hover('[data-context-menu] [data-menu-item="Remind Me"]'); await p.waitForTimeout(250); await p.click('[data-menu-item="In 1 hour"]'); await p.waitForTimeout(600)
let bms = await call(a.token, 'GET', '/users/@me/bookmarks')
const bm = bms.find((x) => x.id === target.id)
ok('Remind Me bookmarks the message with a reminder about an hour out', !!bm && Math.abs(new Date(bm.remind_at).getTime() - Date.now() - 3600_000) < 120_000, JSON.stringify(bm?.remind_at))
await p.click('[data-bookmarks-toggle]'); await p.waitForSelector('[data-bookmarks-panel] [data-bookmark]')
ok('the Bookmarks panel shows the reminder', await p.locator(`[data-bookmark="${target.id}"] [data-bookmark-reminder]`).count() === 1)
await p.click(`[data-bookmark="${target.id}"] [data-bookmark-reminder]`); await p.waitForTimeout(500)
bms = await call(a.token, 'GET', '/users/@me/bookmarks')
ok('and clicking it clears the reminder but keeps the bookmark', bms.find((x) => x.id === target.id)?.remind_at === null)
await p.keyboard.press('Escape'); await p.waitForTimeout(200)
await call(a.token, 'PATCH', `/users/@me/bookmarks/${target.id}`, { remind_at: new Date(Date.now() - 1000).toISOString() })
await p.waitForFunction(() => /Reminder \(#general\)/.test(document.body.innerText), null, { timeout: 30000 }).catch(() => {})
ok('a due reminder pops up as a toast', /Reminder \(#general\) — .*look later/.test(await p.locator('body').innerText()))
bms = await call(a.token, 'GET', '/users/@me/bookmarks')
ok('and fires only once', bms.find((x) => x.id === target.id)?.remind_at === null)

console.log('-- favourite emoji')
await p.click('[data-emoji-button]'); await p.waitForSelector('[data-emoji-search]')
await p.fill('[data-emoji-search]', 'avocado'); await p.waitForSelector('[data-emoji-btn=":avocado:"]'); await p.hover('[data-emoji-btn=":avocado:"]')
await p.click('[data-emoji-fav]'); await p.waitForTimeout(100)
ok('the star marks it a favourite', (await p.getAttribute('[data-emoji-fav]', 'aria-pressed')) === 'true')
await p.fill('[data-emoji-search]', ''); await p.waitForTimeout(200)
ok('Favorites appears first in the grid', await p.locator('[data-emoji-grid] [data-section="favorites"] [data-emoji-btn]').count() === 1 && (await p.locator('[data-emoji-grid] [data-section]').first().getAttribute('data-section')) === 'favorites')
await p.keyboard.press('Escape'); await p.waitForTimeout(200)

console.log('-- message links')
const quoted = await call(b.token, 'POST', `/channels/${other.id}/messages`, { content: `the original ${S}` })
await call(b.token, 'POST', `/channels/${general.id}/messages`, { content: `see ${WEB}/channels/${g.id}/${other.id}?message=${quoted.id}` }); await p.waitForTimeout(900)
const prev = p.locator(`[data-message-link="${quoted.id}"]`)
ok('a link to a message shows a preview card', await prev.count() === 1 && /the original/.test(await prev.locator('[data-message-link-text]').innerText()) && /elsewhere/.test(await prev.innerText()))
await prev.click(); await p.waitForTimeout(1200)
ok('clicking it jumps to that message', new URL(p.url()).pathname === `/channels/${g.id}/${other.id}` && await p.locator(`[data-msg-id="${quoted.id}"]`).isVisible())
await p.goto(`${WEB}/channels/${g.id}/${general.id}?message=${target.id}`); await p.waitForTimeout(1500)
ok('opening a ?message= link scrolls to it and tidies the URL', await p.locator(`[data-msg-id="${target.id}"]`).isVisible() && !p.url().includes('message='))
ok('no page errors', errors.length === 0, errors.join(' | '))
await call(a.token, 'DELETE', `/guilds/${g.id}`)
await browser.close(); await finish()
