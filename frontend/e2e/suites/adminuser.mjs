// Admin user page: guests can be filtered in Users, clicking a user opens their page with activity, standing,
// social and device numbers, and the PII reveal (with a logged reason) shows every address and client seen in the
// last 90 days and the other accounts seen on those addresses.
import { execSync } from 'node:child_process'
import { chromium } from 'playwright'
import { WEB, B, S, H, IP, reg, call, callS, raw, ok, finish, adminToken, testContainer } from '../lib.mjs'

const sql = (q) => execSync(`docker exec ${testContainer('db')} psql -U parley -tAc "${q.replace(/"/g, '\\"')}"`, { stdio: ['pipe', 'pipe', 'pipe'] }).toString().trim()
const admin = await adminToken()
const a = await reg('alice'), b = await reg('bob'), mod = await reg('mod')
await call(admin.token, 'PUT', `/admin/users/${mod.user.id}/roles`, { roles: ['MODERATOR'] })
const g = await call(a.token, 'POST', '/guilds', { name: `Detail ${S}` }); const ch = g.channels.find((x) => x.kind === 'text')
const inv = await call(a.token, 'POST', `/guilds/${g.id}/invites`, {}); await call(b.token, 'POST', `/invites/${inv.code}`)
for (const c of ['one', 'two', 'three']) await call(a.token, 'POST', `/channels/${ch.id}/messages`, { content: c })
const bad = await call(b.token, 'POST', `/channels/${ch.id}/messages`, { content: 'rude' })
await call(a.token, 'POST', '/reports', { kind: 'message', message_id: bad.id, reason: 'rude' })
await call(a.token, 'POST', '/users/@me/relationships', { user_id: b.user.id }); await call(b.token, 'PUT', `/users/@me/relationships/${a.user.id}`)
const g2 = await call(a.token, 'POST', '/guilds', { name: `Other ${S}` }); const inv2 = await call(a.token, 'POST', `/guilds/${g2.id}/invites`, {})
await call(b.token, 'POST', `/invites/${inv2.code}`); await call(a.token, 'PUT', `/guilds/${g2.id}/bans/${b.user.id}`, { reason: 'test' })

console.log('-- guest filter')
const settings = await call(admin.token, 'GET', '/admin/settings')
await callS(admin.token, 'PUT', '/admin/settings', { ...settings, demo_guild_id: g.id })
const guest = await (await fetch(`${B}/auth/guest`, { method: 'POST', headers: { ...H, 'X-Forwarded-For': `10.88.${S % 250}.9` }, body: '{}' })).json()
await callS(admin.token, 'PUT', '/admin/settings', { ...settings, demo_guild_id: '' })
let list = await call(admin.token, 'GET', '/admin/users?guest=true&limit=200')
ok('guest=true lists only guests', list.length > 0 && list.every((u) => u.guest) && list.some((u) => u.id === guest.user.id), JSON.stringify(list.map((u) => u.username)))
list = await call(admin.token, 'GET', `/admin/users?guest=false&q=${S}`)
ok('guest=false leaves them out', !list.some((u) => u.guest) && list.some((u) => u.id === a.user.id))

console.log('-- overview')
let r = await callS(admin.token, 'GET', `/admin/users/${a.user.id}/overview`)
const o = r.body
ok('the overview loads for an admin', r.status === 200 && o.user.username === a.user.username, JSON.stringify(r.body).slice(0, 200))
ok('  message counts', o.messages.total === 3 && o.messages.last_day === 3 && o.messages.in_servers === 3 && o.messages.daily.length === 30 && o.messages.daily.at(-1).count === 3, JSON.stringify(o.messages))
ok('  social counts', o.social.servers === 2 && o.social.servers_owned === 2 && o.social.friends === 1, JSON.stringify(o.social))
ok('  their own reports', o.standing.reports_filed === 1)
ok('  device counts include the address they signed up from', o.devices.addresses >= 1 && o.devices.active_sessions >= 1, JSON.stringify(o.devices))
const ob = (await call(admin.token, 'GET', `/admin/users/${b.user.id}/overview`))
ok("the reported user's standing shows the report and the server ban", ob.standing.reports_against === 1 && ob.standing.reports_open === 1 && ob.standing.server_bans === 1, JSON.stringify(ob.standing))
ok('guests are marked', (await call(admin.token, 'GET', `/admin/users/${guest.user.id}/overview`)).user.guest === true)
r = await callS(a.token, 'GET', `/admin/users/${b.user.id}/overview`)
ok('non-admins cannot see it', r.status === 403)
r = await callS(mod.token, 'GET', `/admin/users/${a.user.id}/overview`)
ok('a moderator sees the overview with the email masked and no reveal', r.status === 200 && r.body.user.email.includes('***') && r.body.can_reveal === false, JSON.stringify(r.body?.user?.email))

console.log('-- signals (PII reveal)')
r = await callS(mod.token, 'POST', `/admin/users/${a.user.id}/signals`, { justification: 'checking for alt accounts' })
ok('a moderator cannot reveal addresses', r.status === 403)
r = await callS(admin.token, 'POST', `/admin/users/${a.user.id}/signals`, { justification: 'short' })
ok('a reason is required', r.status === 400)
const before = Number(sql(`SELECT count(*) FROM admin_access_log WHERE action = 'pii.signals' AND '${a.user.id}' = ANY(target_ids)`))
r = await callS(admin.token, 'POST', `/admin/users/${a.user.id}/signals`, { justification: 'test of the user page' })
const sg = r.body
ok('an admin with the reveal permission sees the email and addresses', r.status === 200 && sg.email === `alice${S}@x.io` && sg.addresses.some((x) => x.ip === IP), JSON.stringify(sg?.addresses))
ok('  with the email domain', sg.email_domain === 'x.io')
ok('  and the browsers/apps they used', sg.clients.length >= 1)
ok('accounts on the same address are listed (bob signed up from it too)', sg.shared.some((x) => x.id === b.user.id && x.ips.includes(IP)), JSON.stringify(sg.shared.map((x) => x.username)))
ok('  and counted per address', sg.addresses.find((x) => x.ip === IP)?.other_accounts >= 1)
ok('the reveal is logged with its reason', Number(sql(`SELECT count(*) FROM admin_access_log WHERE action = 'pii.signals' AND '${a.user.id}' = ANY(target_ids) AND justification = 'test of the user page'`)) === before + 1)

console.log('-- realtime connections are recorded')
const browser = await chromium.launch()
const ctx = await browser.newContext({ viewport: { width: 1280, height: 900 }, extraHTTPHeaders: { 'X-Forwarded-For': `10.66.${S % 250}.7` } })
const pa = await ctx.newPage()
await pa.goto(`${WEB}/login`); await pa.evaluate((t) => localStorage.setItem('parley.token', t), a.token); await pa.goto(`${WEB}/channels/@me`); await pa.waitForTimeout(2500)
ok('a new address from a realtime connection lands in the log, with its platform', sql(`SELECT platform FROM user_network_log WHERE user_id = '${a.user.id}' AND ip = '10.66.${S % 250}.7'`) === 'web')

console.log('-- UI')
const p = await (await browser.newContext({ viewport: { width: 1280, height: 900 } })).newPage()
await p.goto(`${WEB}/login`); await p.evaluate((t) => localStorage.setItem('parley.token', t), admin.token)
await p.goto(`${WEB}/admin/users`); await p.waitForSelector('[data-admin-user-search]')
await p.selectOption('[data-admin-filter="guest"]', 'true').catch(async () => { await p.click('[data-admin-filter="guest"]'); await p.click('text=Guests') })
await p.waitForTimeout(800)
ok('the Account filter shows guests with a GUEST badge', (await p.locator(`[data-admin-user="${guest.user.username}"] [data-badge="guest"]`).count()) === 1)
await p.goto(`${WEB}/admin/users`); await p.fill('[data-admin-user-search]', `alice${S}`); await p.waitForSelector(`[data-admin-user="alice${S}"]`)
await p.click(`[data-admin-user="alice${S}"] >> text=Alice`)
await p.waitForSelector(`[data-admin-user-detail="${a.user.id}"]`, { timeout: 8000 }).catch(() => {})
ok('clicking a user opens their page', (await p.locator(`[data-admin-user-detail="${a.user.id}"]`).count()) === 1, p.url())
ok('  with their numbers', (await p.locator('[data-admin-stat="messages-total"]').innerText()) === '3' && (await p.locator('[data-admin-stat="servers"]').innerText()) === '2')
ok('  and the activity chart', (await p.locator('[data-admin-activity] span').count()) === 30)
await p.screenshot({ path: 'admin-user.png', fullPage: true })
await p.click('[data-admin-signals-reveal]'); await p.fill('[data-admin-signals-why]', 'reviewing the new page'); await p.click('[data-admin-signals-go]')
await p.waitForSelector('[data-admin-signals-shown]')
ok('Reveal shows the addresses and other accounts on them', (await p.locator(`[data-admin-signal-ip="${IP}"]`).count()) === 1 && (await p.locator(`[data-admin-shared-user="bob${S}"]`).count()) === 1)
await p.screenshot({ path: 'admin-user-signals.png', fullPage: true })
await p.click(`[data-admin-shared-user="bob${S}"]`)
await p.waitForSelector(`[data-admin-user-detail="${b.user.id}"]`, { timeout: 8000 }).catch(() => {})
ok('a linked account opens its own page', (await p.locator(`[data-admin-user-detail="${b.user.id}"]`).count()) === 1)
await p.click('[data-admin-detail-content]'); await p.waitForSelector('[data-admin-user-content]')
ok('Uploads and sessions is one click away', p.url().endsWith(`/admin/users/${b.user.id}/content`))
const ph = await (await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true })).newPage()
await ph.goto(`${WEB}/login`); await ph.evaluate((t) => localStorage.setItem('parley.token', t), admin.token)
await ph.goto(`${WEB}/admin/users/${a.user.id}`); await ph.waitForSelector(`[data-admin-user-detail="${a.user.id}"]`)
ok('the page fits a phone', await ph.evaluate(() => document.documentElement.scrollWidth <= 390 + 1))
await ph.screenshot({ path: 'admin-user-phone.png', fullPage: true })
await browser.close()

console.log('-- deletion')
await callS(admin.token, 'DELETE', `/admin/users/${b.user.id}`)
ok('deleting an account forgets where it connected from', sql(`SELECT count(*) FROM user_network_log WHERE user_id = '${b.user.id}'`) === '0')
sql(`DELETE FROM users WHERE id = '${guest.user.id}'`)
await finish()
