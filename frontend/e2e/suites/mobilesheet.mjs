// Phones: no bottom tab bar (navigation is the server bar, your panel and the header inbox), and holding a message
// opens its action sheet.
import { chromium } from 'playwright'
import { WEB, S, reg, call, raw, ok, openDms, finish } from '../lib.mjs'
const a = await reg('alice'), b = await reg('bob')
await openDms(a, b)
const g = await call(a.token, 'POST', '/guilds', { name: `Tabs ${S}` })
const ch = g.channels.find((c) => c.kind === 'text')
const mine = await call(a.token, 'POST', `/channels/${ch.id}/messages`, { content: 'hold me' })
const dm = await call(b.token, 'POST', '/users/@me/channels', { recipient_id: a.user.id })
await call(b.token, 'POST', `/channels/${dm.id}/messages`, { content: 'unread dm' })

const browser = await chromium.launch(); const errors = []
const p = await (await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true })).newPage()
p.on('pageerror', (e) => errors.push(e.message))
await p.goto(`${WEB}/login`); await p.evaluate((t) => localStorage.setItem('parley.token', t), a.token)

console.log('-- phones')
await p.goto(`${WEB}/channels/@me`); await p.waitForSelector('[data-user-panel]')
ok('no bottom tab bar', await p.locator('[data-mobile-tabs]').count() === 0)
const panel = await p.locator('[data-user-panel]').boundingBox()
ok('your panel sits at the bottom of the navigation', panel && Math.abs(panel.y + panel.height - 844) <= 16, JSON.stringify(panel))
await p.goto(`${WEB}/channels/${g.id}/${ch.id}`); await p.waitForSelector(`[data-msg-id="${mine.id}"]`); await p.waitForTimeout(400)
await p.locator('[data-inbox-toggle]:visible').first().tap(); await p.waitForSelector('[data-inbox]'); await p.waitForTimeout(300)
const ib = await p.locator('[data-inbox]').boundingBox()
ok('inside a chat, the inbox opens from the header and fits the screen', ib && ib.x >= 0 && ib.x + ib.width <= 390, JSON.stringify(ib))
await p.locator('[data-inbox-toggle]:visible').first().tap(); await p.waitForTimeout(200)
const headerBtns = await p.evaluate(() => [...document.querySelectorAll('main header button')].filter((b) => b.offsetParent).length)
ok('a channel header on a phone keeps just a few buttons', headerBtns <= 5, String(headerBtns))
await p.locator('[data-header-more]').tap(); await p.waitForSelector('[data-menu-sheet]')
ok('the rest is in the More sheet', await p.locator('[data-menu-sheet] [data-menu-item="Pinned Messages"]').count() === 1 && await p.locator('[data-menu-sheet] [data-menu-item="Search"]').count() === 1)
await p.locator('[data-menu-sheet] [data-menu-item="Pinned Messages"]').tap(); await p.waitForSelector('[data-pins-panel]'); await p.waitForTimeout(500)
const pins = await p.locator('[data-pins-panel]').boundingBox()
ok('pins open as a sheet across the bottom', pins && pins.x <= 1 && Math.abs(pins.width - 390) <= 2 && Math.abs(pins.y + pins.height - 844) <= 2, JSON.stringify(pins))
await p.mouse.click(195, 100); await p.waitForTimeout(200)
await p.locator('[data-header-more]').tap(); await p.locator('[data-menu-sheet] [data-menu-item="Search"]').tap()
ok('Search opens a full-width box over the header', (await p.locator('[data-search-input]').boundingBox())?.width > 250)
await p.locator('[data-phone-search-close]').tap()
console.log('-- keyboard')
const kb = await call(a.token, 'POST', `/guilds/${g.id}/channels`, { name: 'keyboard', kind: 'text' })
for (let i = 0; i < 25; i++) await call(a.token, 'POST', `/channels/${kb.id}/messages`, { content: `filler ${i}` })
await p.goto(`${WEB}/channels/${g.id}/${kb.id}`); await p.waitForSelector('text=filler 24'); await p.waitForTimeout(500)
await p.locator('main textarea').tap(); await p.locator('main textarea').fill('sent from the phone')
await p.locator('[data-composer-send]').tap(); await p.waitForSelector('text=sent from the phone'); await p.waitForTimeout(300)
ok('sending keeps the text box focused (the keyboard stays up)', await p.evaluate(() => document.activeElement?.tagName === 'TEXTAREA'))
await p.setViewportSize({ width: 390, height: 480 }); await p.waitForTimeout(500)
const last = await p.locator('text=sent from the phone').boundingBox(), box = await p.locator('main textarea').boundingBox()
ok('when the keyboard shrinks the screen, the newest message stays right above the text box', last && box && last.y + last.height <= box.y && last.y > box.y - 150, JSON.stringify({ last, box }))
await p.setViewportSize({ width: 390, height: 844 }); await p.waitForTimeout(300)
const flow = await p.evaluate(() => { const b = document.querySelector('[data-chat-bottom]'), list = document.querySelector('[data-message-list]'); return { abs: getComputedStyle(b).position === 'absolute', listBottom: list.getBoundingClientRect().bottom, boxTop: b.getBoundingClientRect().top } })
ok('the message box sits under the list in the layout (the list and its scrollbar end above it)', !flow.abs && flow.listBottom <= flow.boxTop + 1, JSON.stringify(flow))
for (let i = 25; i < 70; i++) await call(a.token, 'POST', `/channels/${kb.id}/messages`, { content: `filler ${i}` })
await p.waitForSelector('text=filler 69'); await p.waitForTimeout(400)
await p.evaluate(() => { const el = document.querySelector('[data-message-list]'); el.scrollTop = el.scrollHeight - el.clientHeight - 300 }); await p.waitForTimeout(400)
ok('a short scroll up shows no jump button', await p.locator('[data-jump-present]').count() === 0)
await p.evaluate(() => { const el = document.querySelector('[data-message-list]'); el.scrollTop = 0 }); await p.waitForSelector('[data-jump-present]')
const jb = await p.locator('[data-jump-present]').boundingBox()
ok('well up the history a phone gets a small round button at the right, not the pill', jb && jb.width <= 44 && jb.x + jb.width > 340 && await p.locator("text=You're viewing older messages").count() === 0, JSON.stringify(jb))
await p.locator('[data-jump-present]').tap(); await p.waitForFunction(() => !document.querySelector('[data-jump-present]'))
ok('it takes you back to the newest message', await p.locator('text=filler 69').isVisible())
await raw(a.token, 'PATCH', `/channels/${kb.id}`, { rate_limit_per_user: 10 }); await p.waitForSelector('[data-composer-status]')
const strip = await p.evaluate(() => getComputedStyle(document.querySelector('[data-composer-status] > div:last-child')).backgroundColor)
ok('slowmode shows in a strip with a solid background above the message box', strip && !/rgba\(0, 0, 0, 0\)|transparent/.test(strip), strip)

await p.goto(`${WEB}/channels/@me/${dm.id}`); await p.waitForTimeout(800)
ok('a DM header on a phone shows the name', await p.locator('[data-dm-header-name]').isVisible())
ok('…with call and video', await p.locator('[data-start-call]').isVisible() && await p.locator('[data-start-video]').isVisible())

console.log('-- long-press sheet')
await p.goto(`${WEB}/channels/${g.id}/${ch.id}`); await p.waitForSelector(`[data-msg-id="${mine.id}"]`); await p.waitForTimeout(500)
const cdp = await p.context().newCDPSession(p)
const hold = async (sel, ms) => {
  const r = await p.locator(sel).first().boundingBox(); const pt = { x: r.x + 20, y: r.y + r.height / 2 }
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [pt] })
  await p.waitForTimeout(ms)
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] })
}
await hold(`[data-msg-id="${mine.id}"] .msg-content`, 650); await p.waitForTimeout(250)
const sheet = p.locator('[data-menu-sheet]')
ok('holding a message opens its action sheet', await sheet.isVisible())
const sb = await sheet.boundingBox()
ok('docked to the bottom, full width', sb && Math.abs(sb.y + sb.height - 844) <= 2 && sb.width >= 388, JSON.stringify(sb))
ok('with the message actions', await sheet.locator('[data-menu-item="Reply"]').count() === 1 && await sheet.locator('[data-menu-item="Copy Text"]').count() === 1)
ok('without also opening the tap bar', !(await p.locator(`[data-msg-id="${mine.id}"] button[title="Reply"]`).isVisible()))
await sheet.locator('[data-menu-item="Reply"]').tap(); await p.waitForTimeout(200)
ok('an action runs and closes the sheet', !(await sheet.isVisible()) && await p.locator('text=Replying to').isVisible())
await hold(`[data-msg-id="${mine.id}"] .msg-content`, 650); await p.waitForTimeout(250)
await p.locator('[data-menu-sheet-backdrop]').tap({ position: { x: 200, y: 100 } }); await p.waitForTimeout(200)
ok('tapping outside closes it', !(await sheet.isVisible()))
await hold(`[data-msg-id="${mine.id}"] .msg-content`, 120); await p.waitForTimeout(400)
ok('a short touch is still just a tap', !(await sheet.isVisible()))

console.log('-- desktop')
const d = await (await browser.newContext({ viewport: { width: 1280, height: 900 } })).newPage()
await d.goto(`${WEB}/login`); await d.evaluate((t) => localStorage.setItem('parley.token', t), a.token)
await d.goto(`${WEB}/channels/${g.id}/${ch.id}`); await d.waitForSelector(`[data-msg-id="${mine.id}"]`)
await d.locator(`[data-msg-id="${mine.id}"] .msg-content`).click({ button: 'right' })
ok('right-click is still a popup menu', await d.locator('[data-context-menu]').isVisible() && await d.locator('[data-menu-sheet]').count() === 0)
ok('no page errors', errors.length === 0, errors.join(' | '))
await call(a.token, 'DELETE', `/guilds/${g.id}`, { password: 'password1', name: g.name })
await browser.close(); await finish()
