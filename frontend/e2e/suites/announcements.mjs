// Announcement channels (follow into another server, Publish copies posts there) and media channels (posts lead
// with an image or video, shown as a gallery).
import { chromium } from 'playwright'
import { WEB, S, reg, call, raw, multi, ok, finish } from '../lib.mjs'
const a = await reg('alice'), b = await reg('bob')
const ga = await call(a.token, 'POST', '/guilds', { name: `News ${S}` })
const gb = await call(b.token, 'POST', '/guilds', { name: `Fans ${S}` })
const inv = await call(a.token, 'POST', `/guilds/${ga.id}/invites`, {}); await call(b.token, 'POST', `/invites/${inv.code}`)
const news = await call(a.token, 'POST', `/guilds/${ga.id}/channels`, { name: 'updates', kind: 'announcement' })
const plain = ga.channels.find((x) => x.kind === 'text')
const dest = gb.channels.find((x) => x.kind === 'text')
// 1x1 PNG
const PNG = Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVR42mP8z8BQDwAEhQGAhKmMIQAAAABJRU5ErkJggg==', 'base64')

console.log('-- api')
ok('announcement is a text channel with news set', news.kind === 'text' && news.news === true)
ok('plain channels can\'t be followed', (await raw(b.token, 'POST', `/channels/${plain.id}/followers`, { channel_id: dest.id })).status === 400)
ok('you need Manage Channels in the target', (await raw(b.token, 'POST', `/channels/${news.id}/followers`, { channel_id: plain.id })).status === 403)

const browser = await chromium.launch(); const errors = []
const ctx = async (t) => { const p = await (await browser.newContext({ viewport: { width: 1280, height: 900 } })).newPage(); p.on('pageerror', (x) => errors.push(x.message)); await p.goto(`${WEB}/login`); await p.evaluate((x) => localStorage.setItem('parley.token', x), t); return p }

console.log('-- follow')
const pb = await ctx(b.token)
await pb.goto(`${WEB}/channels/${ga.id}/${news.id}`); await pb.waitForSelector('[data-follow-channel]')
ok('announcement channels get a megaphone in the list', await pb.locator('[data-channel-row="updates"] svg.lucide-megaphone').count() === 1)
await pb.click('[data-follow-channel]'); await pb.waitForSelector('[data-follow-modal]')
await pb.selectOption('[data-follow-guild]', gb.id); await pb.selectOption('[data-follow-target]', dest.id); await pb.click('[data-follow-confirm]'); await pb.waitForTimeout(600)
const following = await call(b.token, 'GET', `/channels/${dest.id}/following`)
ok('Follow links the channels', following.length === 1 && following[0].channel_id === news.id)
const destMsgs = await call(b.token, 'GET', `/channels/${dest.id}/messages`)
ok('the followed channel gets a notice', destMsgs.some((m) => m.kind === 'channel_follow' && m.content.includes('#updates')))

console.log('-- publish')
const pa = await ctx(a.token)
await pa.goto(`${WEB}/channels/${ga.id}/${news.id}`); await pa.waitForTimeout(800)
const post = await call(a.token, 'POST', `/channels/${news.id}/messages`, { content: `Big release ${S}` }); await pa.waitForTimeout(500)
const row = pa.locator(`[data-msg-id="${post.id}"]`)
await row.hover(); ok('your posts show Publish', await row.locator('[data-publish]').count() === 1)
await row.locator('[data-publish]').click(); await pa.waitForTimeout(800)
ok('published posts are marked', await row.locator('[data-published]').count() === 1)
ok('publishing twice is refused', (await raw(a.token, 'POST', `/channels/${news.id}/messages/${post.id}/crosspost`)).status === 409)
const copy = (await call(b.token, 'GET', `/channels/${dest.id}/messages`)).find((m) => m.content === `Big release ${S}`)
ok('the post is copied to the follower', !!copy && copy.crosspost?.channel_id === news.id && copy.crosspost?.guild_name === `News ${S}`)
await pb.goto(`${WEB}/channels/${gb.id}/${dest.id}`); await pb.waitForTimeout(1000)
ok('the copy says where it came from', (await pb.locator(`[data-msg-id="${copy?.id}"] [data-crosspost-from="${news.id}"]`).innerText().catch(() => '')).includes('#updates'))
const alices = await call(a.token, 'POST', `/channels/${news.id}/messages`, { content: 'second post' })
ok('others can\'t publish posts they didn\'t write', (await raw(b.token, 'POST', `/channels/${news.id}/messages/${alices.id}/crosspost`)).status === 403)
await call(a.token, 'DELETE', `/channels/${news.id}/followers/${dest.id}`)
ok('the source can remove a follower', (await call(b.token, 'GET', `/channels/${dest.id}/following`)).length === 0)

console.log('-- media channels')
const media = await call(a.token, 'POST', `/guilds/${ga.id}/channels`, { name: 'gallery', kind: 'media' })
ok('media is a forum with media set', media.kind === 'forum' && media.media === true)
ok('posts without an image are refused', (await raw(a.token, 'POST', `/channels/${media.id}/threads`, { name: 'text only', content: 'hi' })).status === 400)
await pa.goto(`${WEB}/channels/${ga.id}/${media.id}`); await pa.waitForSelector('[data-forum-new]')
await pa.click('[data-forum-new]'); await pa.fill('[data-post-title]', `Sunset ${S}`)
ok('Post waits for an image', await pa.locator('[data-post-submit]').isDisabled())
await pa.setInputFiles('[data-post-upload]', { name: 'sunset.png', mimeType: 'image/png', buffer: PNG }); await pa.waitForSelector('[data-post-file="sunset.png"]')
await pa.click('[data-post-submit]'); await pa.waitForTimeout(1000)
const posts = await call(a.token, 'GET', `/channels/${media.id}/threads`)
const p1 = posts.find((t) => t.name === `Sunset ${S}`)
ok('the post is created with its image as cover', !!p1?.cover_url && p1.cover_type === 'image/png', JSON.stringify(p1))
await pa.keyboard.press('Escape'); await pa.goto(`${WEB}/channels/${ga.id}/${media.id}`); await pa.waitForTimeout(1000)
ok('the gallery shows the cover', await pa.locator(`[data-media-tile="${p1?.id}"] [data-media-cover]`).count() === 1)
const forum = await call(a.token, 'POST', `/guilds/${ga.id}/channels`, { name: 'talk', kind: 'forum' })
const up = await (await multi(a.token, `/channels/${forum.id}/attachments`, { name: 'x.png', mimeType: 'image/png', buffer: PNG })).json()
const fp = await call(a.token, 'POST', `/channels/${forum.id}/threads`, { name: 'With a picture', content: 'look', attachment_ids: [up.id] })
const fm = await call(a.token, 'GET', `/channels/${fp.id}/messages`)
ok('forum posts can carry files too', fm[fm.length - 1]?.attachments?.length === 1 || fm[0]?.attachments?.length === 1)

ok('no page errors', errors.length === 0, errors.join(' | '))
for (const [t, g] of [[a, ga], [b, gb]]) await call(t.token, 'DELETE', `/guilds/${g.id}`, { password: 'password1', name: g.name })
await browser.close(); await finish()
