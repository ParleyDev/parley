// Scheduled messages, like Discord's: schedule from the message box (right-click Send, the clock, "+", or a long press
// on a phone), see them in Inbox → Scheduled with Send Now / Edit / Delete, and the server sends them when due as you.
// Everyone gets the larger limit (30). Server managers turn them off server-wide (Overview) or per channel (the
// Schedule Messages permission).
import { chromium, devices } from 'playwright'
import { WEB, S, B, reg, call, callS, raw, ok, finish, pngFile } from '../lib.mjs'

const a = await reg('alice'), b = await reg('bob')
const g = await call(a.token, 'POST', '/guilds', { name: `Schedule ${S}` }); const ch = g.channels.find((x) => x.kind === 'text')
const inv = await call(a.token, 'POST', `/guilds/${g.id}/invites`, {}); await call(b.token, 'POST', `/invites/${inv.code}`)
const dm = await call(a.token, 'POST', '/users/@me/channels', { recipient_id: b.user.id })
const later = (ms) => new Date(Date.now() + ms).toISOString()
const HOUR = 3600_000
// Scheduling counts against the message rate limit: wait out a 429.
const post = async (t, p, body) => { for (;;) { const r = await raw(t, 'POST', p, body); if (r.status !== 429) return { status: r.status, body: await r.json().catch(() => null) }; await new Promise((res) => setTimeout(res, 1000)) } }
const list = (t) => call(t, 'GET', '/users/@me/scheduled-messages')

console.log('-- scheduling')
let r = await post(a.token, `/channels/${ch.id}/scheduled-messages`, { content: 'good morning team', send_at: later(HOUR) })
ok('a message can be scheduled in a server channel', r.status === 201 && r.body.status === 'pending' && r.body.content === 'good morning team', JSON.stringify(r))
const s1 = r.body
ok('and shows in your list', (await list(a.token)).some((x) => x.id === s1.id && x.guild_id === g.id))
ok("but not in anyone else's", !(await list(b.token)).some((x) => x.id === s1.id))
r = await post(a.token, `/channels/${dm.id}/scheduled-messages`, { content: 'happy birthday!', send_at: later(HOUR) })
ok('in a DM too', r.status === 201, JSON.stringify(r))
const sDm = r.body
r = await post(a.token, `/channels/${ch.id}/scheduled-messages`, { content: 'past', send_at: later(-60_000) })
ok('a time in the past is refused', r.status === 400)
r = await post(a.token, `/channels/${ch.id}/scheduled-messages`, { content: 'far', send_at: later(400 * 24 * HOUR) })
ok('more than a year ahead is refused', r.status === 400)
r = await post(a.token, `/channels/${ch.id}/scheduled-messages`, { content: '   ', send_at: later(HOUR) })
ok('an empty message is refused', r.status === 400)
r = await post(b.token, `/channels/${dm.id}/scheduled-messages`, { content: 'x', send_at: later(HOUR) })
const bobsOwn = r.body
r = await callS(a.token, 'PATCH', `/users/@me/scheduled-messages/${bobsOwn.id}`, { content: 'hijack' })
ok("someone else's scheduled message can't be edited", r.status === 404)

console.log('-- edit, send now, delete')
r = await callS(a.token, 'PATCH', `/users/@me/scheduled-messages/${s1.id}`, { content: 'good morning everyone', send_at: later(2 * HOUR) })
ok('edit changes the text and time', r.status === 200 && r.body.content === 'good morning everyone' && Math.abs(new Date(r.body.send_at) - Date.now() - 2 * HOUR) < 60_000, JSON.stringify(r))
r = await callS(a.token, 'POST', `/users/@me/scheduled-messages/${sDm.id}/send`)
ok('Send Now sends it straight away', r.status === 200 && r.body.content === 'happy birthday!' && r.body.channel_id === dm.id, JSON.stringify(r))
const dmMsgs = await call(b.token, 'GET', `/channels/${dm.id}/messages`)
ok('the other person gets it, from you', dmMsgs.some((m) => m.content === 'happy birthday!' && m.author.id === a.user.id))
ok('and it leaves the list', !(await list(a.token)).some((x) => x.id === sDm.id))
r = await callS(a.token, 'DELETE', `/users/@me/scheduled-messages/${s1.id}`)
ok('Delete cancels it', r.status === 204 && !(await list(a.token)).some((x) => x.id === s1.id))

console.log('-- replies and files')
const target = await call(b.token, 'POST', `/channels/${ch.id}/messages`, { content: 'who is coming friday?' })
const f = new FormData(); f.append('file', new Blob([pngFile.buffer], { type: 'image/png' }), 'plan.png')
const att = await (await fetch(`${B}/channels/${ch.id}/attachments`, { method: 'POST', headers: { Authorization: 'Bearer ' + a.token }, body: f })).json()
r = await post(a.token, `/channels/${ch.id}/scheduled-messages`, { content: 'me! here is the plan', send_at: later(HOUR), reply_to: target.id, attachment_ids: [att.id] })
ok('a reply with a file can be scheduled', r.status === 201 && r.body.attachments[0]?.filename === 'plan.png' && r.body.reply_to === target.id, JSON.stringify(r))
const sFile = r.body
r = await post(a.token, `/channels/${ch.id}/scheduled-messages`, { content: 'again', send_at: later(HOUR), attachment_ids: [att.id] })
ok('the same file cannot go in two scheduled messages', r.status === 400)
r = await callS(a.token, 'POST', `/users/@me/scheduled-messages/${sFile.id}/send`)
ok('sent, it keeps the reply and the file', r.status === 200 && r.body.reply_to === target.id, JSON.stringify(r.body?.reply_to))
ok('  (the file too)', r.body?.attachments?.[0]?.filename === 'plan.png')

console.log('-- the limit (30 for everyone)')
const made = []
for (let i = 0; i < 30; i++) { const x = await post(a.token, `/channels/${ch.id}/scheduled-messages`, { content: `bulk ${i}`, send_at: later(HOUR + i * 60_000) }); if (x.status === 201) made.push(x.body.id) }
ok('30 can be queued', made.length === 30, String(made.length))
r = await post(a.token, `/channels/${ch.id}/scheduled-messages`, { content: 'one too many', send_at: later(HOUR) })
ok('the 31st is refused', r.status === 400 && /30/.test(r.body?.error ?? r.body?.message ?? JSON.stringify(r.body)), JSON.stringify(r))
for (const id of made) await callS(a.token, 'DELETE', `/users/@me/scheduled-messages/${id}`)

console.log('-- server controls')
const SCHEDULE = 2 ** 31
r = await callS(a.token, 'PUT', `/channels/${ch.id}/permissions/${g.id}`, { kind: 'role', allow: 0, deny: SCHEDULE })
r = await post(b.token, `/channels/${ch.id}/scheduled-messages`, { content: 'nope', send_at: later(HOUR) })
ok('denying Schedule Messages on a channel keeps scheduled messages out of it', r.status === 400, JSON.stringify(r))
const ok2 = await post(b.token, `/channels/${ch.id}/messages`, { content: 'still can talk' })
ok('while members can still send there normally', ok2.status === 201)
await callS(a.token, 'DELETE', `/channels/${ch.id}/permissions/${g.id}`)
r = await post(b.token, `/channels/${ch.id}/scheduled-messages`, { content: 'yes', send_at: later(HOUR) })
ok('lifting it allows them again', r.status === 201)
const gUp = await callS(a.token, 'PATCH', `/guilds/${g.id}`, { scheduled_off: true })
ok('a manager can turn them off server-wide', gUp.status === 200 && gUp.body.scheduled_off === true, JSON.stringify(gUp.body?.scheduled_off))
r = await post(b.token, `/channels/${ch.id}/scheduled-messages`, { content: 'nope', send_at: later(HOUR) })
ok('then nobody can schedule there', r.status === 400 && /turned off/.test(JSON.stringify(r.body)))
r = await callS(b.token, 'PATCH', `/guilds/${g.id}`, { scheduled_off: false })
ok('members without Manage Server cannot turn them back on', r.status === 403)
await callS(a.token, 'PATCH', `/guilds/${g.id}`, { scheduled_off: false })
for (const x of await list(b.token)) await callS(b.token, 'DELETE', `/users/@me/scheduled-messages/${x.id}`)

console.log('-- sent when due (waits ~40s)')
const dueDm = await post(a.token, `/channels/${dm.id}/scheduled-messages`, { content: `on time ${S}`, send_at: later(32_000) })
const dueCh = await post(b.token, `/channels/${ch.id}/scheduled-messages`, { content: 'should fail', send_at: later(32_000) })
await callS(a.token, 'PUT', `/channels/${ch.id}/permissions/${b.user.id}`, { kind: 'member', allow: 0, deny: 2 ** 11 })
let delivered = false, failed = null
for (let i = 0; i < 30 && (!delivered || !failed); i++) {
  await new Promise((res) => setTimeout(res, 2000))
  delivered ||= (await call(b.token, 'GET', `/channels/${dm.id}/messages`)).some((m) => m.content === `on time ${S}` && m.author.id === a.user.id)
  failed ??= (await list(b.token)).find((x) => x.id === dueCh.body.id && x.status === 'failed') ?? null
}
ok('a due message is sent by the server, as you', delivered)
ok('and leaves your list', !(await list(a.token)).some((x) => x.id === dueDm.body.id))
ok('one that can no longer be sent stays in the list as failed, with why', !!failed && /no longer send/i.test(failed.error ?? ''), JSON.stringify(failed))
r = await callS(b.token, 'PATCH', `/users/@me/scheduled-messages/${dueCh.body.id}`, { send_at: later(HOUR) })
ok('rescheduling a failed message queues it again', r.status === 200 && r.body.status === 'pending' && r.body.error === null)
await callS(a.token, 'DELETE', `/channels/${ch.id}/permissions/${b.user.id}`)
await callS(b.token, 'DELETE', `/users/@me/scheduled-messages/${dueCh.body.id}`)
await callS(b.token, 'DELETE', `/users/@me/scheduled-messages/${bobsOwn.id}`)

console.log('-- desktop')
const browser = await chromium.launch(); const errors = []
const p = await browser.newPage({ viewport: { width: 1280, height: 800 } }); p.on('pageerror', (e) => errors.push(e.message))
await p.goto(`${WEB}/login`); await p.evaluate((t) => localStorage.setItem('parley.token', t), a.token)
await p.goto(`${WEB}/channels/${g.id}/${ch.id}`); await p.waitForSelector('[data-composer-box] textarea')
const box = p.locator('[data-composer-box] textarea')
await box.fill('standup in 10')
await p.click('[data-composer-send]', { button: 'right' })
await p.getByRole('menuitem', { name: 'Schedule Message' }).click()
await p.waitForSelector('[data-schedule-dialog]')
ok('right-clicking Send offers Schedule Message, which opens the dialog with your text', await p.inputValue('[data-schedule-text]') === 'standup in 10')
ok('with presets and Custom', await p.locator('[data-schedule-preset]').count() >= 5 && await p.locator('[data-schedule-preset="custom"]').count() === 1)
ok('Schedule waits for a time', await p.locator('[data-schedule-confirm]').isDisabled())
await p.click('[data-schedule-preset="tomorrow"]')
ok('a preset says when it sends', /Tomorrow at 9:00/.test(await p.textContent('[data-schedule-summary]')), await p.textContent('[data-schedule-summary]'))
await p.click('[data-schedule-confirm]')
await p.waitForSelector('[data-schedule-dialog]', { state: 'detached' })
ok('scheduling clears the box', await box.inputValue() === '')
await p.waitForSelector('[data-scheduled-here]')
ok('and the box says you have a scheduled message here', /1 scheduled message/.test(await p.textContent('[data-scheduled-here]')))
await p.screenshot({ path: 'scheduled-desktop.png' })
ok('the clock in the box opens it too', await p.locator('[data-schedule-button]').count() === 1)
await p.click('[data-composer-plus]')
ok('and so does "+"', await p.getByRole('menuitem', { name: 'Schedule Message' }).count() === 1)
await p.keyboard.press('Escape')

await p.click('[data-scheduled-view]')
await p.waitForSelector('[data-inbox-scheduled] [data-scheduled-item]')
const item = p.locator('[data-scheduled-item]').first()
ok('View opens Inbox → Scheduled with the message', /standup in 10/.test(await item.textContent()) && /Tomorrow at 9:00/.test(await item.textContent()))
await p.screenshot({ path: 'scheduled-inbox.png' })
await item.locator('[data-scheduled-edit]').click()
await p.waitForSelector('[data-schedule-dialog]')
ok('Edit opens the dialog with the text and its time', await p.inputValue('[data-schedule-text]') === 'standup in 10' && await p.locator('[data-schedule-custom]').count() === 1)
await p.fill('[data-schedule-text]', 'standup in 5')
await p.click('[data-schedule-confirm]')
await p.waitForSelector('[data-schedule-dialog]', { state: 'detached' })
await p.waitForFunction(() => /standup in 5/.test(document.querySelector('[data-scheduled-item]')?.textContent ?? ''))
ok('the inbox stays open and shows the edit', await p.locator('[data-inbox]').count() === 1)
await p.locator('[data-scheduled-item] [data-scheduled-send]').first().click()
await p.waitForSelector('[data-msg-id] >> text=standup in 5')
ok('Send Now posts it to the channel', true)
await p.waitForFunction(() => !document.querySelector('[data-scheduled-item]'))
ok('and empties the list', await p.locator('[data-scheduled-here]').count() === 0)
await p.keyboard.press('Escape')

await callS(a.token, 'PATCH', `/guilds/${g.id}`, { scheduled_off: true }); await p.waitForTimeout(800)
ok('turned off server-wide, the clock goes away', await p.locator('[data-schedule-button]').count() === 0)
await callS(a.token, 'PATCH', `/guilds/${g.id}`, { scheduled_off: false }); await p.waitForTimeout(800)
console.log('-- settings')
// Server Settings → Overview has the server-wide switch; channel permissions list Schedule Messages.
const st = await browser.newPage({ viewport: { width: 1280, height: 800 } }); st.on('pageerror', (e) => errors.push(e.message))
await st.goto(`${WEB}/login`); await st.evaluate((t) => localStorage.setItem('parley.token', t), a.token)
await st.goto(`${WEB}/channels/${g.id}/${ch.id}`); await st.waitForSelector('[data-composer-box]')
await st.click(`aside button:has-text("Schedule ${S}")`); await st.click('button:has-text("Server Settings")')
await st.waitForSelector('[data-scheduled-toggle]', { timeout: 8000 }).catch(() => {})
ok('Server Settings has the scheduled messages switch, on by default', await st.locator('[data-scheduled-toggle]').isChecked().catch(() => false))
await st.locator('[data-scheduled-toggle]').click().catch(() => {}); await st.waitForTimeout(600)
ok('switching it off saves', (await call(a.token, 'GET', `/guilds/${g.id}`)).scheduled_off === true)
await callS(a.token, 'PATCH', `/guilds/${g.id}`, { scheduled_off: false })
// Per channel it's a permission: Edit Channel → Permissions → Schedule Messages, deny for @everyone.
await st.keyboard.press('Escape'); await st.waitForTimeout(300)
await st.click(`[data-channel-row="${ch.name}"]`, { button: 'right' })
await st.click('[data-context-menu] [data-menu-item="Edit Channel"]')
await st.locator('[role=dialog] button:has-text("Permissions")').first().click()
const row = st.locator('[data-perm-row="SCHEDULE_MESSAGES"]')
await row.waitFor({ timeout: 5000 }).catch(() => {})
ok('channel permissions list Schedule Messages', await row.count() === 1)
await row.locator('button[title="Deny"]').click(); await st.waitForTimeout(800)
r = await post(b.token, `/channels/${ch.id}/scheduled-messages`, { content: 'blocked here', send_at: later(HOUR) })
ok('denying it there keeps members from scheduling in that channel', r.status === 400, JSON.stringify(r))
await st.screenshot({ path: 'scheduled-perm.png' })
await callS(a.token, 'DELETE', `/channels/${ch.id}/permissions/${g.id}`)
await st.close()

console.log('-- phone')
const ph = await (await browser.newContext({ ...devices['iPhone 13'] })).newPage(); ph.on('pageerror', (e) => errors.push(e.message))
await ph.goto(`${WEB}/login`); await ph.evaluate((t) => localStorage.setItem('parley.token', t), a.token)
await ph.goto(`${WEB}/channels/@me/${dm.id}`); await ph.waitForSelector('[data-composer-box] textarea'); await ph.waitForTimeout(1500)
await ph.locator('[data-composer-box] textarea').fill('see you tonight')
const sb = await ph.locator('[data-composer-send]').boundingBox()
const cdp = await ph.context().newCDPSession(ph)
const pt = [{ x: sb.x + sb.width / 2, y: sb.y + sb.height / 2 }]
await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: pt })
await ph.waitForTimeout(700)
await cdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] })
await ph.waitForTimeout(300)
ok('a long press on Send opens Schedule Message', await ph.locator('[data-schedule-dialog]').count() === 1)
ok('without sending the message', !(await call(a.token, 'GET', `/channels/${dm.id}/messages`)).some((m) => m.content === 'see you tonight'))
// Straight after the long press, as a finger would: the first tap must count.
await ph.tap('[data-schedule-preset="custom"]')
await ph.fill('[data-schedule-date]', new Date(Date.now() + 2 * 24 * HOUR).toLocaleDateString('en-CA'))
await ph.fill('[data-schedule-time]', '19:30')
ok('Custom takes a day and a time', /7:30/.test(await ph.textContent('[data-schedule-summary]')), await ph.textContent('[data-schedule-summary]'))
await ph.screenshot({ path: 'scheduled-phone.png' })
await ph.tap('[data-schedule-confirm]')
await ph.waitForSelector('[data-scheduled-here]')
const mine = (await list(a.token)).find((x) => x.content === 'see you tonight')
ok('scheduled from the phone, for the custom time', !!mine && new Date(mine.send_at).getUTCHours() === new Date(new Date().setHours(19, 30, 0, 0)).getUTCHours() && new Date(mine.send_at).getUTCMinutes() === 30, mine?.send_at)
await ph.click('[data-composer-plus]')
ok('"+" on a phone has Schedule', await ph.locator('[data-attach="schedule"]').count() === 1)
await ph.mouse.click(10, 10)
await ph.click('[data-scheduled-view]')
await ph.waitForSelector('[data-inbox-scheduled] [data-scheduled-item]')
ok('and the phone Inbox lists it under Scheduled', /see you tonight/.test(await ph.textContent('[data-inbox-scheduled]')))
await ph.locator('[data-scheduled-delete]').first().click()
await ph.waitForFunction(() => !document.querySelector('[data-scheduled-item]'))
ok('Delete removes it', !(await list(a.token)).some((x) => x.content === 'see you tonight'))

await ph.keyboard.press('Escape').catch(() => {}); await ph.mouse.click(200, 300); await ph.waitForTimeout(300)
await ph.locator('[data-composer-box] textarea').fill('a plain tap still sends')
await ph.tap('[data-composer-send]'); await ph.waitForTimeout(800)
ok('after all that, a plain tap on Send still just sends', (await call(a.token, 'GET', `/channels/${dm.id}/messages`)).some((m) => m.content === 'a plain tap still sends'))
ok('no page errors', errors.length === 0, errors.join(' | '))
await call(a.token, 'DELETE', `/guilds/${g.id}`, { password: 'password1', name: g.name })
await browser.close(); await finish()
