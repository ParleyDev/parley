// Server AFK channel and timeout (idle voice members are moved there and can't speak), a designated #rules channel
// (rulebook icon, linked from the welcome screen), and the welcome screen new members see once after joining.
import { chromium } from 'playwright'
import { WEB, S, reg, call, raw, ok, finish } from '../lib.mjs'
const a = await reg('alice'), b = await reg('bob'), c = await reg('carol')
const g = await call(a.token, 'POST', `/guilds`, { name: `Welcome ${S}` })
const general = g.channels.find((x) => x.kind === 'text'), vc = g.channels.find((x) => x.kind === 'voice')
const afk = await call(a.token, 'POST', `/guilds/${g.id}/channels`, { name: 'Sleepy', kind: 'voice' })
const rules = await call(a.token, 'POST', `/guilds/${g.id}/channels`, { name: 'rules', kind: 'text' })
const intro = await call(a.token, 'POST', `/guilds/${g.id}/channels`, { name: 'introductions', kind: 'text' })
const inv = await call(a.token, 'POST', `/guilds/${g.id}/invites`, {}); await call(b.token, 'POST', `/invites/${inv.code}`)
const browser = await chromium.launch({ args: ['--use-fake-ui-for-media-stream', '--use-fake-device-for-media-stream'] }); const errors = []
const mk = async (tok, path) => {
  const ctx = await browser.newContext({ viewport: { width: 1280, height: 860 }, permissions: ['microphone', 'camera'] })
  const p = await ctx.newPage(); p.on('pageerror', (e) => errors.push(e.message))
  await p.goto(`${WEB}/login`); await p.evaluate((t) => localStorage.setItem('parley.token', t), tok)
  await p.goto(`${WEB}${path}`); await p.waitForTimeout(1000)
  return p
}

console.log('-- settings')
ok('the AFK channel must be a voice channel', (await raw(a.token, 'PATCH', `/guilds/${g.id}`, { afk_channel_id: general.id })).status === 400)
ok('and the rules channel a text channel', (await raw(a.token, 'PATCH', `/guilds/${g.id}`, { rules_channel_id: vc.id })).status === 400)
ok('odd timeouts are refused', (await raw(a.token, 'PATCH', `/guilds/${g.id}`, { afk_timeout: 42 })).status === 400)
ok('members without Manage Server cannot set them', (await raw(b.token, 'PATCH', `/guilds/${g.id}`, { afk_channel_id: afk.id })).status === 403)
const pa = await mk(a.token, `/channels/${g.id}/${general.id}`)
await pa.locator(`button:has-text("Welcome ${S}")`).first().click(); await pa.click('text=Server Settings'); await pa.waitForSelector('[data-afk-channel]')
await pa.selectOption('[data-afk-channel]', afk.id); await pa.selectOption('[data-afk-timeout]', '60'); await pa.selectOption('[data-rules-channel]', rules.id)
await pa.click('button:has-text("Save Changes")'); await pa.waitForTimeout(600)
let gg = await call(a.token, 'GET', `/guilds/${g.id}`)
ok('Overview saves the inactive channel, timeout and rules channel', gg.afk_channel_id === afk.id && gg.afk_timeout === 60 && gg.rules_channel_id === rules.id, JSON.stringify([gg.afk_channel_id, gg.afk_timeout, gg.rules_channel_id]))
await pa.click('[data-settings-tab="welcome"]'); await pa.waitForSelector('[data-welcome-tab]')
await pa.check('[data-welcome-enabled]'); await pa.fill('[data-welcome-desc]', 'A cosy place for testing')
await pa.click('[data-welcome-add]'); await pa.selectOption('[data-welcome-pick="0"]', intro.id); await pa.fill('[data-welcome-text="0"]', 'Say hi'); await pa.fill('[data-welcome-emoji="0"]', '👋')
await pa.click('[data-welcome-preview]'); await pa.waitForSelector('[data-welcome-screen]')
ok('Preview shows the draft', /A cosy place/.test(await pa.locator('[data-welcome-screen]').innerText()))
await pa.click('[data-welcome-close]'); await pa.click('[data-welcome-save]'); await pa.waitForTimeout(600)
gg = await call(a.token, 'GET', `/guilds/${g.id}`)
ok('the welcome screen is saved', gg.welcome_screen?.enabled === true && gg.welcome_screen.channels?.[0]?.channel_id === intro.id && gg.welcome_screen.channels[0].emoji === '👋')
ok('more than five channels are refused', (await raw(a.token, 'PATCH', `/guilds/${g.id}`, { welcome_screen: { enabled: true, channels: Array(6).fill({ channel_id: intro.id }) } })).status === 400)
await pa.keyboard.press('Escape'); await pa.waitForTimeout(300)
ok('the rules channel gets a rulebook icon', await pa.locator(`[data-channel-item="${rules.id}"] [data-rules-icon]`).count() === 1)

console.log('-- welcome screen')
const pc = await mk(c.token, `/invite/${inv.code}`)
await pc.click('button:has-text("Accept Invite"), button:has-text("Join")'); await pc.waitForSelector('[data-welcome-screen]', { timeout: 10000 }).catch(() => {})
ok('a new member sees the welcome screen', await pc.locator('[data-welcome-screen]').count() === 1 && /Say hi/.test(await pc.locator('[data-welcome-screen]').innerText()))
ok('with a link to the rules', await pc.locator('[data-welcome-rules]').count() === 1)
await pc.click(`[data-welcome-channel="${intro.id}"]`); await pc.waitForTimeout(600)
ok('picking a channel goes there', new URL(pc.url()).pathname === `/channels/${g.id}/${intro.id}` && await pc.locator('[data-welcome-screen]').count() === 0)
await pc.goto(`${WEB}/channels/${g.id}/${general.id}`); await pc.waitForTimeout(1200)
ok('and it is shown only once', await pc.locator('[data-welcome-screen]').count() === 0)
const pb = await mk(b.token, `/channels/${g.id}/${vc.id}`)
ok('existing members are not shown it', await pb.locator('[data-welcome-screen]').count() === 0)

console.log('-- AFK')
await pb.click('text=Join Voice'); await pb.waitForSelector('[data-voice-leave]'); await pb.waitForTimeout(800)
ok('someone who just spoke is not moved', await pb.evaluate(() => window.__parleyAfk(0)) === false)
ok('after the timeout without speaking they are moved', await pb.evaluate(() => window.__parleyAfk(10 * 60_000)) === true)
await pb.waitForTimeout(2000)
ok('into the inactive channel', (await pb.evaluate(() => window.__parleyVoice().channel)) === afk.id)
ok('where they are silenced for everyone', await pa.locator(`[data-channel-item="${afk.id}"] [data-voice-silent="suppressed"]`).count() === 1)
ok('and are not moved again', await pb.evaluate(() => window.__parleyAfk(10 * 60_000)) === false)
ok('no page errors', errors.length === 0, errors.join(' | '))
await call(a.token, 'DELETE', `/guilds/${g.id}`, { password: 'password1', name: g.name })
await browser.close(); await finish()
