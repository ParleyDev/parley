// Server overview and safety settings: description, system channel, join notices with greetings and "Wave to say
// hi", default notifications, verification level (with role and owner exemptions and the composer explaining it),
// 2FA required for moderators (server and client), pausing invites (invite page too) and pausing DMs between members.
import { chromium } from 'playwright'
import { createHmac } from 'node:crypto'
import { WEB, S, PASSWORD, reg, call, raw, callS, ok, finish } from '../lib.mjs'
const b32 = (s) => { const A = 'ABCDEFGHIJKLMNOPQRSTUVWXYZ234567'; let bits = 0, val = 0; const out = []; for (const ch of s.toUpperCase()) { val = (val << 5) | A.indexOf(ch); bits += 5; if (bits >= 8) { out.push((val >>> (bits - 8)) & 255); bits -= 8 } } return Buffer.from(out) }
const totp = (secret) => { const msg = Buffer.alloc(8); msg.writeBigInt64BE(BigInt(Math.floor(Date.now() / 30000))); const h = createHmac('sha1', b32(secret)).update(msg).digest(); const o = h[19] & 15; const n = ((h[o] & 127) << 24) | (h[o + 1] << 16) | (h[o + 2] << 8) | h[o + 3]; return String(n % 1e6).padStart(6, '0') }
const a = await reg('alice'), b = await reg('bob')
const g = await call(a.token, 'POST', '/guilds', { name: `Safe ${S}` })
const general = g.channels.find((x) => x.kind === 'text')
const lobby = await call(a.token, 'POST', `/guilds/${g.id}/channels`, { name: 'lobby', kind: 'text' })
const inv = await call(a.token, 'POST', `/guilds/${g.id}/invites`, { max_age: 0, max_uses: 0 })
const patch = (t, body) => raw(t, 'PATCH', `/guilds/${g.id}`, body)
const notices = async (ch) => (await call(a.token, 'GET', `/channels/${ch}/messages?limit=50`)).filter((m) => m.kind === 'member_join')

console.log('-- overview and system messages')
ok('description over 300 characters is refused', (await patch(a.token, { description: 'x'.repeat(301) })).status === 400)
ok('the system channel must be a text channel here', (await patch(a.token, { system_channel_id: g.channels.find((x) => x.kind === 'voice').id })).status === 400)
let saved = await (await patch(a.token, { description: 'A calm place', system_channel_id: lobby.id, default_notifications: 'mentions' })).json()
ok('description, system channel and default notifications save', saved.description === 'A calm place' && saved.system_channel_id === lobby.id && saved.default_notifications === 'mentions')
await call(b.token, 'POST', `/invites/${inv.code}`)
ok('join notices go to the chosen channel', (await notices(lobby.id)).length === 1 && (await notices(general.id)).length === 0)

const browser = await chromium.launch(); const errors = []
const open = async (u, path = `/channels/${g.id}/${lobby.id}`) => {
  const p = await (await browser.newContext({ viewport: { width: 1280, height: 860 } })).newPage(); p.on('pageerror', (e) => errors.push(e.message))
  await p.goto(`${WEB}/login`); await p.evaluate((t) => localStorage.setItem('parley.token', t), u.token)
  await p.goto(WEB + path); await p.waitForTimeout(900)
  return p
}
const pa = await open(a)
const join = pa.locator(`[data-system="member_join"]`).first()
ok('the notice reads like a greeting with their name', (await join.locator('[data-join-greeting]').innerText()).includes(b.user.display_name ?? 'Bob'))
await join.locator('[data-wave]').click(); await pa.waitForTimeout(600)
const waveMsg = (await call(a.token, 'GET', `/channels/${lobby.id}/messages?limit=5`)).find((m) => m.content === '👋')
ok('Wave to say hi replies to the notice with 👋', !!waveMsg && waveMsg.reply_to === (await notices(lobby.id))[0].id)
ok('and the button says it waved', /Waved/.test(await join.locator('[data-wave]').innerText()))
const pb = await open(b)
ok('newcomers don\'t get a wave button on their own notice', await pb.locator('[data-system="member_join"] [data-wave]').count() === 0)
await patch(a.token, { join_wave: false }); await pa.waitForTimeout(500)
ok('turning waves off removes the button', await pa.locator('[data-system="member_join"] [data-wave]').count() === 0)
await pb.click(`[data-guild-icon="${g.id}"]`, { button: 'right' }); await pb.waitForSelector('[data-context-menu]')
await pb.hover('[data-context-menu] [data-menu-item="Notification Settings"]'); await pb.waitForTimeout(150)
ok('the server default shows as the member\'s notification level', await pb.locator('[data-context-menu] [data-menu-item="Only @mentions"] svg').count() === 1)
await pb.keyboard.press('Escape')
await patch(a.token, { join_notices: false })
const c = await reg('carol'); await call(c.token, 'POST', `/invites/${inv.code}`)
ok('with join notices off, nothing is posted', (await notices(lobby.id)).length === 1)

console.log('-- verification level')
await patch(a.token, { verification_level: 1 })
const blocked = await raw(c.token, 'POST', `/channels/${general.id}/messages`, { content: 'hi' })
ok('an unverified member without a role cannot talk', blocked.status === 400 && /verified email/.test((await blocked.json()).error))
ok('the owner is exempt', (await raw(a.token, 'POST', `/channels/${general.id}/messages`, { content: 'owner here' })).status === 201)
const pc = await open(c, `/channels/${g.id}/${general.id}`)
ok('the message box explains why', /verified email/.test(await pc.locator('[data-verification-gate]').innerText().catch(() => '')))
const helper = await call(a.token, 'POST', `/guilds/${g.id}/roles`, { name: 'Member' })
await call(a.token, 'PATCH', `/guilds/${g.id}/members/${c.user.id}`, { roles: [helper.id] })
ok('members with any role are exempt', (await raw(c.token, 'POST', `/channels/${general.id}/messages`, { content: 'with a role' })).status === 201)
await pc.waitForTimeout(500)
ok('and their message box comes back', await pc.locator('[data-verification-gate]').count() === 0 && await pc.locator('[data-composer-box]').count() === 1)
ok('levels stay within 0-3', (await patch(a.token, { verification_level: 4 })).status === 400)
await patch(a.token, { verification_level: 0 })

console.log('-- 2FA for moderators')
const mod = await call(a.token, 'POST', `/guilds/${g.id}/roles`, { name: 'Mod', permissions: 2 | 4 | 8192 })
await call(a.token, 'PATCH', `/guilds/${g.id}/members/${b.user.id}`, { roles: [mod.id] })
ok('only the owner can require 2FA', (await patch(b.token, { mfa_level: 1 })).status === 403)
ok('the owner needs 2FA themselves first', (await patch(a.token, { mfa_level: 1 })).status === 400)
const en = await callS(a.token, 'POST', '/users/@me/mfa/enroll', { password: PASSWORD })
await callS(a.token, 'POST', '/users/@me/mfa/confirm', { code: totp(en.body.secret) })
ok('with 2FA on, the owner can require it', (await patch(a.token, { mfa_level: 1 })).status === 200)
const kick = await raw(b.token, 'DELETE', `/guilds/${g.id}/members/${c.user.id}`)
ok('a moderator without 2FA loses kick', kick.status === 403)
const del = await raw(b.token, 'POST', `/channels/${general.id}/messages/bulk-delete`, { limit: 1 })
ok('and manage messages', del.status === 403)
await pb.reload(); await pb.waitForTimeout(900)
await pb.click(`[data-member-row="${c.user.id}"]`, { button: 'right' }); await pb.waitForSelector('[data-context-menu]')
ok('their menus drop the moderator actions too', await pb.locator('[data-context-menu] [data-menu-item^="Kick"]').count() === 0)
await pb.keyboard.press('Escape')
await patch(a.token, { mfa_level: 0 })
ok('back to normal once it is off', (await raw(b.token, 'POST', `/channels/${general.id}/messages/bulk-delete`, { limit: 1 })).status === 200)

console.log('-- pause invites')
await patch(a.token, { invites_paused: true })
const d = await reg('dave')
const preview = await call(d.token, 'GET', `/invites/${inv.code}`)
ok('the invite preview says joining is paused', preview.paused === true)
const refused = await raw(d.token, 'POST', `/invites/${inv.code}`)
ok('and joining is refused', refused.status === 400 && /paused/.test((await refused.json()).error))
const pd = await open(d, `/invite/${inv.code}`)
ok('the invite page explains it', await pd.locator('[data-invite-paused]').count() === 1)
await patch(a.token, { invites_paused: false })
ok('resuming lets them in', (await raw(d.token, 'POST', `/invites/${inv.code}`)).status === 200)

console.log('-- pause DMs')
const openDm = async (from, to) => { const ch = await call(from.token, 'POST', '/users/@me/channels', { recipient_id: to.user.id }); return raw(from.token, 'POST', `/channels/${ch.id}/messages`, { content: `hello ${Date.now()}` }) }
ok('members who only share this server can DM', (await openDm(d, c)).status === 201)
await patch(a.token, { pause_dms_hours: 2 })
ok('with DMs paused, they cannot', (await openDm(d, c)).status !== 201)
ok('pausing is limited to 24 hours', (await patch(a.token, { pause_dms_hours: 48 })).status === 400)
await patch(a.token, { pause_dms_hours: 0 })
ok('resuming restores it', (await openDm(d, c)).status === 201)

console.log('-- Safety tab')
await pa.reload(); await pa.waitForTimeout(800)
await pa.click(`aside button:has-text("Safe ${S}")`); await pa.click('text=Server Settings'); await pa.waitForTimeout(400)
await pa.click('[role=dialog] button:has-text("Safety")'); await pa.waitForSelector('[data-safety-tab]')
await pa.click('[data-pause-invites="off"]'); await pa.waitForTimeout(500)
const guildNow = async () => (await call(a.token, 'GET', `/guilds/${g.id}`))
ok('the Safety tab pauses invites', (await guildNow()).invites_paused === true)
await pa.click('[data-pause-invites="on"]'); await pa.click('[data-verification="2"]'); await pa.waitForTimeout(500)
ok('and sets the verification level', (await guildNow()).verification_level === 2 && (await guildNow()).invites_paused === false)
ok('no page errors', errors.length === 0, errors.join(' | '))
await call(a.token, 'DELETE', `/guilds/${g.id}`, { password: 'password1', name: g.name })
await browser.close(); await finish()
