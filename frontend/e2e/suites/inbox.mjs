// Notifications extras: server-side prefs (push timeout, email, join defaults), the mentions Inbox, the unread
// badge on the tab icon, text-to-speech, reply-mentions and role-mention suppression.
import { chromium } from 'playwright'
import { WEB, S, reg, call, raw, ok, finish, adminToken } from '../lib.mjs'
const admin = await adminToken()
const a = await reg('alice'); const b = await reg('bob')
const mailFor = async (to) => (await call(admin.token, 'GET', `/admin/mail?to=${encodeURIComponent(to)}`))
const g = await call(a.token, 'POST', '/guilds', { name: `Inbox ${S}` }); const tc = g.channels.find((x) => x.kind === 'text')
const inv = await call(a.token, 'POST', `/guilds/${g.id}/invites`, {})

console.log('-- prefs')
let r = await raw(b.token, 'PATCH', '/users/@me/notification-prefs', { bogus: 1 }); ok('unknown preference refused', r.status === 400)
r = await raw(b.token, 'PATCH', '/users/@me/notification-prefs', { push_timeout_min: 500, default_suppress_everyone: true }); let u = await r.json()
ok('prefs merge and clamp', r.status === 200 && u.notif_prefs.push_timeout_min === 120 && u.notif_prefs.default_suppress_everyone === true)
await call(b.token, 'POST', `/invites/${inv.code}`)
const ns = await call(b.token, 'GET', '/users/@me/notification-settings')
ok('joining a server applies the suppress-@everyone default', ns.some((n) => n.target_id === g.id && n.suppress_everyone === true))
await call(b.token, 'PUT', `/users/@me/notification-settings/${g.id}`, { suppress_roles: true })
ok('role-mention suppression is a per-target setting', (await call(b.token, 'GET', '/users/@me/notification-settings')).some((n) => n.target_id === g.id && n.suppress_roles === true))

console.log('-- email while offline')
const dm = await call(a.token, 'POST', '/users/@me/channels', { recipient_id: b.user.id })
await call(a.token, 'POST', `/channels/${dm.id}/messages`, { content: `mail me ${S}` }); await new Promise((r) => setTimeout(r, 800))
let mails = await mailFor(`bob${S}@x.io`)
ok('an offline user gets a mail about a DM', mails.some((m) => /New message from Alice/.test(m.subject) && m.body.includes(`mail me ${S}`)), JSON.stringify(mails.map((m) => m.subject)))
await call(a.token, 'POST', `/channels/${dm.id}/messages`, { content: 'again' }); await new Promise((r) => setTimeout(r, 800))
ok('…at most once an hour', (await mailFor(`bob${S}@x.io`)).filter((m) => /New message/.test(m.subject)).length === 1)
await call(a.token, 'POST', '/users/@me/relationships', { user_id: b.user.id }); await new Promise((r) => setTimeout(r, 500))
ok('a friend request mails too', (await mailFor(`bob${S}@x.io`)).some((m) => /friend request/.test(m.subject)))
await call(b.token, 'PATCH', '/users/@me/notification-prefs', { email_dms: false })
const c = await reg('carol'); const dmc = await call(c.token, 'POST', '/users/@me/channels', { recipient_id: b.user.id })
await call(b.token, 'POST', `/channels/${dmc.id}/request`, { action: 'accept' }).catch(() => {})
await call(a.token, 'PATCH', '/users/@me/notification-prefs', { email_dms: false })

console.log('-- inbox')
const men = await call(a.token, 'POST', `/channels/${tc.id}/messages`, { content: `hey <@${b.user.id}> look` })
const inbox = await call(b.token, 'GET', '/users/@me/mentions')
ok('recent mentions lists the message', inbox.some((m) => m.id === men.id) && !inbox.some((m) => m.author.id === b.user.id))
ok('others do not see it', !(await call(c.token, 'GET', '/users/@me/mentions')).some((m) => m.id === men.id))

console.log('-- UI')
const browser = await chromium.launch(); const errors = []
const ctx = await browser.newContext({ viewport: { width: 1280, height: 800 } }); const p = await ctx.newPage(); p.on('pageerror', (e) => errors.push(e.message))
await p.addInitScript(() => { Object.defineProperty(window, 'speechSynthesis', { value: { speak() {}, cancel() {} }, configurable: true }) })
await p.goto(`${WEB}/login`); await p.evaluate((t) => localStorage.setItem('parley.token', t), b.token)
await p.evaluate(() => localStorage.setItem('parley.notifications', JSON.stringify({ tts: 'all' })))
await p.goto(`${WEB}/channels/@me`); await p.waitForSelector('[data-user-panel-bar]')
await p.waitForFunction(() => document.querySelector('link[rel="icon"]')?.href.startsWith('data:'))
ok('the tab icon carries a badge while mentions and requests wait', await p.locator('[data-inbox-count]').count() === 1)
await p.click('[data-inbox-toggle]'); await p.waitForSelector(`[data-inbox-item="${men.id}"]`)
ok('the Inbox lists the mention with where it happened', (await p.textContent(`[data-inbox-item="${men.id}"]`)).includes(`#${tc.name}`))
await p.click(`[data-inbox-item="${men.id}"]`); await p.waitForSelector(`[data-msg-id="${men.id}"]`, { timeout: 15000 })
ok('clicking it jumps to the message', await p.evaluate((id) => { const r = document.querySelector(`[data-msg-id="${id}"]`).getBoundingClientRect(); return r.top >= 0 && r.bottom <= window.innerHeight }, men.id))
await p.waitForTimeout(800)
await call(a.token, 'POST', `/channels/${tc.id}/messages`, { content: 'read this aloud' }); await p.waitForTimeout(800)
ok('text-to-speech reads a notifying message', await p.evaluate(() => (window.__parleyTts ?? []).some((t) => /Alice said read this aloud/.test(t))), JSON.stringify(await p.evaluate(() => window.__parleyTts)))
// reply-mention: alice replies to bob's message → counts as a mention (sound + badge), unless turned off
const mine = await call(b.token, 'POST', `/channels/${tc.id}/messages`, { content: 'my own message' })
await p.goto(`${WEB}/channels/@me`); await p.waitForSelector('[data-user-panel-bar]'); await p.evaluate(() => { window.__parleySfx = [] })
await call(a.token, 'POST', `/channels/${tc.id}/messages`, { content: 'replying to you', reply_to: mine.id }); await p.waitForTimeout(800)
ok('a reply to your message plays the mention sound', await p.evaluate(() => (window.__parleySfx ?? []).includes('mention')), JSON.stringify(await p.evaluate(() => window.__parleySfx)))
await p.click('button[title="User Settings"]'); await p.click('text=Notifications'); await p.waitForSelector('[data-server-notif-prefs]')
ok('the Notifications tab shows the extra switches', await p.locator('[data-push-timeout]').count() === 1 && await p.locator('[data-tts="all"][data-on="1"]').count() === 1)
await p.fill('[data-push-timeout]', '25'); await p.locator('[data-push-timeout]').blur(); await p.waitForTimeout(500)
ok('the push timeout saves on blur', (await call(b.token, 'GET', '/users/@me')).notif_prefs.push_timeout_min === 25)
await p.screenshot({ path: '167-notifications.png' })
ok('no page errors', errors.length === 0, errors.join('\n'))
await browser.close(); await finish()
