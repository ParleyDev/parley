// Invite management: expiry and use-limit options, Server Settings › Invites (list, create, revoke) and vanity links
// for servers approved for Discovery.
import { chromium } from 'playwright'
import { WEB, S, reg, login, call, raw, ok, finish } from '../lib.mjs'
let admin = await reg('admin', 'admin-e2e@x.io'); if (!admin.token) admin = await login('admin-e2e@x.io')
const a = await reg('alice'), b = await reg('bob'), c = await reg('carol')
const g = await call(a.token, 'POST', '/guilds', { name: `Invite Lab ${S}` })
const join = await call(a.token, 'POST', `/guilds/${g.id}/invites`, {})
await call(b.token, 'POST', `/invites/${join.code}`)

console.log('-- REST: options')
let r = await raw(a.token, 'POST', `/guilds/${g.id}/invites`, { max_age: 1800, max_uses: 5 }); let inv = await r.json()
const age = (new Date(inv.expires_at) - new Date(inv.created_at)) / 1000
ok('30 minute, 5 use invite created', r.status === 201 && inv.max_uses === 5 && Math.abs(age - 1800) < 5 && inv.vanity === false, JSON.stringify(inv))
r = await raw(a.token, 'POST', `/guilds/${g.id}/invites`, { max_age: 0, max_uses: 0 }); inv = await r.json()
ok('never / no limit leaves both empty', r.status === 201 && inv.expires_at === null && inv.max_uses === null)
for (const s of [3600, 21600, 43200, 86400, 604800, 2592000]) {
  r = await raw(a.token, 'POST', `/guilds/${g.id}/invites`, { max_age: s }); ok(`max_age ${s} accepted`, r.status === 201)
}
for (const n of [1, 10, 25, 50, 100]) { r = await raw(a.token, 'POST', `/guilds/${g.id}/invites`, { max_uses: n }); ok(`max_uses ${n} accepted`, r.status === 201) }
ok('unlisted max_age refused', (await raw(a.token, 'POST', `/guilds/${g.id}/invites`, { max_age: 999 })).status === 400)
ok('unlisted max_uses refused', (await raw(a.token, 'POST', `/guilds/${g.id}/invites`, { max_uses: 7 })).status === 400)

console.log('-- REST: one-use invite')
const once = await call(a.token, 'POST', `/guilds/${g.id}/invites`, { max_uses: 1 })
ok('carol joins with the one-use invite', (await raw(c.token, 'POST', `/invites/${once.code}`)).status === 200)
await call(c.token, 'DELETE', `/guilds/${g.id}/members/@me`)
ok('preview shows it used up', (await call(c.token, 'GET', `/invites/${once.code}`)).expired === true)
ok('second use refused', (await raw(c.token, 'POST', `/invites/${once.code}`)).status === 400)

console.log('-- REST: list and revoke')
let list = await call(a.token, 'GET', `/guilds/${g.id}/invites`)
ok('list carries the inviter', list.length > 5 && list.every((i) => i.creator_display_name === 'Alice' && i.creator_username), JSON.stringify(list[0]))
ok('used-up invite is cleared from the list', !list.some((i) => i.code === once.code))
ok('bob (no Manage Server) cannot list', (await raw(b.token, 'GET', `/guilds/${g.id}/invites`)).status === 403)
const bobs = await call(b.token, 'POST', `/guilds/${g.id}/invites`, { max_age: 86400 })
ok('bob can create one (Create Invite)', !!bobs.code)
ok('bob cannot revoke alice\'s invite', (await raw(b.token, 'DELETE', `/guilds/${g.id}/invites/${join.code}`)).status === 403)
ok('bob revokes his own', (await raw(b.token, 'DELETE', `/guilds/${g.id}/invites/${bobs.code}`)).status === 204)
ok('revoked invite no longer resolves', (await raw(c.token, 'GET', `/invites/${bobs.code}`)).status === 404)

console.log('-- REST: vanity links')
r = await raw(a.token, 'POST', `/guilds/${g.id}/invites`, { vanity: `lab${S}` })
ok('vanity refused before Discovery approval', r.status === 403, String(r.status))
await call(a.token, 'PUT', `/guilds/${g.id}/discovery`, { description: 'A lab for testing invite links.', category: 'community' })
r = await raw(a.token, 'POST', `/guilds/${g.id}/invites`, { vanity: `lab${S}` })
ok('vanity refused while pending', r.status === 403)
await call(admin.token, 'POST', `/admin/discovery/${g.id}/review`, { status: 'approved' })
r = await raw(a.token, 'POST', `/guilds/${g.id}/invites`, { vanity: `Lab-${S}` }); const v1 = await r.json()
ok('vanity claimed once approved (lowercased)', r.status === 201 && v1.code === `lab-${S}` && v1.vanity && !v1.expires_at && !v1.max_uses, JSON.stringify(v1))
ok('bad vanity refused', (await raw(a.token, 'POST', `/guilds/${g.id}/invites`, { vanity: '-x' })).status === 400)
ok('taken vanity refused', (await raw(a.token, 'POST', `/guilds/${g.id}/invites`, { vanity: `LAB-${S}` })).status === 409)
const g2 = await call(b.token, 'POST', '/guilds', { name: `Other ${S}` })
ok('bob (no Manage Server) cannot claim one', (await raw(b.token, 'POST', `/guilds/${g.id}/invites`, { vanity: `bob${S}` })).status === 403)
await call(a.token, 'POST', `/guilds/${g.id}/invites`, { vanity: `lab2-${S}` })
await call(a.token, 'POST', `/guilds/${g.id}/invites`, { vanity: `lab3-${S}` })
r = await raw(a.token, 'POST', `/guilds/${g.id}/invites`, { vanity: `lab4-${S}` })
ok('fourth vanity refused', r.status === 400 && /3/.test((await r.json()).error))
const pv = await call(c.token, 'GET', `/invites/LAB-${S}`)
ok('vanity resolves in any case', pv.guild?.id === g.id && pv.code === `lab-${S}` && pv.expired === false, JSON.stringify(pv))
ok('carol joins through the vanity link', (await raw(c.token, 'POST', `/invites/Lab-${S}`)).status === 200)
list = await call(a.token, 'GET', `/guilds/${g.id}/invites`)
ok('vanity use counted', list.find((i) => i.code === `lab-${S}`)?.uses === 1)
await call(admin.token, 'POST', `/admin/discovery/${g.id}/review`, { status: 'rejected', note: 'test' })
ok('vanity stops resolving when no longer approved', (await raw(c.token, 'GET', `/invites/lab-${S}`)).status === 404)
await call(admin.token, 'POST', `/admin/discovery/${g.id}/review`, { status: 'approved' })
ok('and resolves again once re-approved', (await raw(c.token, 'GET', `/invites/lab-${S}`)).status === 200)
ok('vanity can be removed', (await raw(a.token, 'DELETE', `/guilds/${g.id}/invites/lab3-${S}`)).status === 204)
const audit = await call(a.token, 'GET', `/guilds/${g.id}/audit`)
ok('audit log records vanity and revokes', ['invite.vanity_create', 'invite.vanity_delete', 'invite.delete'].every((x) => audit.some((e) => e.action === x)), JSON.stringify(audit).slice(0, 300))
await call(b.token, 'DELETE', `/guilds/${g2.id}`, { password: 'password1', name: g2.name })

console.log('-- UI')
const browser = await chromium.launch()
const errors = []
const ctx = await browser.newContext({ viewport: { width: 1440, height: 900 } })
const p = await ctx.newPage(); p.on('pageerror', (e) => errors.push(e.message))
await p.goto(`${WEB}/login`); await p.evaluate((t) => localStorage.setItem('parley.token', t), a.token)
await p.goto(`${WEB}/channels/${g.id}`); await p.waitForTimeout(900)
await p.click(`aside button:has-text("Invite Lab")`); await p.click('text=Invite People'); await p.waitForSelector('[data-invite-summary]'); await p.waitForTimeout(500)
ok('invite modal says it never expires', /never expires/.test(await p.locator('[data-invite-summary]').innerText().catch(() => '')))
await p.click('[data-invite-edit]'); await p.waitForTimeout(200)
ok('expiry offers all eight options', (await p.locator('[data-invite-expiry] option').allInnerTexts()).join('|') === '30 minutes|1 hour|6 hours|12 hours|1 day|7 days|30 days|Never')
ok('uses offers no limit and six counts', (await p.locator('[data-invite-uses] option').allInnerTexts()).join('|') === 'No limit|1 use|5 uses|10 uses|25 uses|50 uses|100 uses')
await p.selectOption('[data-invite-expiry]', '43200'); await p.selectOption('[data-invite-uses]', '10')
await p.click('[data-invite-generate]'); await p.waitForTimeout(600)
const summary = await p.locator('[data-invite-summary]').innerText()
ok('new link summary', /expires in 12 hours and can be used 10 times/.test(summary), summary)
const code = (await p.locator('[role=dialog] input[readonly]').inputValue()).split('/invite/')[1]
list = await call(a.token, 'GET', `/guilds/${g.id}/invites`)
const made = list.find((i) => i.code === code)
ok('generated invite has the chosen limits', made?.max_uses === 10 && Math.abs((new Date(made.expires_at) - new Date(made.created_at)) / 1000 - 43200) < 5, JSON.stringify(made))
await p.keyboard.press('Escape'); await p.waitForTimeout(300)

const openInvites = async (name, gid) => {
  await p.keyboard.press('Escape'); await p.waitForTimeout(200)
  if (gid) { await p.goto(`${WEB}/channels/${gid}`); await p.waitForTimeout(900) }
  await p.click(`aside button:has-text("${name}")`); await p.click('text=Server Settings'); await p.waitForTimeout(400)
  await p.click('[role=dialog] button:has-text("Invites")'); await p.waitForTimeout(800)
}
await openInvites('Invite Lab')
ok('invites tab shows', await p.locator('[data-invites-tab]').count() === 1)
ok('vanity links listed', await p.locator('[data-vanity]').count() === 2)
ok('active invites listed with uses and expiry', await p.locator(`[data-invite-row="${code}"] [data-invite-uses-cell]`).innerText() === '0 / 10' && /in 1[12] hours/.test(await p.locator(`[data-invite-row="${code}"] [data-invite-expires]`).innerText()))
await p.fill('[data-vanity-input]', `ui ${S}!`); ok('vanity input keeps only allowed characters', (await p.inputValue('[data-vanity-input]')) === `ui${S}`)
await p.click('[data-vanity-add]'); await p.waitForTimeout(600)
ok('vanity added from the UI', await p.locator(`[data-vanity="ui${S}"]`).count() === 1 && /all 3 vanity links/.test(await p.locator('[data-vanity-section]').innerText()))
await p.click(`[data-vanity-remove="ui${S}"]`); await p.waitForTimeout(200)
ok('vanity removal asks first', await p.locator(`[data-vanity="ui${S}"]`).count() === 1 && await p.locator(`[data-vanity-remove-confirm="ui${S}"]`).count() === 1)
await p.click(`[data-vanity-remove-confirm="ui${S}"]`); await p.waitForTimeout(600)
ok('vanity removed from the UI', await p.locator(`[data-vanity="ui${S}"]`).count() === 0 && (await call(a.token, 'GET', `/guilds/${g.id}/invites`)).every((i) => i.code !== `ui${S}`))
await p.selectOption('[data-new-invite-expiry]', '1800'); await p.selectOption('[data-new-invite-uses]', '1')
const before = await p.locator('[data-invite-row]').count()
await p.click('[data-new-invite]'); await p.waitForTimeout(600)
ok('create from the tab adds a row', await p.locator('[data-invite-row]').count() === before + 1)
const first = await p.locator('[data-invite-row]').first().getAttribute('data-invite-row')
ok('it expires in 30 minutes', /in (29|30) minutes/.test(await p.locator(`[data-invite-row="${first}"] [data-invite-expires]`).innerText()))
await p.click(`[data-invite-revoke="${first}"]`); await p.waitForTimeout(600)
ok('revoked from the UI', await p.locator(`[data-invite-row="${first}"]`).count() === 0 && (await raw(c.token, 'GET', `/invites/${first}`)).status === 404)

// A server that isn't approved sees the Discovery hint instead.
const g3 = await call(a.token, 'POST', '/guilds', { name: `Plain ${S}` })
await p.waitForTimeout(600); await openInvites(`Plain ${S}`, g3.id)
ok('unapproved server sees the Discovery hint', await p.locator('[data-vanity-locked]').count() === 1)
// Phone width: no sideways scroll.
await openInvites('Invite Lab', g.id)
await p.setViewportSize({ width: 390, height: 800 }); await p.waitForTimeout(300)
ok('phone: tab fits the width', await p.evaluate(() => { const t = document.querySelector('[data-invites-tab]'); return !!t && t.scrollWidth <= t.clientWidth + 1 }))
ok('no page errors', errors.length === 0, errors.join(' | '))
await call(a.token, 'DELETE', `/guilds/${g3.id}`, { password: 'password1', name: g3.name })
await call(a.token, 'DELETE', `/guilds/${g.id}`, { password: 'password1', name: g.name })
await browser.close()
await finish()
