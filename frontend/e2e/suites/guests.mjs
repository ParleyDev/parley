// Try Parley without an account: an admin picks a demo server, and anyone can join it as a guest from /try or the
// login page. Guests stay in that server (no other servers, DMs or friends), post at a tighter rate, can claim the
// account with an email and password, and are removed an hour after they were last active.
import { execSync } from 'node:child_process'
import { chromium } from 'playwright'
import { WEB, B, S, H, reg, call, callS, raw, ok, finish, adminToken, testContainer } from '../lib.mjs'

const sql = (q) => execSync(`docker exec ${testContainer('db')} psql -U parley -tAc "${q.replace(/"/g, '\\"')}"`, { stdio: ['pipe', 'pipe', 'pipe'] }).toString().trim()
const admin = await adminToken()
const a = await reg('alice'), b = await reg('bob')
const demo = await call(a.token, 'POST', '/guilds', { name: `Demo ${S}` }); const general = demo.channels.find((x) => x.kind === 'text')
const other = await call(a.token, 'POST', '/guilds', { name: `Other ${S}` })
const inv = await call(a.token, 'POST', `/guilds/${other.id}/invites`, {})
const settings = await call(admin.token, 'GET', '/admin/settings')
const setDemo = (id) => callS(admin.token, 'PUT', '/admin/settings', { ...settings, demo_guild_id: id })
const guest = async (ip, body = {}) => { const r = await fetch(`${B}/auth/guest`, { method: 'POST', headers: { ...H, 'X-Forwarded-For': ip }, body: JSON.stringify(body) }); return { status: r.status, body: await r.json().catch(() => null) } }
const ipOf = (n) => `10.77.${S % 250}.${n}`

console.log('-- off by default')
await setDemo('')
let r = await guest(ipOf(1))
ok('no demo server: guests are off', r.status === 404, JSON.stringify(r))
ok('and /instance says so', (await (await fetch(`${B}/instance`)).json()).guests === false)

console.log('-- admin setting')
r = await callS(a.token, 'PUT', '/admin/settings', { ...settings, demo_guild_id: demo.id })
ok('only admins pick the demo server', r.status === 403)
r = await setDemo('not-a-server')
ok('a bad server id is refused', r.status === 400)
r = await setDemo(demo.id)
ok('an admin can pick one', r.status === 200 && r.body.demo_guild_id === demo.id && r.body.guests === true, JSON.stringify(r.body?.demo_guild_id))
ok('/instance now offers guests', (await (await fetch(`${B}/instance`)).json()).guests === true)

console.log('-- a guest')
r = await guest(ipOf(2), { display_name: 'Curious Cat' })
ok('anyone can start a guest session', r.status === 200 && r.body.token && r.body.user.guest === true && r.body.guild_id === demo.id, JSON.stringify(r))
const g1 = r.body
ok('with the name they chose and a guest_ username', g1.user.display_name === 'Curious Cat' && g1.user.username.startsWith('guest_'))
ok('already in the demo server', (await call(g1.token, 'GET', '/guilds')).some((x) => x.id === demo.id))
r = await callS(g1.token, 'POST', `/channels/${general.id}/messages`, { content: 'hi from a guest' })
ok('they can chat there', r.status === 201 || r.status === 200, JSON.stringify(r))
ok('members see a Guest badge on them', (await call(a.token, 'GET', `/users/${g1.user.id}`)).badges?.includes('guest'))
r = await guest(ipOf(3))
ok('without a name they get "Guest XXXX"', /^Guest [A-Z0-9]{4}$/.test(r.body?.user?.display_name ?? ''), r.body?.user?.display_name)
const g2 = r.body

console.log('-- limits')
r = await callS(g1.token, 'POST', '/guilds', { name: 'mine' })
ok("can't create a server", r.status === 403 && r.body?.code === 'guest', JSON.stringify(r))
r = await callS(g1.token, 'POST', `/invites/${inv.code}`)
ok("can't join another server by invite", r.status === 403 && r.body?.code === 'guest')
ok('  (and is not in it)', !(await call(g1.token, 'GET', '/guilds')).some((x) => x.id === other.id))
r = await callS(g1.token, 'POST', '/users/@me/channels', { recipient_id: a.user.id })
ok("can't open a DM", r.status === 403 && r.body?.code === 'guest')
r = await callS(a.token, 'POST', '/users/@me/channels', { recipient_id: g1.user.id })
ok("and nobody can DM them", r.status === 400)
r = await callS(g1.token, 'POST', '/users/@me/relationships', { user_id: a.user.id })
ok("can't send friend requests", r.status === 403 && r.body?.code === 'guest')
r = await callS(a.token, 'POST', '/users/@me/relationships', { user_id: g1.user.id })
ok("or get them", r.status === 400)
r = await callS(g1.token, 'POST', '/applications', { name: 'bot' })
ok("can't create apps", r.status === 403)
let limited = false
for (let i = 0; i < 8 && !limited; i++) { const x = await raw(g2.token, 'POST', `/channels/${general.id}/messages`, { content: `spam ${i}` }); limited = x.status === 429 }
ok('a tighter message rate than normal accounts', limited)
ok("guest names can't be registered", (await fetch(`${B}/auth/register`, { method: 'POST', headers: H, body: JSON.stringify({ username: `guest_${S}`, email: `g${S}@x.io`, password: 'password1' }) })).status === 400)
let tooMany = false
for (let i = 0; i < 6 && !tooMany; i++) tooMany = (await guest(ipOf(9))).status === 429
ok('a handful of guests per network an hour', tooMany)
for (const id of sql(`SELECT id FROM users WHERE guest AND display_name LIKE 'Guest %' AND created_at > now() - interval '1 minute' AND id <> '${g2.user.id}'`).split('\n').filter(Boolean)) sql(`DELETE FROM users WHERE id = '${id}'`)

console.log('-- claim')
r = await callS(g1.token, 'POST', '/auth/claim', { username: `guest_x${S}`, email: `cat${S}@x.io`, password: 'password1' })
ok('a guest_ username is refused on claim', r.status === 400)
r = await callS(g1.token, 'POST', '/auth/claim', { username: a.user.username, email: `cat${S}@x.io`, password: 'password1' })
ok('a taken username is refused', r.status === 409)
r = await callS(g1.token, 'POST', '/auth/claim', { username: `cat${S}`, email: `cat${S}@x.io`, password: 'password1' })
ok('claiming keeps the account', r.status === 200 && r.body.guest === false && r.body.username === `cat${S}`, JSON.stringify(r))
const login = await (await fetch(`${B}/auth/login`, { method: 'POST', headers: H, body: JSON.stringify({ login: `cat${S}`, password: 'password1' }) })).json()
ok('and they can log in with it', login.user?.id === g1.user.id)
ok('their messages are still there', (await call(a.token, 'GET', `/channels/${general.id}/messages`)).some((m) => m.content === 'hi from a guest' && m.author.id === g1.user.id))
r = await callS(g1.token, 'POST', `/invites/${inv.code}`)
ok('and the limits are gone', r.status === 200)
r = await callS(a.token, 'POST', '/auth/claim', { username: 'x', email: 'x@x.io', password: 'password1' })
ok('a normal account has nothing to claim', r.status === 400)
sql(`DELETE FROM users WHERE id = '${g1.user.id}'`)

console.log('-- removal')
const g3 = (await guest(ipOf(4))).body
r = await callS(g3.token, 'POST', '/auth/logout')
ok('logging out of a guest removes it at once', r.status === 204 && sql(`SELECT count(*) FROM users WHERE id = '${g3.user.id}'`) === '0')
sql(`UPDATE users SET guest_seen_at = now() - interval '2 hours' WHERE id = '${g2.user.id}'`)
sql(`UPDATE sessions SET last_seen_at = now() - interval '2 hours' WHERE user_id = '${g2.user.id}'`)
let gone = false
for (let i = 0; i < 80 && !gone; i++) { await new Promise((res) => setTimeout(res, 1000)); gone = sql(`SELECT count(*) FROM users WHERE id = '${g2.user.id}'`) === '0' }
ok('a guest idle for an hour is removed by the sweep', gone)
ok('  with its messages', !(await call(a.token, 'GET', `/channels/${general.id}/messages?limit=100`)).some((m) => m.author.id === g2.user.id && m.content.startsWith('spam')))
const g4 = (await guest(ipOf(5))).body
sql(`UPDATE users SET guest_seen_at = now() - interval '30 minutes' WHERE id = '${g4.user.id}'`)
sql(`UPDATE sessions SET last_seen_at = now() - interval '30 minutes' WHERE user_id = '${g4.user.id}'`)
ok('one idle for half an hour stays', sql(`SELECT count(*) FROM users WHERE id = '${g4.user.id}'`) === '1')
sql(`DELETE FROM users WHERE id = '${g4.user.id}'`)

console.log('-- UI')
const browser = await chromium.launch()
const ctx = await browser.newContext({ viewport: { width: 1280, height: 800 }, extraHTTPHeaders: { 'X-Forwarded-For': ipOf(20) } })
let p = await ctx.newPage()
await p.goto(`${WEB}/login`)
await p.waitForSelector('[data-try-guest-button]', { timeout: 10000 })
ok('the login page offers "Try it without an account"', true)
await p.screenshot({ path: 'guests-login.png' })
await p.click('[data-try-guest-button]')
await p.waitForSelector('[data-guest-banner]', { timeout: 15000 })
ok('one click lands in the app with a guest banner', true)
ok('  inside the demo server', p.url().includes(`/channels/${demo.id}`), p.url())
ok('no Add a Server button for guests', (await p.locator('[data-add-server]').count()) === 0)
await p.screenshot({ path: 'guests-app.png' })
await p.click('[data-guest-claim]')
await p.fill('[data-claim-email]', `dog${S}@x.io`); await p.fill('[data-claim-username]', `dog${S}`); await p.fill('[data-claim-password]', 'password1')
await p.screenshot({ path: 'guests-claim.png' })
await p.click('[data-claim-submit]')
await p.waitForSelector('[data-guest-banner]', { state: 'detached', timeout: 10000 }).catch(() => {})
ok('Sign up to keep it turns the guest into a normal account', (await p.locator('[data-guest-banner]').count()) === 0 && (await p.locator('[data-add-server]').count()) === 1)
const dogId = sql(`SELECT id FROM users WHERE username = 'dog${S}'`)
ok('  (saved as dog)', !!dogId && sql(`SELECT guest FROM users WHERE id = '${dogId}'`) === 'f')
await ctx.close()

const ctx2 = await browser.newContext({ viewport: { width: 390, height: 800 }, extraHTTPHeaders: { 'X-Forwarded-For': ipOf(21) } })
p = await ctx2.newPage()
await p.goto(`${WEB}/try`)
await p.waitForSelector('[data-guest-banner]', { timeout: 15000 }).catch(() => {})
ok('/try goes straight into the demo server as a guest', p.url().includes(`/channels/${demo.id}`) && (await p.locator('[data-guest-banner]').count()) === 1, p.url())
await p.screenshot({ path: 'guests-phone.png' })
const tryId = await p.evaluate(() => localStorage.getItem('parley.token'))
ok('a guest is never saved in the account switcher', !(await p.evaluate(() => localStorage.getItem('parley.accounts') ?? '')).includes(tryId ?? 'none'))
await ctx2.close()

await setDemo('')
const ctx3 = await browser.newContext({ extraHTTPHeaders: { 'X-Forwarded-For': ipOf(22) } })
p = await ctx3.newPage()
await p.goto(`${WEB}/try`)
await p.waitForSelector('[data-try-error]', { timeout: 10000 }).catch(() => {})
ok('with guests off, /try explains and offers sign-up', (await p.locator('[data-try-error]').count()) === 1)
await p.goto(`${WEB}/login`); await p.waitForTimeout(1000)
ok('and the login page hides the button', (await p.locator('[data-try-guest-button]').count()) === 0)
await browser.close()
for (const id of sql(`SELECT id FROM users WHERE guest AND created_at > now() - interval '10 minutes'`).split('\n').filter(Boolean)) sql(`DELETE FROM users WHERE id = '${id}'`)
if (dogId) sql(`DELETE FROM users WHERE id = '${dogId}'`)
await finish()
