// Server tags (wear a server's official tag), the partnered badge, and the year in review.
import { chromium } from 'playwright'
import { WEB, S, reg, call, raw, ok, finish, adminToken, openProfileEditor } from '../lib.mjs'
const owner = await reg('owner'), a = await reg('alice'), b = await reg('bob')
const g = await call(owner.token, 'POST', '/guilds', { name: `Tags ${S}` })
const ch = g.channels.find((x) => x.kind === 'text')
const inv = await call(owner.token, 'POST', `/guilds/${g.id}/invites`, {}); for (const u of [a, b]) await call(u.token, 'POST', `/invites/${inv.code}`)

console.log('-- server tags')
ok('members can\'t set the server\'s tag', (await raw(a.token, 'PUT', `/guilds/${g.id}/tag`, { tag: 'NOPE' })).status === 403)
ok('tags are 2-4 letters', (await raw(owner.token, 'PUT', `/guilds/${g.id}/tag`, { tag: 'TOOLONG' })).status === 400)
ok('you can\'t wear a tag before the server has one', (await raw(a.token, 'PUT', '/users/@me/server-tag', { guild_id: g.id })).status === 400)
const browser = await chromium.launch(); const errors = []
const ctx = async (t) => { const p = await (await browser.newContext({ viewport: { width: 1280, height: 900 } })).newPage(); p.on('pageerror', (x) => errors.push(x.message)); await p.goto(`${WEB}/login`); await p.evaluate((x) => localStorage.setItem('parley.token', x), t); return p }
const po = await ctx(owner.token)
await po.goto(`${WEB}/channels/${g.id}/${ch.id}`); await po.waitForTimeout(800)
await po.locator(`button:has-text("Tags ${S}")`).first().click(); await po.click('text=Server Settings'); await po.waitForSelector('[data-settings-nav]')
const secs = (await po.locator('[data-settings-section]').allInnerTexts()).join('|')
ok('settings are grouped like Discord (Expression, People, Apps, Moderation)', ['Expression', 'People', 'Apps', 'Moderation'].every((x) => secs.includes(x)), secs)
await po.click('[data-settings-tab="tag"]'); await po.waitForSelector('[data-server-tag-page]')
ok('Server Tag has its own page with a live preview', await po.locator('[data-server-tag-preview]').count() === 1 && await po.locator('[data-tag-badge-option]').count() >= 10 && await po.locator('[data-tag-color-option]').count() >= 10)
await po.fill('[data-server-tag-input]', 'fox!')
ok('names are letters and digits, max 4', (await po.inputValue('[data-server-tag-input]')) === 'FOX')
await po.click('[data-tag-show-all]'); await po.click('[data-tag-badge-option="🦊"]'); await po.click('[data-tag-color-option="#e0884a"]')
ok('the preview wears it', (await po.locator('[data-server-tag-preview]').innerText()).includes('FOX'))
await po.click('[data-server-tag-save]'); await po.waitForSelector('[data-server-tag-savebar]', { state: 'detached' })
const saved = await call(owner.token, 'GET', `/guilds/${g.id}`)
ok('the owner saves name, badge and colour', saved.tag === 'FOX' && saved.tag_badge === '🦊' && saved.tag_color === '#e0884a', JSON.stringify([saved.tag, saved.tag_badge, saved.tag_color]))
ok('colours are #rrggbb', (await raw(owner.token, 'PUT', `/guilds/${g.id}/tag`, { tag: 'FOX', badge: '🦊', color: 'red' })).status === 400)
await po.keyboard.press('Escape')
const pa = await ctx(a.token)
await pa.goto(`${WEB}/channels/@me`); await openProfileEditor(pa, { section: 'tag' })
await pa.waitForSelector('[data-wear-tag-select]'); await pa.selectOption('[data-wear-tag-select]', g.id); await pa.waitForTimeout(600)
let me = await call(a.token, 'GET', '/users/@me')
ok('a member wears it from Profiles', me.clan_tag === 'FOX' && me.clan_tag_guild === g.id)
ok('and the profile form shows it', (await pa.inputValue('[data-clan-tag-input]')) === 'FOX')
await pa.keyboard.press('Escape')
await call(a.token, 'POST', `/channels/${ch.id}/messages`, { content: `tagged ${S}` })
await po.goto(`${WEB}/channels/${g.id}/${ch.id}`); await po.waitForSelector(`[data-msg-id] [data-server-tag="${g.id}"]`)
ok('it shows next to their name with the badge', (await po.locator(`[data-server-tag="${g.id}"]`).first().innerText()).includes('🦊'))
ok('in the server colour', /rgb/.test(await po.locator(`[data-server-tag="${g.id}"]`).first().evaluate((e) => e.style.background)))

console.log('-- the server behind a tag')
const out = await reg('outsider')
ok('anyone can see the server behind a tag', (await call(out.token, 'GET', `/guilds/${g.id}/tag-card`)).name === `Tags ${S}`)
const plain = await call(owner.token, 'POST', '/guilds', { name: `Plain ${S}` })
ok('but not servers without one', (await raw(out.token, 'GET', `/guilds/${plain.id}/tag-card`)).status === 404)
await call(owner.token, 'DELETE', `/guilds/${plain.id}`)
let tc = await call(out.token, 'GET', `/guilds/${g.id}/tag-card`)
ok('an invite-only server offers no way in', tc.join === null && !tc.member && tc.member_count === 3)
ok('and joining from the tag is refused', (await raw(out.token, 'POST', `/guilds/${g.id}/tag-join`)).status === 403)
await po.click(`[data-msg-id] [data-server-tag="${g.id}"]`); await po.waitForSelector(`[data-server-tag-card="${g.id}"] [data-server-tag-go]`)
ok('clicking a tag opens the server card; members can go there', (await po.locator('[data-server-tag-card-name]').innerText()) === `Tags ${S}`)
await po.keyboard.press('Escape')
await raw(owner.token, 'PUT', `/guilds/${g.id}/application-form`, { enabled: true, questions: [{ title: 'Why join?', paragraph: false, required: false }] })
tc = await call(out.token, 'GET', `/guilds/${g.id}/tag-card`)
ok('with applications on, outsiders can apply', tc.join === 'apply', JSON.stringify(tc))
const po2 = await ctx(out.token)
await call(a.token, 'POST', `/channels/${ch.id}/messages`, { content: `hello outsider ${S}` })
const dmo = await call(a.token, 'POST', '/users/@me/channels', { recipient_id: out.user.id })
if (dmo?.id) { await call(a.token, 'POST', `/channels/${dmo.id}/messages`, { content: `see my tag ${S}` }) }
await po2.goto(`${WEB}/channels/@me/${dmo?.id ?? ''}`); await po2.waitForSelector(`[data-server-tag="${g.id}"]`, { timeout: 8000 }).catch(() => {})
if (await po2.locator(`[data-server-tag="${g.id}"]`).count()) {
  await po2.locator(`[data-server-tag="${g.id}"]`).first().click(); await po2.waitForSelector('[data-server-tag-join="apply"]')
  await po2.click('[data-server-tag-join="apply"]'); await po2.waitForURL(new RegExp(`/channels/${g.id}`), { timeout: 8000 }).catch(() => {})
  ok('Apply to Join takes them in as an applicant', (await call(out.token, 'GET', `/guilds/${g.id}/tag-card`)).member === true && po2.url().includes(g.id))
} else ok('the outsider sees the tag in a DM', false)
await raw(owner.token, 'PUT', `/guilds/${g.id}/application-form`, { enabled: false, questions: [] })
await call(owner.token, 'PUT', `/guilds/${g.id}/tag`, { tag: 'WOLF', badge: '🐺' })
ok('changing the server\'s tag changes theirs', (await call(a.token, 'GET', '/users/@me')).clan_tag === 'WOLF')
await call(a.token, 'PATCH', '/users/@me', { clan_tag: 'WOLF' })
ok('saving the same text keeps it the server\'s', (await call(a.token, 'GET', '/users/@me')).clan_tag_guild === g.id)
await call(a.token, 'DELETE', `/guilds/${g.id}/members/@me`)
me = await call(a.token, 'GET', '/users/@me')
ok('leaving the server takes it off', me.clan_tag === '' && !me.clan_tag_guild)

console.log('-- partnered')
const admin = await adminToken()
const listed = await raw(owner.token, 'PUT', `/guilds/${g.id}/discovery`, { description: 'A place for foxes and wolves to chat together', category: 'gaming' })
const r = await raw(admin.token, 'PATCH', `/admin/discovery/${g.id}`, { partnered: true })
ok('admins mark a listed server partnered', listed.status === 200 && r.status === 200 && (await call(owner.token, 'GET', `/guilds/${g.id}`)).partnered === true, `${listed.status} ${r.status} ${listed.status !== 200 ? await listed.text() : ''}`)
await po.reload(); await po.waitForSelector('[data-partnered]', { timeout: 5000 }).catch(() => {})
ok('the server header shows the badge', await po.locator('[data-partnered]').count() >= 1)

console.log('-- recap')
for (const t of ['one', 'two', 'three']) await call(b.token, 'POST', `/channels/${ch.id}/messages`, { content: `${t} ${S}` })
const rec = await call(b.token, 'GET', '/users/@me/recap')
ok('the recap counts your messages and servers', rec.messages === 3 && rec.top_servers[0]?.name === `Tags ${S}` && rec.months.length === 12)
const pb = await ctx(b.token)
await pb.goto(`${WEB}/channels/@me`); await pb.click('[data-control="User Settings"]'); await pb.click('[data-open-recap]'); await pb.waitForSelector('[data-recap-stat="messages"]')
ok('Year in review opens from My Account', (await pb.locator('[data-recap-stat="messages"]').innerText()).startsWith('3'))
ok('no page errors', errors.length === 0, errors.join(' | '))
await call(owner.token, 'DELETE', `/guilds/${g.id}`)
await browser.close(); await finish()
