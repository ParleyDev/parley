// Server icons show what is happening now: a corner badge for people in voice, someone streaming or on camera, or a
// live event, and a hover card listing who is there (only voice channels I can see).
import { chromium } from 'playwright'
import { B, WEB, S, reg, call, callS, ok, finish } from '../lib.mjs'
const WS = B.replace(/^http/, 'ws').replace(/\/api$/, '/ws')
const a = await reg('alice'), b = await reg('bob'), c = await reg('carol')
const g = await call(a.token, 'POST', '/guilds', { name: `Live ${S}` })
const vc = g.channels.find((x) => x.kind === 'voice')
const hidden = await call(a.token, 'POST', `/guilds/${g.id}/channels`, { name: 'staff-vc', kind: 'voice' })
const inv = await call(a.token, 'POST', `/guilds/${g.id}/invites`, {}); for (const u of [b, c]) await call(u.token, 'POST', `/invites/${inv.code}`)
await callS(a.token, 'PUT', `/channels/${hidden.id}/permissions/${g.id}`, { kind: 'role', allow: 0, deny: 1024 })
await callS(a.token, 'PUT', `/channels/${hidden.id}/permissions/${c.user.id}`, { kind: 'member', allow: 1024, deny: 0 })
const sock = (tok) => new Promise((res) => { const w = new WebSocket(`${WS}?token=${tok}`); w.onopen = () => setTimeout(() => res(w), 300) })
const pause = (ms) => new Promise((r) => setTimeout(r, ms))

const browser = await chromium.launch(); const errors = []
const p = await (await browser.newContext({ viewport: { width: 1400, height: 900 } })).newPage(); p.on('pageerror', (e) => errors.push(e.message))
await p.goto(`${WEB}/login`); await p.evaluate((t) => localStorage.setItem('parley.token', t), b.token)
await p.goto(`${WEB}/channels/@me`); await p.waitForSelector(`[data-guild-icon="${g.id}"]`); await p.waitForTimeout(800)
const icon = p.locator(`[data-guild-icon="${g.id}"]`)
ok('a quiet server has no badge', await icon.locator('[data-guild-activity]').count() === 0)

console.log('-- voice')
const ca = await sock(c.token)
ca.send(JSON.stringify({ op: 'voice_join', channel_id: hidden.id, e2ee: true })); await pause(800)
ok('someone in a channel I cannot see shows nothing', await icon.locator('[data-guild-activity]').count() === 0)
const wa = await sock(a.token)
wa.send(JSON.stringify({ op: 'voice_join', channel_id: vc.id, e2ee: true }))
await icon.locator('[data-guild-activity="voice"]').waitFor({ timeout: 5000 }).catch(() => {})
ok('people in voice put a speaker on the icon', await icon.locator('[data-guild-activity="voice"]').count() === 1)
await icon.hover(); await p.waitForSelector('[data-guild-activity-card]')
ok('hovering lists who is in voice', await p.locator('[data-guild-activity-card] [data-activity-row="voice"] img, [data-guild-activity-card] [data-activity-row="voice"] [data-avatar]').count() >= 1 || await p.locator('[data-activity-row="voice"]').count() === 1)
ok('with the server name', (await p.locator('[data-guild-activity-card]').innerText()).includes(`Live ${S}`))
await p.mouse.move(700, 450)

console.log('-- streaming')
wa.send(JSON.stringify({ op: 'voice_state', self_mute: false, self_deaf: false, self_video: false, self_stream: true }))
await icon.locator('[data-guild-activity="stream"]').waitFor({ timeout: 5000 }).catch(() => {})
ok('a stream turns it into a screen badge', await icon.locator('[data-guild-activity="stream"]').count() === 1)
await icon.hover(); await p.waitForSelector('[data-activity-row="stream"]')
ok('and the card lists the streamer', await p.locator('[data-activity-row="voice"]').count() === 0)
await p.mouse.move(700, 450)

console.log('-- live event')
const ev = await call(a.token, 'POST', `/guilds/${g.id}/events`, { name: `Game night ${S}`, starts_at: new Date(Date.now() + 60_000).toISOString(), channel_id: vc.id })
await callS(a.token, 'POST', `/guilds/${g.id}/events/${ev.id}/start`)
ok('my live events are listed', (await call(b.token, 'GET', '/users/@me/events/active')).some((e) => e.id === ev.id))
ok('not to outsiders', !(await call((await reg('dave')).token, 'GET', '/users/@me/events/active')).some((e) => e.id === ev.id))
await icon.locator('[data-guild-activity="event"]').waitFor({ timeout: 5000 }).catch(() => {})
ok('a live event takes the badge', await icon.locator('[data-guild-activity="event"]').count() === 1)
await icon.hover(); await p.waitForSelector('[data-activity-row="event"]')
ok('and shows in the card', (await p.locator('[data-activity-row="event"]').innerText()).includes(`Game night ${S}`))
await p.mouse.move(700, 450)
await callS(a.token, 'POST', `/guilds/${g.id}/events/${ev.id}/end`)
wa.close(); ca.close()
await icon.locator('[data-guild-activity]').waitFor({ state: 'detached', timeout: 8000 }).catch(() => {})
ok('everyone gone: the badge goes too', await icon.locator('[data-guild-activity]').count() === 0)
ok('no page errors', errors.length === 0, errors.join(' | '))
await call(a.token, 'DELETE', `/guilds/${g.id}`, { password: 'password1', name: g.name })
await browser.close(); await finish()
