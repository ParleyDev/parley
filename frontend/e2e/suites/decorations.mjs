// Image avatar decorations from the mounted assets folder (ASSETS_PATH → /data/assets/avatar-decorations). CI mounts
// e2e/fixtures/assets (one still ring, one two-frame APNG); any folder with at least one still and one animated file works.
import { chromium } from 'playwright'
import { B, WEB, reg, call, callS, ok, finish, openProfileEditor } from '../lib.mjs'

console.log('-- API')
const list = await (await fetch(`${B}/assets/avatar-decorations`)).json()
ok('catalog lists the mounted files (no login needed)', Array.isArray(list) && list.length >= 2 && list.every((d) => d.id && d.name && typeof d.animated === 'boolean'), JSON.stringify(list).slice(0, 200))
const moving = list.find((d) => d.animated), still = list.find((d) => !d.animated)
ok('animated and still files are told apart', !!moving && !!still)
let r = await fetch(`${B}/assets/avatar-decorations/${moving.id}`)
const etag = r.headers.get('etag')
ok('file served as an image with caching headers', r.status === 200 && r.headers.get('content-type').startsWith('image/') && r.headers.get('cache-control').includes('max-age') && !!etag)
ok('unchanged file answers 304 to its ETag', (await fetch(`${B}/assets/avatar-decorations/${moving.id}`, { headers: { 'If-None-Match': etag } })).status === 304)
const frame = Buffer.from(await (await fetch(`${B}/assets/avatar-decorations/${moving.id}/static`)).arrayBuffer())
ok('animated file has a still PNG first frame', frame.subarray(1, 4).toString() === 'PNG' && !frame.includes(Buffer.from('acTL')))
ok('unknown or traversal ids are 404', (await fetch(`${B}/assets/avatar-decorations/nope-${Date.now()}`)).status === 404 && (await fetch(`${B}/assets/avatar-decorations/..%2F..%2Fetc%2Fpasswd`)).status === 404)

const a = await reg('decor')
r = await callS(a.token, 'PATCH', '/users/@me', { avatar_decoration: `asset:${moving.id}` })
ok('a mounted decoration can be saved', r.status === 200 && r.body.avatar_decoration === `asset:${moving.id}`, JSON.stringify(r.body).slice(0, 160))
ok('a missing one is refused', (await callS(a.token, 'PATCH', '/users/@me', { avatar_decoration: 'asset:not-there' })).status === 400)
ok('presets still work', (await callS(a.token, 'PATCH', '/users/@me', { avatar_decoration: 'gold' })).body.avatar_decoration === 'gold')

console.log('-- UI')
const browser = await chromium.launch(); const errors = []
const p = await browser.newPage({ viewport: { width: 1440, height: 900 } }); p.on('pageerror', (e) => errors.push(e.message))
await p.goto(`${WEB}/login`); await p.evaluate((t) => localStorage.setItem('parley.token', t), a.token); await p.goto(`${WEB}/channels/@me`); await p.waitForSelector('[data-panel-self]')
await openProfileEditor(p, { section: 'decoration' }); await p.waitForSelector('[data-decoration-gallery]')
ok('Profiles shows the gallery under the preset frames', await p.locator('[data-decoration-options] [data-decoration-option="gold"]').count() === 1 && await p.locator('[data-decoration-grid] [data-decoration-option]').count() >= 2)
await p.fill('[data-decoration-search]', moving.name)
ok('search narrows the grid', await p.locator(`[data-decoration-grid] [data-decoration-option="asset:${moving.id}"]`).count() === 1 && await p.locator('[data-decoration-grid] [data-decoration-option]').count() < list.length)
const tileImg = p.locator(`[data-decoration-grid] [data-decoration-option="asset:${moving.id}"] img[data-decoration]`)
ok('tiles draw the still frame', (await tileImg.getAttribute('src')).endsWith('/static'))
await p.locator(`[data-decoration-grid] [data-decoration-option="asset:${moving.id}"]`).click()
await p.waitForFunction((id) => [...document.querySelectorAll('[data-profile-card] img[data-decoration]')].some((i) => i.getAttribute('src').endsWith(`/${id}`)), moving.id)
ok('the preview card plays it', true)
await p.screenshot({ path: 'decorations-1-settings.png' })
await p.click('button:has-text("Save Changes")'); await p.waitForTimeout(600)
ok('saving stores asset:<id>', (await call(a.token, 'GET', '/users/@me')).avatar_decoration === `asset:${moving.id}`)
await p.keyboard.press('Escape'); await p.waitForTimeout(200); await p.keyboard.press('Escape'); await p.waitForTimeout(300)
const panelImg = p.locator('[data-panel-self] img[data-decoration]')
ok('the self panel avatar wears it, still', await panelImg.count() === 1 && (await panelImg.getAttribute('src')).endsWith('/static'))
const box = await panelImg.boundingBox(); const av = await p.locator('[data-panel-self] .rounded-full').first().boundingBox()
ok('drawn at 1.2x the avatar, centred', Math.abs(box.width - av.width * 1.2) <= 2 && Math.abs((box.x + box.width / 2) - (av.x + av.width / 2)) <= 2, JSON.stringify({ box, av }))
await p.locator('[data-panel-self] img[data-decoration]').locator('..').hover(); await p.waitForTimeout(200)
ok('hovering the avatar plays it', !(await panelImg.getAttribute('src')).endsWith('/static'))
await p.mouse.move(800, 400)
await p.evaluate(() => { document.documentElement.dataset.motion = 'reduced' })
await p.locator('[data-panel-self] img[data-decoration]').locator('..').hover(); await p.waitForTimeout(200)
ok('reduced motion keeps it still on hover', (await panelImg.getAttribute('src')).endsWith('/static'))
ok('no page errors', errors.length === 0, errors.join('\n'))
await browser.close(); await finish()
