// Navigation: the Ctrl+K quick switcher (fuzzy search, @ # ! * prefixes, unread first, Enter to go, friends without a
// DM), Alt+↑/↓ in sidebar order, Alt+Shift+↑/↓ through unread channels, Ctrl+Alt+↑/↓ between servers, Ctrl+I inbox,
// Ctrl+P pins, Escape / Shift+Escape to mark read, and the "Unread ↓ / New mentions ↓" pills in a long channel list.
import { chromium } from 'playwright'
import { WEB, S, reg, call, ok, finish } from '../lib.mjs'
const a = await reg('alice'), b = await reg('bob'), c = await reg('carol')
await call(a.token, 'POST', '/users/@me/relationships', { user_id: c.user.id }); await call(c.token, 'PUT', `/users/@me/relationships/${a.user.id}`)
const g = await call(a.token, 'POST', '/guilds', { name: `Nav ${S}` })
const g2 = await call(a.token, 'POST', '/guilds', { name: `Second ${S}` })
const inv = await call(a.token, 'POST', `/guilds/${g.id}/invites`, {}); await call(b.token, 'POST', `/invites/${inv.code}`)
const general = g.channels.find((x) => x.kind === 'text')
const cat = await call(a.token, 'POST', `/guilds/${g.id}/channels`, { name: 'Zone', kind: 'category' })
const inCat = await call(a.token, 'POST', `/guilds/${g.id}/channels`, { name: 'zebra-talk', kind: 'text', parent_id: cat.id })
const many = []
for (let i = 0; i < 22; i++) many.push(await call(a.token, 'POST', `/guilds/${g.id}/channels`, { name: `room-${String(i).padStart(2, '0')}`, kind: 'text', parent_id: cat.id }))
const browser = await chromium.launch(); const errors = []
const p = await (await browser.newContext({ viewport: { width: 1280, height: 700 } })).newPage(); p.on('pageerror', (e) => errors.push(e.message))
await p.goto(`${WEB}/login`); await p.evaluate((t) => localStorage.setItem('parley.token', t), a.token)
await p.goto(`${WEB}/channels/${g.id}/${general.id}`); await p.waitForSelector('[data-composer-box] textarea'); await p.waitForTimeout(800)
const here = () => new URL(p.url()).pathname
const blur = () => p.evaluate(() => document.activeElement?.blur())

console.log('-- quick switcher')
await blur(); await p.keyboard.press('Control+k'); await p.waitForSelector('[data-quick-switcher]')
await p.keyboard.type('zebr'); await p.waitForTimeout(150)
ok('typing finds channels by name', (await p.locator('[data-qs-index="0"]').getAttribute('data-qs-key')) === inCat.id)
await p.keyboard.press('Enter'); await p.waitForTimeout(400)
ok('Enter goes there', here() === `/channels/${g.id}/${inCat.id}` && await p.locator('[data-quick-switcher]').count() === 0)
await blur(); await p.keyboard.press('Control+k'); await p.keyboard.type('*sec'); await p.waitForTimeout(150)
ok('* searches servers only', await p.locator('[data-qs-results] [data-qs-kind]').evaluateAll((els) => els.every((e) => e.dataset.qsKind === 'guild')) && await p.locator(`[data-qs-key="guild:${g2.id}"]`).count() === 1)
await p.fill('[data-qs-input]', '#'); await p.waitForTimeout(150)
ok('# lists text channels only', await p.locator('[data-qs-results] [data-qs-kind]').evaluateAll((els) => els.length > 0 && els.every((e) => e.dataset.qsKind === 'channel')))
await p.fill('[data-qs-input]', '@car'); await p.waitForTimeout(150)
ok('@ finds people, even friends without a DM yet', await p.locator(`[data-qs-key="friend:${c.user.id}"]`).count() === 1)
await p.keyboard.press('Enter'); await p.waitForTimeout(800)
ok('and picking one opens a DM with them', /^\/channels\/@me\//.test(here()))
await p.goto(`${WEB}/channels/${g.id}/${general.id}`); await p.waitForTimeout(800)
await call(b.token, 'POST', `/channels/${many[5].id}/messages`, { content: `hi <@${a.user.id}>` }); await p.waitForTimeout(600)
await blur(); await p.keyboard.press('Control+k'); await p.waitForTimeout(200)
ok('with nothing typed it starts with what mentions you', (await p.locator('[data-qs-index="0"]').getAttribute('data-qs-key')) === many[5].id)
await p.keyboard.press('Escape'); await p.waitForTimeout(150)

console.log('-- stepping')
await blur(); await p.keyboard.press('Alt+ArrowDown'); await p.waitForTimeout(300)
const voice = g.channels.find((x) => x.kind === 'voice')
ok('Alt+↓ goes to the next row in the sidebar (the voice channel)', here() === `/channels/${g.id}/${voice.id}`, here())
await blur(); await p.keyboard.press('Alt+ArrowDown'); await p.waitForTimeout(300)
ok('and then into the category, in sidebar order', here() === `/channels/${g.id}/${inCat.id}`, here())
await blur(); await p.keyboard.press('Alt+Shift+ArrowDown'); await p.waitForTimeout(300)
ok('Alt+Shift+↓ jumps to the next unread channel', here() === `/channels/${g.id}/${many[5].id}`, here())
await blur(); await p.keyboard.press('Control+Alt+ArrowDown'); await p.waitForTimeout(500)
ok('Ctrl+Alt+↓ goes to the next server', here().startsWith(`/channels/${g2.id}`), here())
await blur(); await p.keyboard.press('Control+Alt+ArrowUp'); await p.waitForTimeout(500)
ok('Ctrl+Alt+↑ comes back', here().startsWith(`/channels/${g.id}`))
await blur(); await p.keyboard.press('Control+i'); await p.waitForTimeout(300)
ok('Ctrl+I opens the inbox', await p.locator('[data-inbox]').count() === 1)
await p.keyboard.press('Escape'); await p.mouse.click(700, 400); await blur(); await p.keyboard.press('Control+p'); await p.waitForTimeout(300)
ok('Ctrl+P shows pinned messages', /Pinned Messages/.test(await p.locator('main').innerText()))

console.log('-- unread pills and marking read')
await p.goto(`${WEB}/channels/${g.id}/${general.id}`); await p.waitForTimeout(800)
await call(b.token, 'POST', `/channels/${many[21].id}/messages`, { content: 'down here' }); await p.waitForTimeout(800)
ok('an unread channel scrolled out of view gets a pill', await p.locator('[data-unread-pill="below"]').count() === 1)
await p.click('[data-unread-pill="below"]'); await p.waitForTimeout(900)
ok('clicking it scrolls to the channel', await p.locator(`[data-channel-item="${many[21].id}"] a`).isVisible() && await p.locator('[data-unread-pill="below"]').count() === 0)
await p.focus('[data-composer-box] textarea'); await p.keyboard.press('Shift+Escape'); await p.waitForTimeout(800)
ok('Shift+Escape marks the whole server read', await p.locator('[data-channel-item] > a[data-unread]').count() === 0)
ok('no page errors', errors.length === 0, errors.join(' | '))
await call(a.token, 'DELETE', `/guilds/${g.id}`, { password: 'password1', name: g.name }); await call(a.token, 'DELETE', `/guilds/${g2.id}`, { password: 'password1', name: g2.name })
await browser.close(); await finish()
