// Editing in the DAW's timeline by hand: copy, cut and paste, nudging with the arrow keys, the selection box,
// Ctrl-drag to copy and Alt-drag off the grid, zooming about the pointer, the loop's edges, markers, track order
// and height, and take lanes. Each command is checked on the server, as one change, undone in one step.
import { WEB, B, S, IP, reg, call, callS, ok, finish, launchBrowser } from '../lib.mjs'
import { sine, wavFile } from '../audio.mjs'

const a = await reg('alice')
const g = await call(a.token, 'POST', '/guilds', { name: `Edit ${S}` })
const studio = (await callS(a.token, 'POST', `/guilds/${g.id}/channels`, { name: 'daw', kind: 'studio' })).body
const P = (await callS(a.token, 'POST', `/channels/${studio.id}/studio/projects`, { name: 'Edit Song', bpm: 120 })).body
const full = () => call(a.token, 'GET', `/studio/projects/${P.id}`)
const ops = (list) => callS(a.token, 'POST', `/studio/projects/${P.id}/ops`, { ops: list })
const upload = async (name) => (await fetch(`${B}/channels/${P.channel_id}/studio/audio?name=${name}&duration_ms=4000`, { method: 'POST', headers: { Authorization: `Bearer ${a.token}`, 'Content-Type': 'audio/wav', 'X-Forwarded-For': IP }, body: wavFile({ seconds: 4, signal: sine(220, 0.4) }) })).json()
const one = await upload('One.wav'), two = await upload('Two.wav')
const id = () => crypto.randomUUID()
const LA = id(), LB = id(), LC = id(), CA = id(), CB = id(), CC = id(), T1 = id(), T2 = id(), G = id()
const r0 = await ops([{ op: 'lane.put', lane: { id: LA, name: 'One', position: 0 } }, { op: 'lane.put', lane: { id: LB, name: 'Two', position: 1 } }, { op: 'lane.put', lane: { id: LC, name: 'Three', position: 2 } },
  { op: 'clip.put', clip: { id: CA, lane_id: LA, audio_id: one.id, start_ms: 0, length_ms: 2000 } }, { op: 'clip.put', clip: { id: CB, lane_id: LA, audio_id: one.id, start_ms: 4000, length_ms: 2000 } },
  { op: 'clip.put', clip: { id: CC, lane_id: LB, audio_id: one.id, start_ms: 1000, length_ms: 1000 } },
  { op: 'clip.put', clip: { id: T1, lane_id: LC, audio_id: one.id, start_ms: 8000, length_ms: 2000, group_id: G } }, { op: 'clip.put', clip: { id: T2, lane_id: LC, audio_id: two.id, start_ms: 8000, length_ms: 2000, group_id: G, muted: true } },
  { op: 'project', markers: [{ id: 'm1', ms: 1000, name: 'Verse' }] }])
ok('the project is set up', r0.status === 200, JSON.stringify(r0.body).slice(0, 200))

const browser = await launchBrowser(); const errors = []
const p = await browser.newPage({ viewport: { width: 1440, height: 900 } }); p.on('pageerror', (e) => errors.push(e.message))
await p.goto(`${WEB}/login`, { waitUntil: 'networkidle' }); await p.evaluate((t) => localStorage.setItem('parley.token', t), a.token)
await p.goto(`${WEB}/channels/${g.id}/${P.channel_id}`); await p.waitForSelector(`[data-daw-clip="${CA}"]`, { timeout: 15000 })
const settle = () => p.waitForTimeout(700)
const ver = async () => (await full()).project.version
const clips = async () => (await full()).clips
const clip = async (cid) => (await clips()).find((c) => c.id === cid)
const box = (sel) => p.locator(sel).boundingBox()
const center = async (sel) => { const b = await box(sel); return { x: b.x + b.width / 2, y: b.y + b.height / 2 } }
const selected = () => p.locator('[data-daw-clip][data-selected="1"]').evaluateAll((l) => l.map((e) => e.dataset.dawClip).sort())
// Where a time is on the screen: from a clip whose start and length are known.
const xOf = async (ms) => { const b = await box(`[data-daw-clip="${CA}"]`), at = (await clip(CA)); return b.x + ((ms - at.start_ms) / at.length_ms) * b.width }
const headMs = async () => { const h = await box('[data-daw-playhead]'), b = await box(`[data-daw-clip="${CA}"]`), at = await clip(CA); return at.start_ms + ((h.x - b.x) / b.width) * at.length_ms }
const seekTo = async (ms) => { const r = await box('[data-daw-ruler]'); await p.mouse.click(await xOf(ms), r.y + r.height - 6); await p.waitForTimeout(150) }
const undo = async () => { await p.keyboard.press('Control+z'); await settle() }
const mod = 'Control'

console.log('-- copy, cut and paste')
let v = await ver()
await p.click(`[data-daw-clip="${CA}"]`); await seekTo(12000)
ok('the playhead is where the ruler was clicked', Math.abs(await headMs() - 12000) < 30, String(await headMs()))
await p.keyboard.press(`${mod}+c`); await p.keyboard.press(`${mod}+v`); await settle()
let all = await clips(), made = all.filter((c) => c.lane_id === LA && c.start_ms === 12000)
ok('a copied clip is pasted at the playhead on its own track, the same but for where it is', made.length === 1 && made[0].length_ms === 2000 && made[0].audio_id === one.id && all.length === 6, JSON.stringify(made))
ok('as one change', await ver() === v + 1, `${v} -> ${await ver()}`)
ok('and the pasted clip is the selection', JSON.stringify(await selected()) === JSON.stringify([made[0]?.id]))
await undo()
ok('undone in one step', (await clips()).length === 5 && await ver() === v + 2)

await p.click(`[data-daw-clip="${CA}"]`); await p.click(`[data-daw-clip="${CC}"]`, { modifiers: ['Shift'] })
v = await ver()
await p.keyboard.press(`${mod}+x`); await settle()
all = await clips()
ok('cut removes the selected clips in one change', all.length === 3 && !all.some((c) => c.id === CA || c.id === CC) && await ver() === v + 1, `${all.length} clips, ${v} -> ${await ver()}`)
// The clip the screen is measured from is gone: put the playhead by the other one.
const bB = await box(`[data-daw-clip="${CB}"]`), ruler = await box('[data-daw-ruler]')
await p.mouse.click(bB.x + bB.width * 3, ruler.y + ruler.height - 6); await p.waitForTimeout(150)
await p.keyboard.press(`${mod}+v`); await settle()
all = await clips()
const pa = all.find((c) => c.lane_id === LA && c.start_ms === 10000), pc = all.find((c) => c.lane_id === LB && c.start_ms === 11000)
ok('and pastes them at the playhead as far apart as they were, each on its track', !!pa && !!pc && pa.length_ms === 2000 && pc.length_ms === 1000 && all.length === 5 && await ver() === v + 2, JSON.stringify(all.map((c) => [c.lane_id === LA ? 'A' : c.lane_id === LB ? 'B' : 'C', c.start_ms])))
await undo(); await undo()
all = await clips()
ok('two undos bring the cut clips back where they were', all.length === 5 && (await clip(CA))?.start_ms === 0 && (await clip(CC))?.start_ms === 1000, JSON.stringify(all.map((c) => c.start_ms)))

console.log('-- nudge')
await p.click(`[data-daw-clip="${CC}"]`); v = await ver()
await p.keyboard.press('ArrowRight'); await settle()
ok('the right arrow moves the selection one grid step', (await clip(CC)).start_ms === 1500 && await ver() === v + 1, String((await clip(CC)).start_ms))
await p.keyboard.press('Shift+ArrowRight'); await p.keyboard.press('Shift+ArrowRight'); await settle()
ok('with Shift, a millisecond', (await clip(CC)).start_ms === 1502, String((await clip(CC)).start_ms))
await p.keyboard.press('ArrowLeft'); await settle()
ok('from off the grid the arrow goes to the grid line on that side first', (await clip(CC)).start_ms === 1500, String((await clip(CC)).start_ms))
await p.keyboard.press('ArrowLeft'); await settle()
ok('and then a step', (await clip(CC)).start_ms === 1000, String((await clip(CC)).start_ms))
await p.click(`[data-daw-clip="${CA}"]`); await p.click(`[data-daw-clip="${CB}"]`, { modifiers: ['Shift'] }); v = await ver()
await p.keyboard.press('ArrowLeft'); await settle()
ok('a selection whose first clip is at the start does not move', (await clip(CA)).start_ms === 0 && (await clip(CB)).start_ms === 4000 && await ver() === v)
await p.keyboard.press('ArrowRight'); await settle()
ok('several clips move together in one change', (await clip(CA)).start_ms === 500 && (await clip(CB)).start_ms === 4500 && await ver() === v + 1)
await undo()
ok('undone in one step', (await clip(CA)).start_ms === 0 && (await clip(CB)).start_ms === 4000)

console.log('-- the selection box')
const laneA = await box(`[data-daw-lane="${LA}"]`), laneB = await box(`[data-daw-lane="${LB}"]`)
await p.mouse.move(await xOf(3200), laneA.y + 20); await p.mouse.down()
await p.mouse.move(await xOf(2500), laneA.y + 40, { steps: 4 }); await p.mouse.move(await xOf(1500), laneB.y + laneB.height / 2, { steps: 6 })
ok('dragging over empty track draws a box', await p.locator('[data-daw-select-box]').count() === 1)
await p.mouse.up(); await p.waitForTimeout(150)
ok('and the clips it touches are selected, on every track it crosses', JSON.stringify(await selected()) === JSON.stringify([CA, CC].sort()), JSON.stringify(await selected()))
ok('the box is gone when the button is let go', await p.locator('[data-daw-select-box]').count() === 0)
const before = await headMs()
ok('and the playhead stayed where it was', Math.abs(before - 10000) < 60, String(before))
await p.mouse.move(await xOf(7000), laneA.y + 20); await p.mouse.down(); await p.mouse.move(await xOf(3500), laneA.y + 30, { steps: 6 }); await p.keyboard.down('Shift'); await p.keyboard.up('Shift'); await p.mouse.up()
ok('a new box replaces the selection', JSON.stringify(await selected()) === JSON.stringify([CB]), JSON.stringify(await selected()))
await p.keyboard.down('Shift'); await p.mouse.move(await xOf(3000), laneB.y + 20); await p.mouse.down(); await p.mouse.move(await xOf(1200), laneB.y + 40, { steps: 6 }); await p.mouse.up(); await p.keyboard.up('Shift')
ok('with Shift it adds to it', JSON.stringify(await selected()) === JSON.stringify([CB, CC].sort()), JSON.stringify(await selected()))
await p.mouse.click(await xOf(3000), laneA.y + 20); await p.waitForTimeout(150)
ok('a click on empty track clears the selection and moves the playhead there', (await selected()).length === 0 && Math.abs(await headMs() - 3000) < 30, String(await headMs()))

console.log('-- copy and free move by dragging')
v = await ver()
let from = await center(`[data-daw-clip="${CC}"]`)
await p.keyboard.down(mod); await p.mouse.move(from.x, from.y); await p.mouse.down(); await p.mouse.move(from.x + 60, from.y, { steps: 6 }); await p.mouse.move(from.x + 120, from.y, { steps: 6 }); await p.mouse.up(); await p.keyboard.up(mod); await settle()
all = await clips()
const dup = all.filter((c) => c.lane_id === LB && c.id !== CC)
ok('a clip dragged with Ctrl held stays, and a copy is dropped where it was let go, on the grid', (await clip(CC)).start_ms === 1000 && dup.length === 1 && dup[0].start_ms === 4000 && dup[0].length_ms === 1000 && await ver() === v + 1, JSON.stringify(dup))
await undo()
ok('undone in one step', (await clips()).length === 5)
from = await center(`[data-daw-clip="${CC}"]`)
await p.keyboard.down('Alt'); await p.mouse.move(from.x, from.y); await p.mouse.down(); await p.mouse.move(from.x + 20, from.y, { steps: 4 }); await p.mouse.move(from.x + 33, from.y, { steps: 4 }); await p.mouse.up(); await p.keyboard.up('Alt'); await settle()
const cc = await clip(CC)
ok('with Alt held the clip moves off the grid and no copy is made', cc.start_ms > 1000 && cc.start_ms % 250 !== 0 && (await clips()).length === 5, String(cc.start_ms))
await undo()

console.log('-- zoom about the pointer')
const tl = await box('[data-daw-timeline]')
const px = tl.x + 300, w0 = (await box(`[data-daw-clip="${CA}"]`)).width
const under = async () => { const b = await box(`[data-daw-clip="${CA}"]`); return ((px - b.x) / b.width) * 2000 }
const t0 = await under()
await p.mouse.move(px, laneB.y + 60)
await p.keyboard.down(mod); await p.mouse.wheel(0, -300); await p.waitForTimeout(200); await p.mouse.wheel(0, -300); await p.keyboard.up(mod); await p.waitForTimeout(300)
const w1 = (await box(`[data-daw-clip="${CA}"]`)).width, t1 = await under()
ok('Ctrl and the wheel zoom in', w1 > w0 * 2, `${w0} -> ${w1}`)
ok('and the time under the pointer stays under it', Math.abs(t1 - t0) < 2000 * 2 / w1 + 1, `${t0} -> ${t1}`)
await p.keyboard.down(mod); await p.mouse.wheel(0, 300); await p.waitForTimeout(200); await p.mouse.wheel(0, 300); await p.keyboard.up(mod); await p.waitForTimeout(300)
const w2 = (await box(`[data-daw-clip="${CA}"]`)).width, t2 = await under()
ok('zooming out again is back where it was, the same time still under the pointer', Math.abs(w2 - w0) < 0.5 && Math.abs(t2 - t0) < 2000 * 2 / w2 + 1, `${w2}, ${t2}`)
const sl = await p.locator('[data-daw-timeline]').evaluate((e) => e.scrollLeft)
await p.mouse.wheel(0, 200); await p.waitForTimeout(150)
ok('the wheel alone does not zoom', Math.abs((await box(`[data-daw-clip="${CA}"]`)).width - w2) < 0.5)
await p.locator('[data-daw-timeline]').evaluate((e, x) => { e.scrollLeft = x }, sl); await p.locator('[data-daw-arrangement]').evaluate((e) => { e.scrollTop = 0 })

console.log('-- the loop\'s edges')
await ops([{ op: 'project', loop_start_ms: 2000, loop_end_ms: 4000, loop_on: true }]); await p.waitForSelector('[data-daw-loop-edge="end"]')
v = await ver()
let e = await center('[data-daw-loop-edge="end"]')
await p.mouse.move(e.x, e.y); await p.mouse.down(); await p.mouse.move(e.x + 40, e.y, { steps: 5 }); await p.mouse.move(await xOf(6000), e.y, { steps: 5 }); await p.mouse.up(); await settle()
let pr = (await full()).project
ok('dragging the end of the loop moves that end alone', pr.loop_start_ms === 2000 && pr.loop_end_ms === 6000 && pr.loop_on === true && pr.version === v + 1, JSON.stringify([pr.loop_start_ms, pr.loop_end_ms, pr.version - v]))
e = await center('[data-daw-loop-edge="start"]')
await p.mouse.move(e.x, e.y); await p.mouse.down(); await p.mouse.move(e.x - 20, e.y, { steps: 5 }); await p.mouse.move(await xOf(1000), e.y, { steps: 5 }); await p.mouse.up(); await settle()
pr = (await full()).project
ok('and the start likewise', pr.loop_start_ms === 1000 && pr.loop_end_ms === 6000, JSON.stringify([pr.loop_start_ms, pr.loop_end_ms]))
const h0 = await headMs()
e = await center('[data-daw-loop-edge="end"]')
await p.mouse.click(e.x, e.y); await settle()
ok('a click on an edge changes nothing and does not move the playhead', (await ver()) === pr.version && Math.abs(await headMs() - h0) < 30)
await undo()
ok('undo puts the edge back', (await full()).project.loop_start_ms === 2000)
await ops([{ op: 'project', loop_on: false }])

console.log('-- markers')
v = await ver()
let m = await center('[data-daw-marker="m1"]')
await p.mouse.move(m.x, m.y); await p.mouse.down(); await p.mouse.move(m.x + 30, m.y, { steps: 5 }); await p.mouse.move(m.x + (await xOf(3000)) - (await xOf(1000)), m.y, { steps: 5 }); await p.mouse.up(); await settle()
pr = (await full()).project
ok('a marker dragged along the ruler lands on the grid where it was let go, keeping its name', pr.markers.length === 1 && pr.markers[0].ms === 3000 && pr.markers[0].name === 'Verse' && pr.version === v + 1, JSON.stringify(pr.markers))
ok('and the playhead did not jump to it', Math.abs(await headMs() - h0) < 30, String(await headMs()))
await undo()
ok('undone in one step', (await full()).project.markers[0].ms === 1000)
m = await center('[data-daw-marker="m1"]')
await p.mouse.click(m.x, m.y); await p.waitForTimeout(150)
ok('a click on a marker still goes to it', Math.abs(await headMs() - 1000) < 30, String(await headMs()))

console.log('-- track order and height')
v = await ver()
const order = async () => (await full()).lanes.sort((x, y) => x.position - y.position).map((l) => l.name).join(' ')
await p.click(`[data-daw-lane-head="${LB}"] [data-daw-lane-menu]`); await p.click(`[data-daw-lane-settings="${LB}"] [data-daw-lane-up]`); await settle()
ok('Move up puts the track above the one before it, in one change', await order() === 'Two One Three' && await ver() === v + 1, await order())
const heads = await p.locator('[data-daw-lane-head]').evaluateAll((l) => l.map((x) => x.dataset.dawLaneHead))
ok('on screen too, and its clips with it', heads.join() === [LB, LA, LC].join() && (await box(`[data-daw-clip="${CC}"]`)).y < (await box(`[data-daw-clip="${CA}"]`)).y, heads.join())
ok('the first track cannot go further up', await p.locator(`[data-daw-lane-settings="${LB}"] [data-daw-lane-up]`).isDisabled())
await p.click(`[data-daw-lane-settings="${LB}"] [data-daw-lane-down]`); await p.click(`[data-daw-lane-settings="${LB}"] [data-daw-lane-down]`); await settle()
ok('Move down twice takes it to the bottom', await order() === 'One Three Two' && await p.locator(`[data-daw-lane-settings="${LB}"] [data-daw-lane-down]`).isDisabled(), await order())
await p.mouse.click(5, 5); await undo(); await undo(); await undo()
ok('three undos restore the order', await order() === 'One Two Three', await order())
v = await ver()
const hh = await box(`[data-daw-lane-head="${LA}"]`), rs = await center(`[data-daw-lane-resize="${LA}"]`), cy0 = (await box(`[data-daw-clip="${CC}"]`)).y
await p.mouse.move(rs.x, rs.y); await p.mouse.down(); await p.mouse.move(rs.x, rs.y + 20, { steps: 4 }); await p.mouse.move(rs.x, rs.y + 44, { steps: 4 }); await p.mouse.up(); await p.waitForTimeout(200)
const hh1 = await box(`[data-daw-lane-head="${LA}"]`)
ok('dragging a track\'s lower edge makes it taller', Math.abs(hh1.height - hh.height - 44) <= 1, `${hh.height} -> ${hh1.height}`)
ok('its row in the timeline and its clips with it, and the tracks below move down', Math.abs((await box(`[data-daw-lane="${LA}"]`)).height - hh1.height) <= 1 && (await box(`[data-daw-clip="${CA}"]`)).height > hh.height - 14 && Math.abs((await box(`[data-daw-clip="${CC}"]`)).y - cy0 - 44) <= 1)
ok('the height is this device\'s view, not an edit', await ver() === v && Object.values(await p.evaluate(() => JSON.parse(localStorage.getItem('parley.dawLaneHeights') || '{}'))).length === 1, await p.evaluate(() => Object.keys(localStorage).filter((k) => /daw/i.test(k)).join()))
await p.reload(); await p.waitForSelector(`[data-daw-clip="${CA}"]`)
ok('and is kept on this device', Math.abs((await box(`[data-daw-lane-head="${LA}"]`)).height - hh1.height) <= 1)
await p.dblclick(`[data-daw-lane-resize="${LA}"]`); await p.waitForTimeout(150)
ok('a double-click on the edge gives the usual height back', Math.abs((await box(`[data-daw-lane-head="${LA}"]`)).height - hh.height) <= 1)

console.log('-- take lanes')
ok('a track with alternatives recorded over one another offers its takes; one without does not', await p.locator(`[data-daw-takes-toggle="${LC}"]`).count() === 1 && await p.locator(`[data-daw-takes-toggle="${LA}"]`).count() === 0)
ok('only the take in use is drawn as the clip', await p.locator(`[data-daw-clip="${T1}"]`).count() === 1 && await p.locator(`[data-daw-clip="${T2}"]`).count() === 0)
await p.click(`[data-daw-takes-toggle="${LC}"]`)
const segs = () => p.locator(`[data-daw-take-lane="${LC}"] [data-daw-take-seg]`).evaluateAll((l) => l.map((x) => [x.dataset.dawTakeSeg, x.dataset.active ?? '', x.parentElement.dataset.takeRow]))
let sg = await segs()
ok('opened, there is a row for each take, the one in use marked', sg.length === 2 && await p.locator(`[data-daw-take-lane="${LC}"]`).count() === 2 && sg.find((x) => x[0] === T1)?.[1] === '1' && sg.find((x) => x[0] === T2)?.[1] === '', JSON.stringify(sg))
ok('and the track\'s head is as tall as its rows', Math.abs((await box(`[data-daw-lane-head="${LC}"]`)).height - (await box(`[data-daw-lane="${LC}"]`)).height) <= 1)
v = await ver()
await p.click(`[data-daw-take-seg="${T2}"]`); await settle()
ok('a click on the other take uses it there instead, in one change', (await clip(T2)).muted === false && (await clip(T1)).muted === true && await ver() === v + 1)
sg = await segs()
ok('and the clip drawn on the track is that take', sg.find((x) => x[0] === T2)?.[1] === '1' && await p.locator(`[data-daw-clip="${T2}"]`).count() === 1 && await p.locator(`[data-daw-clip="${T1}"]`).count() === 0, JSON.stringify(sg))
await undo()
ok('undone in one step', (await clip(T1)).muted === false && (await clip(T2)).muted === true)
// Split through the takes: each side then chooses its own.
await p.click(`[data-daw-clip="${T1}"]`)
const rl = await box('[data-daw-ruler]'), bt = await box(`[data-daw-clip="${T1}"]`)
await p.mouse.click(bt.x + bt.width / 2, rl.y + rl.height - 6); await p.waitForTimeout(150)
await p.click(`[data-daw-clip="${T1}"]`); await p.keyboard.press('s'); await settle()
all = (await clips()).filter((c) => c.lane_id === LC)
const right = all.filter((c) => c.start_ms === 9000)
ok('splitting splits every take, and the right half is a group of its own', all.length === 4 && right.length === 2 && right[0].group_id === right[1].group_id && right[0].group_id !== G && all.filter((c) => c.start_ms === 8000).every((c) => c.group_id === G && c.length_ms === 1000), JSON.stringify(all.map((c) => [c.start_ms, c.length_ms, c.muted, c.group_id?.slice(0, 4)])))
const other = right.find((c) => c.audio_id === two.id)
await p.click(`[data-daw-take-seg="${other.id}"]`); await settle()
all = (await clips()).filter((c) => c.lane_id === LC && !c.muted)
ok('so the second half can use the other take while the first keeps its own', all.length === 2 && all.find((c) => c.start_ms === 8000)?.audio_id === one.id && all.find((c) => c.start_ms === 9000)?.audio_id === two.id, JSON.stringify(all.map((c) => [c.start_ms, c.audio_id === one.id ? 'one' : 'two'])))
await p.click(`[data-daw-takes-toggle="${LC}"]`)
ok('the takes can be hidden again', await p.locator(`[data-daw-take-lane="${LC}"]`).count() === 0)

ok('no page errors', errors.length === 0, errors.join('\n'))
await browser.close(); await finish()
