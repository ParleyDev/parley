// System messages: pins, threads, server joins and DM calls leave a notice in the conversation.
import { chromium } from 'playwright'
import { WEB, S, reg, call, callS, raw, ok, finish } from '../lib.mjs'

const a = await reg('alice'); const b = await reg('bob')
const g = await call(a.token, 'POST', '/guilds', { name: `Sys ${S}` })
const tc = (await call(a.token, 'GET', `/guilds/${g.id}/channels`)).find((x) => x.kind === 'text')
const list = (tok, ch = tc.id) => call(tok, 'GET', `/channels/${ch}/messages?limit=20`)
const sys = (msgs, kind) => msgs.filter((m) => m.kind === kind)

console.log('-- member join')
const inv = await call(a.token, 'POST', `/guilds/${g.id}/invites`, {}); await call(b.token, 'POST', `/invites/${inv.code}`)
let ms = await list(a.token)
let j = sys(ms, 'member_join')
ok('joining via invite posts "joined the server." to the first text channel, authored by the joiner', j.length === 1 && j[0].author.id === b.user.id && j[0].content === 'joined the server.')
await call(b.token, 'POST', `/invites/${inv.code}`)
ok('re-using the invite while already a member posts nothing', sys(await list(a.token), 'member_join').length === 1)

console.log('-- pins')
const target = await call(a.token, 'POST', `/channels/${tc.id}/messages`, { content: `pin me ${S}` })
let r = await raw(a.token, 'PUT', `/channels/${tc.id}/pins/${target.id}`); ok('pinned', r.status === 200)
ms = await list(b.token); let p = sys(ms, 'pins_add')
ok('a pins_add notice follows, linking the pinned message', p.length === 1 && p[0].reply_to === target.id && p[0].content === 'pinned a message to this channel.' && p[0].author.id === a.user.id, JSON.stringify(p))
await raw(a.token, 'PUT', `/channels/${tc.id}/pins/${target.id}`)
ok('pinning again is a no-op (no second notice)', sys(await list(b.token), 'pins_add').length === 1)
await raw(a.token, 'DELETE', `/channels/${tc.id}/pins/${target.id}`)
ok('unpinning is silent', sys(await list(b.token), 'pins_add').length === 1 && sys(await list(b.token), 'pins_remove').length === 0)
ok('the pinned message itself is not listed as pinned any more', (await call(b.token, 'GET', `/channels/${tc.id}/pins`)).length === 0)

console.log('-- threads')
r = await callS(a.token, 'POST', `/channels/${tc.id}/threads`, { name: `Lunch ${S}`, message_id: target.id })
ok('thread created', r.status === 201, JSON.stringify(r.body))
const tid = r.body.id
ms = await list(b.token); let t = sys(ms, 'thread_created')
ok('a thread_created notice carries the thread id and roots at the message', t.length === 1 && t[0].ref_id === tid && t[0].reply_to === target.id && t[0].content === `started a thread: Lunch ${S}`, JSON.stringify(t))
r = await callS(a.token, 'POST', `/channels/${tc.id}/threads`, { name: `Free ${S}` })
ok('a thread without a root message still gets a notice', sys(await list(b.token), 'thread_created').length === 2 && sys(await list(b.token), 'thread_created').some((m) => m.ref_id === r.body.id && m.reply_to === null))
const forum = await call(a.token, 'POST', `/guilds/${g.id}/channels`, { name: 'board', kind: 'forum' })
await callS(a.token, 'POST', `/channels/${forum.id}/threads`, { name: 'Post', content: 'body' })
ok('forum posts do not spam the forum with notices', sys(await list(b.token, forum.id), 'thread_created').length === 0)
ok('system rows never count as mentions', t[0].mentions.length === 0 && !t[0].mention_everyone)

console.log('-- UI')
const browser = await chromium.launch({ args: ['--use-fake-ui-for-media-stream', '--use-fake-device-for-media-stream'] }); const errors = []
const mk = async (tok, url) => { const p = await browser.newPage({ viewport: { width: 1440, height: 900 } }); p.on('pageerror', (e) => errors.push(e.message)); await p.goto(`${WEB}/login`); await p.evaluate((t) => localStorage.setItem('parley.token', t), tok); await p.goto(url); await p.waitForSelector('textarea'); return p }
const pb = await mk(b.token, `${WEB}/channels/${g.id}/${tc.id}`)
await pb.waitForSelector('[data-system="pins_add"]')
const first = await call(b.token, 'POST', `/channels/${tc.id}/messages`, { content: `after my join ${S}` })
await pb.waitForSelector(`[data-msg-id="${first.id}"]`)
ok('a message right after your own system row still shows the author header', await pb.locator(`[data-msg-id="${first.id}"] [data-msg-author]`).count() === 1)
ok('join, pin and thread notices render as system rows', await pb.locator('[data-system="member_join"]').count() === 1 && await pb.locator('[data-system="pins_add"]').count() === 1 && await pb.locator('[data-system="thread_created"]').count() === 2)
ok('pin row names the actor and offers a jump link', (await pb.locator('[data-system="pins_add"] [data-msg-author]').textContent()) === 'Alice' && await pb.locator(`[data-system="pins_add"] [data-system-jump="${target.id}"]`).count() === 1)
// Pad the channel so the pinned message scrolls out, then jump.
for (let i = 0; i < 30; i++) await call(a.token, 'POST', `/channels/${tc.id}/messages`, { content: `filler ${i}` })
await pb.waitForFunction(() => document.querySelectorAll('[data-msg-id]').length > 30)
await pb.click(`[data-system-jump="${target.id}"]`)
await pb.waitForFunction((id) => { const el = document.querySelector(`[data-msg-id="${id}"]`); if (!el) return false; const r = el.getBoundingClientRect(); return r.top >= 0 && r.bottom <= window.innerHeight }, target.id)
ok('"See the message" scrolls the pinned message into view', true)
await pb.screenshot({ path: '135-system-messages.png' })
await pb.click(`[data-system-thread="${tid}"]`); await pb.waitForSelector('[data-thread-panel]')
ok('clicking the thread name opens the thread panel', (await pb.locator('[data-thread-panel]').textContent()).includes(`Lunch ${S}`))
// Live: alice pins another message while bob watches.
const second = await call(a.token, 'POST', `/channels/${tc.id}/messages`, { content: `second pin ${S}` })
await raw(a.token, 'PUT', `/channels/${tc.id}/pins/${second.id}`)
await pb.waitForFunction(() => document.querySelectorAll('[data-system="pins_add"]').length === 2)
ok('new pin notices arrive live', true)

console.log('-- jumping to unloaded messages')
// Push the pinned message far beyond the first page, reload, and jump from the Pinned panel, search and a bookmark.
for (let i = 0; i < 130; i++) await call(a.token, 'POST', `/channels/${tc.id}/messages`, { content: `deep filler ${i}` })
await pb.reload(); await pb.waitForSelector('textarea')
ok('after reload the pinned message is not loaded', await pb.locator(`[data-msg-id="${target.id}"]`).count() === 0)
await pb.click('[data-pins-toggle]'); await pb.waitForSelector('[data-pins-panel] [data-msg-card]')
await pb.locator(`[data-pins-panel] [data-msg-card="${second.id}"] [data-jump]`).click()
await pb.waitForFunction((id) => { const el = document.querySelector(`[data-msg-id="${id}"]`); if (!el) return false; const r = el.getBoundingClientRect(); return r.top >= 0 && r.bottom <= window.innerHeight }, second.id, { timeout: 20000 })
ok('Jump from the Pinned panel loads older pages and scrolls the pin into view', await pb.locator('[data-pins-panel]').count() === 0 && !(await pb.locator('body').textContent()).includes('not loaded'))
await pb.reload(); await pb.waitForSelector('textarea')
await pb.fill('[data-search-input]', `pin me ${S}`); await pb.press('[data-search-input]', 'Enter'); await pb.waitForSelector('[data-search-hit]')
await pb.locator('[data-search-hit] [data-jump]').first().click()
await pb.waitForFunction((id) => { const el = document.querySelector(`[data-msg-id="${id}"]`); if (!el) return false; const r = el.getBoundingClientRect(); return r.top >= 0 && r.bottom <= window.innerHeight }, target.id, { timeout: 20000 })
ok('a search hit far back also loads and scrolls', true)
await call(b.token, 'PUT', `/users/@me/bookmarks/${target.id}`)
await pb.reload(); await pb.waitForSelector('textarea')
await pb.click('[data-bookmarks-toggle]'); await pb.waitForSelector('[data-bookmarks-panel] [data-msg-card]')
await pb.locator(`[data-bookmarks-panel] [data-msg-card="${target.id}"] [data-jump]`).click()
await pb.waitForFunction((id) => { const el = document.querySelector(`[data-msg-id="${id}"]`); if (!el) return false; const r = el.getBoundingClientRect(); return r.top >= 0 && r.bottom <= window.innerHeight }, target.id, { timeout: 20000 })
ok('a bookmark far back loads and scrolls too', true)

console.log('-- DM call')
const dm = await call(a.token, 'POST', '/users/@me/channels', { recipient_id: b.user.id })
const pa = await mk(a.token, `${WEB}/channels/@me/${dm.id}`)
await pa.click('[data-start-call]'); await pa.waitForTimeout(1500)
ms = await list(b.token, dm.id); let c = sys(ms, 'call_started')
ok('first person in a DM call leaves "started a call."', c.length === 1 && c[0].author.id === a.user.id && c[0].content === 'started a call.', JSON.stringify(c))
const pb2 = await mk(b.token, `${WEB}/channels/@me/${dm.id}`)
await pb2.waitForSelector('[data-call-join]'); await pb2.click('[data-call-join]'); await pb2.waitForTimeout(1500)
ok('joining an existing call adds no second notice', sys(await list(b.token, dm.id), 'call_started').length === 1)
ok('call row renders', await pb2.locator('[data-system="call_started"]').count() === 1)
await pa.click('[data-dm-call] button[title="Leave Call"]'); await pb2.click('[data-dm-call] button[title="Leave Call"]')
await pb2.waitForSelector('[data-system="call_ended"]', { timeout: 10000 })
c = sys(await list(b.token, dm.id), 'call_ended')
ok('once everyone leaves, the notice becomes "started a call that lasted …"', c.length === 1 && /^started a call that lasted a few seconds\.$/.test(c[0].content) && sys(await list(b.token, dm.id), 'call_started').length === 0, JSON.stringify(c))
ok('the ended row renders in place', (await pb2.locator('[data-system="call_ended"]').textContent()).includes('lasted a few seconds'))
// Unanswered: alice calls and hangs up before bob picks up.
await pa.click('[data-start-call]'); await pa.waitForSelector('[data-dm-call] [data-call-participant]'); await pa.waitForTimeout(500)
await pa.click('[data-dm-call] button[title="Leave Call"]'); await pb2.waitForSelector('[data-system="call_missed"]', { timeout: 10000 })
ok('bob reads "You missed a call from Alice."', (await pb2.locator('[data-system="call_missed"]').textContent()).includes('You missed a call from Alice'))
ok('alice reads that no one answered', (await pa.locator('[data-system="call_missed"]').textContent()).includes('No one answered'))
await pb2.screenshot({ path: '161-call-notices.png' })
ok('no page errors', errors.length === 0, errors.join('\n'))
await browser.close(); await finish()
