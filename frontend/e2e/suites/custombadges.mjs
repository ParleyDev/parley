// Custom badges (Admin Console → Badges): admins make badges and give them to people; profiles carry them as
// custom:<id> after the built-in ones, drawn from the public catalog, which every session gets again on a change.
import { chromium } from 'playwright'
import { WEB, S, reg, call, callS, ok, finish, adminToken, pngFile, multi } from '../lib.mjs'

const admin = await adminToken()
const a = await reg('badgee'), b = await reg('badgepal')
const made = []
const cleanup = async () => { for (const id of made) await callS(admin.token, 'DELETE', `/admin/badges/${id}`) }

console.log('-- making badges')
let r = await callS(a.token, 'POST', '/admin/badges', { name: 'Nope', emoji: '⭐' }); ok('only admins make badges', r.status === 403)
r = await callS(admin.token, 'POST', '/admin/badges', { name: 'No icon' }); ok('a badge needs an emoji or a picture', r.status === 400)
r = await callS(admin.token, 'POST', '/admin/badges', { name: 'Bad', emoji: 'abc' }); ok('an emoji must be an emoji', r.status === 400)
r = await callS(admin.token, 'POST', '/admin/badges', { name: 'Bad', emoji: '⭐', color: 'red' }); ok('a colour is #rrggbb', r.status === 400)
r = await callS(admin.token, 'POST', '/admin/badges', { name: 'Bad', icon_url: 'https://elsewhere.example/x.png' }); ok('a picture must be uploaded here', r.status === 400)
r = await callS(admin.token, 'POST', '/admin/badges', { name: `Bug hunter ${S}`, description: 'Found and reported a security bug', emoji: '🐛', color: '#22C55E' })
ok('an admin makes a badge', r.status === 201 && r.body.color === '#22c55e', JSON.stringify(r.body)); const bug = r.body; made.push(bug.id)
const up = await (await multi(admin.token, '/images?kind=icon', pngFile)).json()
r = await callS(admin.token, 'POST', '/admin/badges', { name: `Pioneer ${S}`, icon_url: up.url, color: '#f59e0b' })
ok('or with an uploaded picture', r.status === 201 && r.body.icon_url === up.url && r.body.emoji === ''); const pio = r.body; made.push(pio.id)
const cat = await call(a.token, 'GET', '/badges')
ok('the catalog is public', cat.some((x) => x.id === bug.id && x.description === 'Found and reported a security bug'))

console.log('-- giving them')
r = await callS(a.token, 'PUT', `/admin/users/${b.user.id}/badges/${bug.id}`); ok('only admins give badges', r.status === 403)
r = await callS(admin.token, 'PUT', `/admin/users/${a.user.id}/badges/${bug.id}`, { note: 'reported the XSS' }); ok('an admin gives one', r.status === 204)
r = await callS(admin.token, 'PUT', `/admin/users/${a.user.id}/badges/${bug.id}`, {}); ok('giving it again is harmless', r.status === 204)
await callS(admin.token, 'PUT', `/admin/users/${a.user.id}/badges/${pio.id}`, {})
let prof = await call(b.token, 'GET', `/users/${a.user.id}`)
ok('the profile carries both, in catalog order', prof.badges.includes(`custom:${bug.id}`) && prof.badges.indexOf(`custom:${bug.id}`) < prof.badges.indexOf(`custom:${pio.id}`), JSON.stringify(prof.badges))
const holders = await call(admin.token, 'GET', `/admin/badges/${bug.id}/holders`)
ok('admins see who has it, with the note', holders.length === 1 && holders[0].user_id === a.user.id && holders[0].note === 'reported the XSS' && !!holders[0].awarded_by)
ok('the note is not on the public profile', !JSON.stringify(prof).includes('reported the XSS'))
ok('the list counts holders', (await call(admin.token, 'GET', '/admin/badges')).find((x) => x.id === bug.id)?.holders === 1)
const audit = JSON.stringify(await call(admin.token, 'GET', '/admin/audit?limit=20'))
ok('making and giving are audited', audit.includes('badge.create') && audit.includes('badge.award'))

console.log('-- on profiles')
const browser = await chromium.launch(); const errors = []
const p = await browser.newPage({ viewport: { width: 1440, height: 900 } }); p.on('pageerror', (e) => errors.push(e.message))
const g = await call(a.token, 'POST', '/guilds', { name: `Badges ${S}` }); const tc = g.channels.find((x) => x.kind === 'text')
const inv = await call(a.token, 'POST', `/guilds/${g.id}/invites`, {}); await call(b.token, 'POST', `/invites/${inv.code}`)
const msg = await call(a.token, 'POST', `/channels/${tc.id}/messages`, { content: `hi ${S}` })
await p.goto(`${WEB}/login`); await p.evaluate((t) => localStorage.setItem('parley.token', t), b.token)
await p.goto(`${WEB}/channels/${g.id}/${tc.id}`); await p.waitForSelector(`[data-msg-id="${msg.id}"]`)
await p.click(`[data-msg-id="${msg.id}"] [data-msg-author]`); await p.waitForSelector(`[role=dialog] [data-badge="custom:${bug.id}"]`)
const pop = p.locator('[role=dialog]')
ok('the popout shows the emoji badge', (await pop.locator(`[data-badge="custom:${bug.id}"]`).textContent()).includes('🐛'))
ok('and the picture badge', await pop.locator(`[data-badge="custom:${pio.id}"] img`).count() === 1)
await pop.locator(`[data-badge="custom:${bug.id}"]`).hover(); await p.waitForSelector('[role=tooltip]')
ok('its tooltip says what it is for', (await p.locator('[role=tooltip]').textContent()).includes(`Bug hunter ${S}: Found and reported a security bug`))
await p.screenshot({ path: 'custombadges-popout.png' })
// An admin renames it: open sessions get the new catalog at once.
await callS(admin.token, 'PATCH', `/admin/badges/${bug.id}`, { name: `Bug slayer ${S}` })
await p.mouse.move(0, 0); await p.waitForTimeout(300); await pop.locator(`[data-badge="custom:${bug.id}"]`).hover()
await p.waitForFunction((n) => document.querySelector('[role=tooltip]')?.textContent?.includes(n), `Bug slayer ${S}`, { timeout: 5000 }).catch(() => {})
ok('a change reaches open sessions', (await p.locator('[role=tooltip]').textContent()).includes(`Bug slayer ${S}`))
await p.keyboard.press('Escape')

console.log('-- the console')
const pa = await browser.newPage({ viewport: { width: 1440, height: 900 } }); pa.on('pageerror', (e) => errors.push(e.message))
await pa.goto(`${WEB}/login`); await pa.evaluate((t) => localStorage.setItem('parley.token', t), admin.token)
await pa.goto(`${WEB}/admin/badges`); await pa.waitForSelector(`[data-badge-row="Bug slayer ${S}"]`)
await pa.click('[data-badge-new]')
await pa.fill('[data-badge-name]', `Helper ${S}`); await pa.fill('[data-badge-description]', 'Answers questions for newcomers'); await pa.fill('[data-badge-emoji]', '🤝')
await pa.click('[data-badge-save]'); await pa.waitForSelector(`[data-badge-row="Helper ${S}"]`)
const helper = (await call(admin.token, 'GET', '/admin/badges')).find((x) => x.name === `Helper ${S}`); if (helper) made.push(helper.id)
ok('the page makes a badge', helper?.emoji === '🤝' && helper.description === 'Answers questions for newcomers')
await pa.click(`[data-badge-holders="Helper ${S}"]`)
await pa.fill('[data-badge-give-search]', `badgepal${S}`)
await pa.click(`[data-badge-give="badgepal${S}"]`)
await pa.waitForSelector(`[data-badge-holder="badgepal${S}"]`)
ok('and gives it to someone', (await call(a.token, 'GET', `/users/${b.user.id}`)).badges.includes(`custom:${helper?.id}`))
await pa.screenshot({ path: 'custombadges-admin.png' })
await pa.goto(`${WEB}/admin/users/${a.user.id}`); await pa.waitForSelector('[data-admin-card="badges"]')
ok('an account page lists its badges', await pa.locator(`[data-user-badge="Bug slayer ${S}"]`).count() === 1)
await pa.click(`[data-user-badge-take="Bug slayer ${S}"]`); await pa.waitForSelector(`[data-user-badge="Bug slayer ${S}"]`, { state: 'detached' })
ok('and takes one back', !(await call(b.token, 'GET', `/users/${a.user.id}`)).badges.includes(`custom:${bug.id}`))
await pa.selectOption('[data-user-badge-pick]', helper.id); await pa.click('[data-user-badge-give]')
await pa.waitForSelector(`[data-user-badge="Helper ${S}"]`)
ok('or gives another', (await call(b.token, 'GET', `/users/${a.user.id}`)).badges.includes(`custom:${helper.id}`))

console.log('-- deleting')
r = await callS(admin.token, 'DELETE', `/admin/badges/${pio.id}`); ok('deleting a badge', r.status === 204)
prof = await call(b.token, 'GET', `/users/${a.user.id}`)
ok('takes it off everyone', !prof.badges.includes(`custom:${pio.id}`) && !(await call(a.token, 'GET', '/badges')).some((x) => x.id === pio.id))

await browser.close()
await cleanup()
ok('no page errors', errors.length === 0, errors.join(' | '))
await finish()
