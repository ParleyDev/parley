import { chromium } from 'playwright'
import { WEB, S, reg, call, callS, raw, ok, finish, adminToken } from '../lib.mjs'

const admin = await adminToken()
const a = await reg('alice'); const b = await reg('bob')
const me = await call(admin.token, 'GET', '/users/@me')

console.log('-- API')
let r = await raw(a.token, 'GET', '/admin/audit'); ok('non-admins cannot read the audit log', r.status === 403)
const g = await call(b.token, 'POST', '/guilds', { name: `Bobs Bar ${S}` })
await call(b.token, 'PUT', `/guilds/${g.id}/discovery`, { description: 'a lovely place for testing things', category: 'gaming' })
await callS(admin.token, 'PATCH', `/admin/users/${a.user.id}`, { is_admin: true })
await callS(admin.token, 'PATCH', `/admin/users/${a.user.id}`, { is_admin: false, suspended: true })
await callS(admin.token, 'PATCH', `/admin/users/${a.user.id}`, { suspended: false })
await callS(admin.token, 'DELETE', `/admin/users/${a.user.id}/sessions`)
await callS(admin.token, 'POST', `/admin/discovery/${g.id}/review`, { status: 'rejected', note: 'needs a banner' })
const settings = await call(admin.token, 'GET', '/admin/settings')
await callS(admin.token, 'PUT', '/admin/settings', { ...settings, announcement: `audit ${S}` })
await callS(admin.token, 'PUT', '/admin/settings', { ...settings, announcement: settings.announcement })
await callS(admin.token, 'DELETE', `/admin/guilds/${g.id}`)
await callS(admin.token, 'DELETE', `/admin/users/${b.user.id}`)
const log = await call(admin.token, 'GET', `/admin/audit?q=${S}`)
const mine = (await call(admin.token, 'GET', `/admin/audit`)).filter((e) => e.actor_id === me.id)
const find = (action, target) => mine.find((e) => e.action === action && (!target || e.target_name === target))
ok('promote, demote, suspend and unsuspend are logged against @alice', ['user.promote', 'user.demote', 'user.suspend', 'user.unsuspend'].every((x) => find(x, `alice${S}`)))
ok('logging a user out everywhere is logged', !!find('user.logout_all', `alice${S}`))
const rej = find('discovery.rejected', `Bobs Bar ${S}`); ok('discovery decisions carry the note', rej?.details?.note === 'needs a banner' && rej.target_kind === 'guild' && rej.target_id === g.id)
const su = mine.filter((e) => e.action === 'settings.update'); ok('settings changes record just the changed keys, twice', su.length >= 2 && su[0].details.announcement === settings.announcement && su[1].details.announcement === `audit ${S}` && !('registration_enabled' in su[0].details))
ok('server and account deletions keep the names after the rows are gone', find('guild.delete', `Bobs Bar ${S}`)?.target_id === g.id && find('user.delete', `bob${S}`)?.target_id === b.user.id)
ok('entries name the actor and are newest first', mine.every((e) => e.actor_name === me.username) && mine[0].action === 'user.delete')
ok('the q filter matches target names', log.length >= 6 && log.every((e) => e.target_name.includes(String(S)) || e.action.includes(String(S))))
ok('q matches actions too', (await call(admin.token, 'GET', '/admin/audit?q=discovery.rej')).every((e) => e.action === 'discovery.rejected'))
const page1 = await call(admin.token, 'GET', '/admin/audit'); const page2 = await call(admin.token, 'GET', `/admin/audit?before=${page1[1].id}`)
ok('before= pages by id', page2[0]?.id === page1[2]?.id)

console.log('-- UI')
const browser = await chromium.launch(); const errors = []
const p = await browser.newPage({ viewport: { width: 1440, height: 900 } }); p.on('pageerror', (e) => errors.push(e.message))
await p.goto(`${WEB}/login`); await p.evaluate((t) => localStorage.setItem('parley.token', t), admin.token)
await p.goto(`${WEB}/admin`); await p.waitForSelector('[data-admin-nav="audit"]'); await p.click('[data-admin-nav="audit"]'); await p.waitForSelector('[data-admin-audit-row]')
ok('Audit Log page lists entries', await p.locator('[data-admin-audit-row]').count() >= 6)
const first = p.locator('[data-admin-audit-row]').first()
ok('the newest entry reads "@admin deleted account @bob"', (await first.textContent()).includes(`@${me.username}`) && (await first.textContent()).includes('deleted account') && (await first.textContent()).includes(`@bob${S}`))
await p.fill('[data-admin-audit-search]', 'discovery.rejected'); await p.waitForFunction(() => { const rows = document.querySelectorAll('[data-admin-audit-row]'); return rows.length > 0 && [...rows].every((r) => r.getAttribute('data-audit-action') === 'discovery.rejected') })
ok('filtering narrows the list and shows the note', (await p.locator('[data-admin-audit-row]').first().locator('[data-audit-detail]').textContent()).includes('needs a banner'))
await p.screenshot({ path: '96-audit-log.png' })
ok('no page errors', errors.length === 0, errors.join(' | '))
await browser.close(); await finish()
